#!/usr/bin/env python3
"""Native makefsdata oracle with bounded output and checksum assertions."""
import importlib.util
import json
from pathlib import Path
import re
import resource
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]

def helper(name):
    spec = importlib.util.spec_from_file_location(name, ROOT / 'scripts' / (name + '.py'))
    module = importlib.util.module_from_spec(spec); spec.loader.exec_module(module)
    return module

def limits():
    resource.setrlimit(resource.RLIMIT_FSIZE, (8*1024*1024,8*1024*1024))

def run():
    source = ROOT / 'ref' / json.loads((ROOT/'config/sources.json').read_text())['directory']
    work = ROOT / 'build/native-tools-qualified'; output=ROOT/'artifacts/native-tools'
    work.mkdir(parents=True,exist_ok=True);output.mkdir(parents=True,exist_ok=True)
    staged = work/'source'
    repairs = helper('stage').makefsdata(ROOT,source,staged)
    helper('profiles').write_header(ROOT,source,'makefsdata',work/'include')
    command=['gcc','-std=c17','-D_DEFAULT_SOURCE','-I',str(work/'include'),'-I',str(ROOT/'src/port'),'-I',str(staged/'src/include'),str(staged/'src/apps/http/makefsdata/makefsdata.c'),'-o',str(work/'makefsdata')]
    build=subprocess.run(command,text=True,capture_output=True,timeout=30)
    (output/'build.log').write_text(build.stdout+build.stderr)
    build.check_returncode()
    content=work/'content';content.mkdir(exist_ok=True)
    cases={'empty.txt':b'', 'odd.txt':b'abcde', 'multiple.txt':bytes(i%251 for i in range(4097))}
    for name,data in cases.items():(content/name).write_bytes(data)
    # Reproduce the pinned upstream failure with a strict file-size cap.
    original_command=[str(source/'src/apps/http/makefsdata/makefsdata.c') if part==str(staged/'src/apps/http/makefsdata/makefsdata.c') else str(work/'makefsdata-upstream') if part==str(work/'makefsdata') else part for part in command]
    original_build=subprocess.run(original_command,text=True,capture_output=True,timeout=30)
    original_build.check_returncode()
    before=work/'before';before.mkdir(exist_ok=True)
    before_command=[str(work/'makefsdata-upstream'),str(content),'-f:before.c','-11','-c']
    original=subprocess.run(before_command,cwd=before,text=True,capture_output=True,timeout=10,preexec_fn=limits)
    assert original.returncode != 0, 'Expected pinned upstream checksum loop to hit bounded output limit'
    before_evidence={'command':before_command,'exit_code':original.returncode,'output_limit_bytes':8*1024*1024,
                     'temporary_sizes':{p.name:p.stat().st_size for p in before.glob('*.tmp')}}
    (output/'before.json').write_text(json.dumps(before_evidence,indent=2)+'\n')
    for temporary in before.glob('*.tmp'):temporary.unlink()
    command=[str(work/'makefsdata'),'content','-f:fsdata.c','-11','-c']
    result=subprocess.run(command,cwd=work,text=True,capture_output=True,timeout=10,preexec_fn=limits)
    (output/'run.log').write_text(result.stdout+result.stderr);result.check_returncode()
    generated=(work/'fsdata.c').read_text()
    (output/'fsdata.c').write_text(generated)
    counts={}
    for name,data in cases.items():
        var='_' + name.replace('.','_')
        match=re.search(r'chksums_'+re.escape(var)+r'\[\] = \{(.*?)\};',generated,re.S)
        if not match:raise AssertionError('Missing checksum table '+var)
        records=[tuple(int(n,0) for n in row) for row in re.findall(r'\{(\d+), (0x[0-9a-f]+), (\d+)\}',match.group(1))]
        if not records or records[0][0]!=0:raise AssertionError('Missing HTTP header checksum '+name)
        offset=records[0][2]; consumed=0
        array=re.search(r'data_'+re.escape(var)+r'\[\].*?= \{(.*?)\};',generated,re.S)
        assert array, 'Missing generated byte image '+name
        image=bytes(int(value,16) for value in re.findall(r'0x([0-9a-f]{2})\b',array.group(1)))
        payload_start=((len(name)+2+3)//4)*4
        header=image[payload_start:payload_start+offset]
        assert header.startswith(b'HTTP/1.1 ') and header.endswith(b'\r\n\r\n')
        padded=header+(b'\0' if len(header)%2 else b'')
        total=sum(int.from_bytes(padded[i:i+2],'little') for i in range(0,len(padded),2))
        while total>65535:total=(total&65535)+(total>>16)
        assert records[0][1]==total,(name,records[0][1],total)
        assert image[payload_start+offset:]==data, 'Generated body mismatch '+name
        for position,checksum,length in records[1:]:
            assert position==offset+consumed,(name,position,offset,consumed)
            chunk=data[consumed:consumed+length]; assert len(chunk)==length
            # inet_chksum exposes the network checksum in a host u16; on the
            # declared little-endian ABI the stored sum uses little-endian words.
            words=chunk + (b'\0' if len(chunk)%2 else b'')
            total=sum(int.from_bytes(words[i:i+2],'little') for i in range(0,len(words),2))
            while total>65535:total=(total&65535)+(total>>16)
            assert checksum==total,(name,checksum,total)
            consumed+=length
        assert consumed==len(data),(name,consumed,len(data))
        counts[name]={'bytes':len(data),'checksum_chunks':len(records)-1}
    report={'status':'passed','upstream_failure':before_evidence,'cases':counts,'adaptations':repairs,'limits':{'timeout_seconds':10,'output_bytes_per_file':8*1024*1024},'command':command,'source':str(source)}
    (output/'report.json').write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps(report,indent=2))

if __name__=='__main__':run()
