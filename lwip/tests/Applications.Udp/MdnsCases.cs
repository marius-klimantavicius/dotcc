using System.Buffers.Binary;
using System.Collections.Concurrent;
using System.Text;
using Managed.Networking;
using static Managed.Networking.Lwip;
using static UdpPeer;

internal static unsafe class MdnsCases
{
    private sealed class State { internal bool Ready; internal int TxtCalls; internal Exception? Error; }
    private static readonly ConcurrentDictionary<Lwip, State> States = new();
    private static void Probed(Lwip owner, netif* iface, byte result, sbyte slot)
    {
        var state = States[owner];
        if (result == 1) state.Ready = true;
        else state.Error = new InvalidOperationException("Unexpected conflict for isolated mDNS fixture name");
    }
    private static void Text(Lwip owner, mdns_service* service, void* unused)
    {
        var state = States[owner];
        try
        {
            fixed (byte* bytes = "path=/fixture"u8)
                Require(owner.mdns_resp_add_service_txtitem(service, bytes, 13) == 0, "mDNS TXT callback");
            state.TxtCalls++;
        }
        catch (Exception failure) { state.Error = failure; }
    }

    // Decode only the responder's outputs; bounds protect fixture diagnostics.
    // No malformed input or mutation scenario is generated by this reader.
    private static string Name(byte[] message, ref int offset)
    {
        var labels = new List<string>(); int cursor = offset, end = -1, hops = 0;
        while (true)
        {
            Require(cursor < message.Length && hops++ < 128, "mDNS output name bounds");
            int length = message[cursor++];
            if ((length & 0xc0) == 0xc0)
            {
                Require(cursor < message.Length, "mDNS output pointer bounds");
                int target = ((length & 0x3f) << 8) | message[cursor++];
                if (end < 0) end = cursor;
                cursor = target; continue;
            }
            Require(length <= 63 && cursor + length <= message.Length, "mDNS output label bounds");
            if (length == 0) { offset = end < 0 ? cursor : end; return string.Join('.', labels); }
            labels.Add(Encoding.ASCII.GetString(message, cursor, length)); cursor += length;
        }
    }
    private static ushort Word(byte[] bytes, int offset)
    { Require(offset + 2 <= bytes.Length, "mDNS output word bounds"); return BinaryPrimitives.ReadUInt16BigEndian(bytes.AsSpan(offset)); }

    internal static void Run(VirtualPair pair)
    {
        var state = new State(); States[pair.B.Core] = state;
        using var peer = new UdpPeer(pair.A, 31535);
        nint iface = 0; sbyte slot = -1; bool attached = false;
        try
        {
            pair.B.Invoke(owner =>
            {
                iface = owner.Globals.netif_default;
                owner.mdns_resp_init(); owner.mdns_resp_register_name_result_cb(&Probed);
                fixed (byte* hostname = Encoding.ASCII.GetBytes("dotcc-udp-fixture\0"), instance = Encoding.ASCII.GetBytes("Fixture\0"), service = Encoding.ASCII.GetBytes("_dotcc\0"))
                {
                    Require(owner.mdns_resp_add_netif((netif*)iface, hostname) == 0, "mDNS attach interface"); attached = true;
                    slot = owner.mdns_resp_add_service((netif*)iface, instance, service, mdns_sd_proto.DNSSD_PROTO_UDP, 4242, &Text, null);
                    Require(slot >= 0, "mDNS service registration");
                }
            });
            Wait(pair, () => { bool ready = false; pair.B.Invoke(_ => { if (state.Error != null) throw state.Error; ready = state.Ready; }); return ready; });
            byte[] question = new byte[12]; BinaryPrimitives.WriteUInt16BigEndian(question, 0x4d44); question[5] = 1;
            using var query = new MemoryStream(); query.Write(question);
            foreach (string label in new[] { "_dotcc", "_udp", "local" }) { byte[] text = Encoding.ASCII.GetBytes(label); query.WriteByte((byte)text.Length); query.Write(text); }
            query.Write(new byte[] { 0, 0, 12, 0, 1 }); // PTR, IN; legacy unicast query.
            peer.Send("10.0.0.2", 5353, query.ToArray());
            var reply = peer.Next(pair); byte[] bytes = reply.Bytes;
            Require(reply.Port == 5353 && Word(bytes, 0) == 0x4d44 && (Word(bytes, 2) & 0x800f) == 0x8000, "mDNS response header");
            int offset = 12;
            for (int i = 0; i < Word(bytes, 4); i++) { Name(bytes, ref offset); offset += 4; }
            bool ptr = false, srv = false, txt = false;
            int records = Word(bytes, 6) + Word(bytes, 8) + Word(bytes, 10);
            for (int i = 0; i < records; i++)
            {
                string name = Name(bytes, ref offset); ushort type = Word(bytes, offset), length = Word(bytes, offset + 8); offset += 10;
                Require(offset + length <= bytes.Length, "mDNS output resource bounds");
                int data = offset;
                if (type == 12 && name == "_dotcc._udp.local") ptr |= Name(bytes, ref data) == "Fixture._dotcc._udp.local";
                if (type == 33 && name == "Fixture._dotcc._udp.local")
                { Require(length >= 7 && Word(bytes, data + 4) == 4242, "mDNS SRV port"); data += 6; srv |= Name(bytes, ref data) == "dotcc-udp-fixture.local"; }
                if (type == 16 && name == "Fixture._dotcc._udp.local") txt |= bytes.AsSpan(data, length).SequenceEqual(new byte[] { 13 }.Concat("path=/fixture"u8.ToArray()).ToArray());
                offset += length;
            }
            Require(ptr && srv && txt, "mDNS original PTR/SRV/TXT service response");
            pair.B.Invoke(owner =>
            {
                if (state.Error != null) throw state.Error;
                Require(state.TxtCalls > 0, "mDNS TXT callback executed");
                Require(owner.mdns_resp_del_service((netif*)iface, (byte)slot) == 0, "mDNS service removal"); slot = -1;
                Require(owner.mdns_resp_remove_netif((netif*)iface) == 0, "mDNS interface removal"); attached = false;
                Require(owner.mdns_resp_netif_active((netif*)iface) == 0, "mDNS interface inactive after removal");
            });
        }
        finally
        {
            pair.B.Invoke(owner =>
            {
                if (slot >= 0) owner.mdns_resp_del_service((netif*)iface, (byte)slot);
                if (attached) owner.mdns_resp_remove_netif((netif*)iface);
                owner.mdns_resp_register_name_result_cb(null);
            });
            pair.Drain(); States.TryRemove(pair.B.Core, out _);
        }
    }
}
