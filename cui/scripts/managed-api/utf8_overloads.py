"""Derive UTF-8 input overloads from reviewed Ui methods, preserving their bodies.

This only substitutes text argument marshalling. Native calls, validation, scope
tracking, state synchronization and pointer retention are copied unchanged.
"""
import itertools
import re
from pathlib import Path

INPUTS = ('Ui.Api.cs', 'Ui.Overloads.cs', 'Ui.cs', 'Resources.cs', 'Callbacks.cs')
TEXT_TYPES = {
    'string': ('string', 'ReadOnlySpan<byte>', 'TextBuffer'),
    'ReadOnlySpan<string>': ('ReadOnlySpan<string>', 'ReadOnlySpan<ReadOnlyMemory<byte>>', 'ReadOnlySpan<TextBuffer>'),
}


def parameters(text):
    parts, start, depth = [], 0, 0
    for i, c in enumerate(text):
        if c in '<([': depth += 1
        elif c in '>)]': depth -= 1
        elif c == ',' and depth == 0:
            parts.append(text[start:i].strip()); start = i + 1
    if text[start:].strip(): parts.append(text[start:].strip())
    result = []
    for part in parts:
        declaration, sep, default = part.partition(' = ')
        kind, name = declaration.rsplit(' ', 1)
        result.append((kind, name, sep + default))
    return result


def methods(source):
    # Only Ui; other classes in these files have independent ownership rules.
    source = source.split('public sealed unsafe partial class Ui', 1)[1]
    pattern = r'^    public ([\w?<>]+) (\w+)\(([^\n]*)\)\s*(=>|\{)'
    tokens = r'/\*[\s\S]*?\*/|//[^\n]*|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|[{}]'
    for match in re.finditer(pattern, source, re.M):
        result, name, args, opening = match.groups()
        params = parameters(args)
        if not any(p[0] in TEXT_TYPES for p in params): continue
        if opening == '=>':
            end = source.index(';', match.end()) + 1
        else:
            depth = 1
            for token in re.finditer(tokens, source[match.end():]):
                if token[0] == '{': depth += 1
                elif token[0] == '}': depth -= 1
                if depth == 0:
                    end = match.end() + token.end(); break
            else: raise ValueError(f'Unclosed method: {name}')
        body = opening + source[match.end():end]
        yield result, name, params, body


def generate(wrapper: Path, reviewed=None):
    entries = []
    for name in INPUTS:
        data = reviewed[name].decode() if reviewed and name in reviewed else (wrapper / name).read_text()
        entries.extend(methods(data))
    names = {entry[1] for entry in entries}
    output = ['// <auto-generated/>', '#nullable enable', '// Reproduce with scripts/managed-api/generate.py; edit the reviewed source methods.',
              'using System.Runtime.InteropServices;',
              'using Raw = global::Managed.Forms.Cui;', 'using static global::Managed.Forms.Cui;',
              'using CBool = global::Managed.Forms.Cui.CBool;', 'namespace Cui.Managed;',
              'public sealed unsafe partial class Ui', '{']
    for result, name, params, body in entries:
        kinds = [TEXT_TYPES.get(kind, (kind,)) for kind, _, _ in params]
        for combination in itertools.product(*kinds):
            if combination == tuple(p[0] for p in params): continue
            signature = ', '.join(kind + ' ' + p[1] + p[2] for kind, p in zip(combination, params))
            args = []
            for original, arg, _ in params:
                if original in TEXT_TYPES:
                    args.append(f'new {"Utf8Argument" if original == "string" else "Utf8Arguments"}({arg})')
                else:
                    modifier = original.split(' ')[0]
                    args.append((modifier + ' ' if modifier in ('ref', 'out', 'in') else '') + arg)
            output.append(f'    public {result} {name}({signature}) => {name}Utf8Core({", ".join(args)});')
        signature = ', '.join(('Utf8Argument' if kind == 'string' else 'Utf8Arguments' if kind in TEXT_TYPES else kind) + ' ' + arg + default
                              for kind, arg, default in params)
        for kind, arg, _ in params:
            if kind == 'string':
                body = body.replace(f'ArgumentNullException.ThrowIfNull({arg})', f'{arg}.ThrowIfNull(nameof({arg}))')
        # Convenience methods forward to the same reviewed overloads with the
        # internal text carrier, not through a UTF-16 round trip.
        body = re.sub(r'(?<![.\w])(' + '|'.join(sorted(names, key=len, reverse=True)) + r')\(', r'\1Utf8Core(', body)
        output.append(f'    private {result} {name}Utf8Core({signature})\n    {body}')
    output.append('}')
    return ('\n'.join(output) + '\n').encode()
