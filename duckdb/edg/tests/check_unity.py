#!/usr/bin/env python3
"""Focused unity recipe checks with retained synthetic inputs and real EDG preprocessing.

No whole-program merge or DuckDB execution is performed. All fixtures and logs
remain below --output-dir, including rejected inputs.
"""
import argparse
import copy
import json
import os
from pathlib import Path
import shutil
import sys
import unittest

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import unity
from portable import inventory

OUTPUT = None
COMPILER = None


class UnityTests(unittest.TestCase):
    def setUp(self):
        self.root = OUTPUT / self._testMethodName
        self.root.mkdir()
        self.source = self.root / 'acquired/source'
        self.stage = self.root / 'portable/source'
        self.build = self.root / 'native'
        for path in (self.source, self.stage, self.build):
            path.mkdir(parents=True)
        self.units = []
        for index in range(6):
            name = 'source%d.cpp' % index
            (self.source / name).write_text('int function%d() { return %d; }\n' % (index, index))
            shutil.copy2(self.source / name, self.stage / name)
            self.units.append(dict(file=str(self.stage / name), directory=str(self.stage),
                role='library', target='library', language='c++', arguments=['c++', '-DMODE=1',
                '-I' + str(self.stage / 'first'), '-I' + str(self.stage / 'second'), '-std=c++17', '-c', str(self.stage / name)]))
        acquired = self.source.parent / 'source-manifest.json'
        acquired.write_text(json.dumps(dict(files=inventory(self.source), symlinks=[])))
        self.portable = dict(source=str(self.source), stagedSource=str(self.stage),
            sourceManifestSha256=unity.sha(acquired), units=self.units, staticExtensions=['example'],
            stagedInputs=[dict(item, path='source/' + item['path']) for item in inventory(self.stage)])
        self.portable_path = self.root / 'portable.json'
        self.portable_path.write_text(json.dumps(self.portable))
        self.native_unit = dict(self.units[2], file=str(self.build / 'ub_group.cpp'), directory=str(self.build),
            arguments=[value.replace(str(self.stage), str(self.source)) for value in self.units[2]['arguments']])
        self.wrapper = Path(self.native_unit['file'])
        self.write_members([2, 4])
        self.native = dict(source=str(self.source), build=str(self.build), staticExtensions=['example'], units=[self.native_unit])
        self.native_path = self.root / 'native.json'
        self.native_path.write_text(json.dumps(self.native))
        self.remaining = []
        for index in (2, 3, 4, 5):
            ii = self.root / ('original%d.ii' % index)
            ii.write_text((self.stage / ('source%d.cpp' % index)).read_text())
            self.remaining.append(dict(sourceIndex=index, source=self.units[index]['file'], **unity.record(ii)))
        core = self.root / 'core.ii'
        core.write_text('int core() { return 0; }\n')
        self.base = dict(status='preprocessed-composition', frozenInputsUnchanged=True,
            programInputs=[dict(kind='core-and-libcxx', coveredSourceIndices=[0, 1], **unity.record(core)),
                           *[dict(item, kind='retained-configured-tu') for item in self.remaining]],
            remainingInputs=self.remaining,
            currentPreprocessingContract=dict(selected=[dict(index=index, source=unit['file'],
                sourceSha256=unity.sha(unit['file'])) for index, unit in enumerate(self.units)]))

    def write_members(self, indices):
        self.wrapper.write_text('// Unity Build generated by CMake\n' + ''.join(
            '#include ' + json.dumps(str(self.source / ('source%d.cpp' % index))) + '\n' for index in indices))

    def select(self):
        return unity.select_groups(self.native, self.portable, {item['source'] for item in self.remaining})

    def test_order_flags_and_complete_partition(self):
        unity.validate_base(self.base, self.portable)
        result = self.select()
        self.assertEqual(result['groups'][0]['orderedMembers'], [self.units[i]['file'] for i in (2, 4)])
        group = dict(result['groups'][0], coveredSourceIndices=[2, 4])
        output = dict(path='selected.ii', sha256='fixture')
        inputs = unity.compose_inputs(self.base['programInputs'], [group], [output], len(self.units))
        self.assertEqual(inputs[0], self.base['programInputs'][0])
        self.assertEqual([item['path'] for item in inputs[1:]], ['selected.ii', self.remaining[1]['path'], self.remaining[3]['path']])
        self.assertEqual(group['frontendFlags'], unity.frontend_flags(self.units[2])[0])

    def test_mixed_group_keeps_all_remaining_members_separate(self):
        self.write_members([0, 2])
        result = self.select()
        self.assertEqual(result['groups'], [])
        self.assertEqual(len(result['excludedMixedGroups']), 1)
        self.assertEqual(len(result['ungroupedRemainingTUs']), 4)
        self.assertEqual(unity.compose_inputs(self.base['programInputs'], [], [], 6), self.base['programInputs'])

    def test_duplicate_member_rejected(self):
        self.write_members([2, 2])
        with self.assertRaisesRegex(ValueError, 'duplicate'):
            self.select()

    def test_duplicate_groups_rejected(self):
        self.native['units'].append(dict(self.native_unit))
        with self.assertRaisesRegex(ValueError, 'Duplicate source'):
            self.select()

    def test_unknown_source_rejected(self):
        self.write_members([2, 7])
        with self.assertRaisesRegex(ValueError, 'unconfigured'):
            self.select()

    def test_extra_wrapper_semantics_rejected(self):
        with self.wrapper.open('a') as stream:
            stream.write('#define INJECTED 1\n')
        with self.assertRaisesRegex(ValueError, 'syntax'):
            self.select()

    def test_define_target_and_include_order_mismatch_rejected(self):
        original = copy.deepcopy(self.native_unit)
        for mutation in ('define', 'target', 'includes'):
            self.native_unit.clear()
            self.native_unit.update(copy.deepcopy(original))
            if mutation == 'define':
                self.native_unit['arguments'][1] = '-DMODE=2'
            elif mutation == 'target':
                self.native_unit['target'] = 'other'
            else:
                self.native_unit['arguments'][2:4] = reversed(self.native_unit['arguments'][2:4])
            with self.subTest(mutation=mutation), self.assertRaises(ValueError):
                self.select()

    def test_partial_or_duplicate_selection_rejected(self):
        group = dict(target='library', orderedMembers=[self.units[0]['file'], self.units[2]['file']], coveredSourceIndices=[0, 2])
        with self.assertRaisesRegex(ValueError, 'overlaps core'):
            unity.compose_inputs(self.base['programInputs'], [group], [dict(path='x')], 6)
        group.update(orderedMembers=[self.units[2]['file'], self.units[4]['file']], coveredSourceIndices=[2, 4])
        with self.assertRaisesRegex(ValueError, 'Repeated'):
            unity.compose_inputs(self.base['programInputs'], [group, group], [dict(path='x'), dict(path='y')], 6)

    def test_missing_duplicate_and_false_coverage_rejected(self):
        cases = [self.base['programInputs'][:-1], [*self.base['programInputs'], self.base['programInputs'][1]]]
        for inputs in cases:
            with self.assertRaisesRegex(ValueError, 'coverage'):
                unity.coverage(inputs, 6)
        changed = copy.deepcopy(self.base)
        changed['remainingInputs'][0]['sourceIndex'] = 3
        with self.assertRaisesRegex(ValueError, 'index mismatch'):
            unity.validate_base(changed, self.portable)

    def test_source_mapping_and_changed_original_rejected(self):
        unity.verify_source_mapping(self.portable, self.native)
        changed = dict(self.native, source=str(self.stage))
        with self.assertRaisesRegex(ValueError, 'source root'):
            unity.verify_source_mapping(self.portable, changed)
        (self.source / 'source0.cpp').write_text('changed')
        with self.assertRaisesRegex(ValueError, 'inventory'):
            unity.verify_source_mapping(self.portable, self.native)

    def test_codegen_mapping_requires_identical_generated_inputs(self):
        codegen = self.build / 'codegen'
        codegen.mkdir()
        (codegen / 'loader.cpp').write_text('native generated loader')
        with self.assertRaisesRegex(ValueError, 'codegen'):
            unity.verify_source_mapping(self.portable, self.native)
        shutil.copytree(codegen, self.stage.parent / 'codegen')
        unity.verify_source_mapping(self.portable, self.native)

    def test_source_and_retained_artifact_tampering_rejected(self):
        (self.stage / 'source2.cpp').write_text('changed')
        with self.assertRaisesRegex(ValueError, 'checksum'):
            unity.validate_base(self.base, self.portable)
        Path(self.remaining[0]['path']).write_text('tampered retained input')
        with self.assertRaisesRegex(ValueError, 'dependency changed'):
            unity.verify_dependencies(self.remaining)

    def test_changed_header_environment_and_clock_rejected(self):
        previous = dict(standard='c++17', environmentValueHashes={}, preprocessingClock={'epochSeconds': 0},
                        headerInventory=[dict(path='api.h', sha256='old', kind='file')])
        for key, value in [('standard', 'c++20'), ('environmentValueHashes', {'LANG': 'different'}),
                           ('preprocessingClock', {'epochSeconds': 1}),
                           ('headerInventory', [dict(path='api.h', sha256='new', kind='file')]),
                           ('headerInventory', [*previous['headerInventory'], dict(path='new.h', sha256='new')])]:
            with self.subTest(key=key), self.assertRaises(ValueError):
                unity.verify_contract(previous, dict(previous, **{key: value}))

    def test_real_preprocess_and_inventory_receipts(self):
        # The fixture compiler is real EDG; no simulated successful preprocessing.
        compiler = self.root / 'cpfe-dot'
        shutil.copy2(COMPILER, compiler)
        env = dict(os.environ, EDG_BASE=str(unity.EDG / 'upstream/bases/docker/dev-env/gcc'),
                   EDG_DOT_TARGET='portable-lp64-binary80-v2')
        includes = [unity.EDG / ('backend/runtime/' + name + '/include') for name in ('libcxx', 'posix', 'libc')]
        fingerprint, _ = unity.preprocessing_inputs(self.portable, self.portable_path, compiler, 'c++17',
            includes, [], self.units, env, 'library', 0)
        self.base.update(portableManifest=unity.record(self.portable_path), standard='c++17',
            preprocessingClock=unity.preprocessing_clock(0), preprocessingCompiler=unity.record(compiler),
            currentPreprocessingContract=fingerprint, provider=dict(includeDirectories=[], preincludeHeaders=[]))
        base_path = self.root / 'base.json'
        base_path.write_text(json.dumps(self.base))
        planned = unity.prepare(base_path, self.native_path, self.root / 'inventory')
        self.assertEqual(planned['status'], 'inventory-only')
        self.assertEqual(planned['programInputs'], [])
        self.assertEqual(planned['plannedProgramInputCount'], 4)
        result = unity.prepare(base_path, self.native_path, self.root / 'preprocessed', preprocess=True)
        self.assertEqual(result['status'], 'preprocessed-composition')
        self.assertTrue(result['frozenInputsUnchanged'])
        self.assertFalse(result['executionVerified'])
        self.assertEqual(result['programInputCount'], 4)
        generated = Path(result['preprocessing'][0]['output']['path']).read_text()
        self.assertLess(generated.index('function2'), generated.index('function4'))
        self.assertNotIn('function3', generated)
        unity.verify_dependencies(result['verifiedInputs'])
        Path(self.remaining[0]['path']).write_text('tampered')
        with self.assertRaises(ValueError):
            unity.prepare(base_path, self.native_path, self.root / 'rejected')
        self.assertEqual(json.loads((self.root / 'rejected/composition.json').read_text())['status'], 'failed')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-dir', type=Path, required=True)
    parser.add_argument('--compiler', type=Path, default=unity.EDG / 'build/bin/cpfe-dot')
    args = parser.parse_args()
    OUTPUT = args.output_dir.resolve()
    OUTPUT.mkdir(parents=True, exist_ok=False)
    COMPILER = args.compiler.resolve()
    result = unittest.TextTestRunner(verbosity=2).run(unittest.defaultTestLoader.loadTestsFromTestCase(UnityTests))
    receipt = dict(status='passed' if result.wasSuccessful() else 'failed', testsRun=result.testsRun,
                   errors=len(result.errors), failures=len(result.failures), compiler=unity.record(COMPILER),
                   recipe=unity.record(unity.__file__), testHarness=unity.record(__file__),
                   scope='Synthetic recipe validation and real tiny EDG preprocessing; no DuckDB translation or execution claim')
    (OUTPUT / 'results.json').write_text(json.dumps(receipt, indent=2) + '\n')
    sys.exit(not result.wasSuccessful())
