    source_locations = []
    for filename, text in files.items():
        if not (filename.startswith("Translated") or filename == "Managed.Runtime.generated.cs") or not filename.endswith(".cs"):
            continue
        for line_number, text_line in enumerate(text.splitlines(), 1):
            marker = re.fullmatch(r"// dot-gen:(?:origin|runtime-origin) (@?\w+)", text_line.strip())
            if marker:
                entry = dict(origins.get(marker[1], {}), managedName=marker[1],
                             generatedFile=filename, generatedLine=line_number + 1)
                if filename == "Managed.Runtime.generated.cs":
                    entry["runtimeOwner"] = "Managed.Runtime"
                elif filename == "Translated.Runtime.generated.cs":
                    entry["runtimeOwner"] = qualified.replace("@", "")
                source_locations.append(entry)
