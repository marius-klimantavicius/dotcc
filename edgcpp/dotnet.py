def generated_source(source):
    """Mark owned C# output and retain an explicit nullable context for Roslyn."""
    if source.startswith(GENERATED_MARKER):
        return source
    context = "" if source.startswith("#nullable ") else "#nullable enable\n"
    return GENERATED_MARKER + context + source


