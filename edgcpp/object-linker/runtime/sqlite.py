#!/usr/bin/env python3
"""Supply SQLite APPDEF hooks from the existing shared BCL mutex provider."""
import argparse
import hashlib
import json
from pathlib import Path
import re

REPO = Path(__file__).resolve().parents[3]
HOOKS = {'edg_sqlite_mutex_methods', 'edg_sqlite_memory_barrier', 'edg_sqlite_database_mmap_supported'}


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def once(text, old, new):
    if text.count(old) != 1:
        raise ValueError('Canonical SQLite adapter anchor changed: ' + old)
    return text.replace(old, new)


def prepare(project):
    report_path = project / 'link-report.json'
    report = json.loads(report_path.read_text())
    owner = 'global::' + report['namespace'] + '.' + report['class']
    records = {record['generatedType']: record for record in report['records']}
    record = records.get(owner + '.sqlite3_mutex_methods')
    if record is None or (record['size'], record['alignment']) != (72, 8):
        raise ValueError('SQLite APPDEF requires the complete portable mutex callback layout')
    source_map = json.loads((project / report['sourceMap']).read_text())
    obj = next(obj for obj in source_map['objects'] if obj['unitId'] == record['unitId'])
    types = {row['id']: row for row in obj['executionTypes']}
    routines = {row['typeId']: row for row in obj['routineTypes']}
    source_records = {row['typeId']: row for row in obj['recordTypes']}

    def signature(identifier):
        node = types[identifier]
        if node['kind'] == 'pointer':
            return 'ptr(' + signature(node['pointeeTypeId']) + ')'
        if node['kind'] == 'record':
            return source_records[identifier]['identityKey']
        if node['kind'] == 'routine':
            routine = routines[identifier]
            parameters = sorted((row for row in obj['routineParameters'] if row['typeId'] == identifier), key=lambda row: row['ordinal'])
            if routine['variadic'] or routine['exceptionPolicy'] != 'unwind':
                raise ValueError('Unexpected SQLite mutex callback policy')
            return signature(routine['returnTypeId']) + '(' + ','.join(signature(row['parameterTypeId']) for row in parameters) + ')'
        return node['kind']

    fields = sorted((row for row in obj['recordFields'] if row['recordTypeId'] == record['typeId']), key=lambda row: row['ordinal'])
    pointer = 'ptr(record:sqlite3_mutex)'
    expected = [('xMutexInit', 'i32()'), ('xMutexEnd', 'i32()'), ('xMutexAlloc', pointer + '(i32)'),
                ('xMutexFree', 'void(' + pointer + ')'), ('xMutexEnter', 'void(' + pointer + ')'),
                ('xMutexTry', 'i32(' + pointer + ')'), ('xMutexLeave', 'void(' + pointer + ')'),
                ('xMutexHeld', 'i32(' + pointer + ')'), ('xMutexNotheld', 'i32(' + pointer + ')')]
    actual = [(row['sourceName'], signature(row['typeId']), row['byteOffset'], row['bitWidth']) for row in fields]
    if actual != [(name, 'ptr(' + kind + ')', index * 8, None) for index, (name, kind) in enumerate(expected)]:
        raise ValueError('SQLite mutex callback ABI differs from the canonical provider')

    # Read these constants from the owned preprocessing metadata, so the adapter
    # still works after the source/header tree has been removed.
    macros_path = project / report['macroMap']
    macros = json.loads(macros_path.read_text())
    definitions = [row for obj in macros['objects'] for row in obj['macroDefinitions']]
    constants = []
    for name in ('SQLITE_OK', 'SQLITE_NOMEM', 'SQLITE_BUSY'):
        values = {row['definitionText'] for row in definitions if row['name'] == name and row['form'] == 'object'}
        if len(values) != 1:
            raise ValueError('Ambiguous/missing owned SQLite macro: ' + name)
        match = re.fullmatch(r'#define ' + name + r' ([0-9]+)', values.pop())
        if match is None:
            raise ValueError('Expected SQLite integer macro: ' + name)
        constants.append('    private const int ' + name + ' = ' + match.group(1) + ';')

    source = REPO / 'sqlite/src/HostVfs.Mutex.cs'
    code = source.read_text()
    code = once(code, 'using static Managed.Database.Sqlite;', 'using static ' + owner + ';')
    code = once(code, 'namespace Managed.Database;', 'namespace Edg.Runtime.Sqlite;')
    code = once(code, 'public static unsafe class HostMutex\n{', 'public static unsafe class HostMutex\n{\n' + '\n'.join(constants))
    files = {'Runtime.Sqlite.HostMutex.cs': '// <auto-generated />\n// Adapted from the single canonical sqlite/src/HostVfs.Mutex.cs.\n' + code}
    bodies, provided = {}, []
    for requirement in report['runtimeRequirements']:
        name = requirement['ExternalKey']
        if name not in HOOKS:
            continue
        if requirement['parameters'] or requirement['variadic']:
            raise ValueError('Unexpected SQLite hook signature: ' + name)
        returns, expression = {
            'edg_sqlite_mutex_methods': (owner + '.sqlite3_mutex_methods*', 'global::Edg.Runtime.Sqlite.HostMutex.GetMutextMethods()'),
            'edg_sqlite_memory_barrier': ('void', 'global::System.Threading.Thread.MemoryBarrier()'),
            'edg_sqlite_database_mmap_supported': ('int', 'global::System.OperatingSystem.IsWindows() ? 0 : 1'),
        }[name]
        if requirement['returnType'] != returns:
            raise ValueError('Unexpected SQLite hook return: ' + name)
        bodies.setdefault(requirement['container'], []).append('    public static partial ' + returns + ' ' + requirement['generatedName'] + '() => ' + expression + ';')
        provided.append({key: requirement[key] for key in ('ExternalKey', 'Signature', 'container', 'generatedName')})
    if {row['ExternalKey'] for row in provided} != HOOKS:
        raise ValueError('Expected all three SQLite Unix APPDEF runtime hooks')
    for index, (container, methods) in enumerate(sorted(bodies.items())):
        namespace, name = container.removeprefix('global::').rsplit('.', 1)
        files['Runtime.Sqlite.Bindings.' + str(index) + '.cs'] = '// <auto-generated />\n#nullable enable\nnamespace ' + namespace + ';\npublic static unsafe partial class ' + name + '\n{\n' + '\n'.join(methods) + '\n}\n'
    receipt_path = project / 'runtime-sqlite.json'
    if receipt_path.exists() or any((project / name).exists() for name in files):
        raise ValueError('SQLite runtime outputs exist; retain this attempt and use a fresh project')
    for name, text in files.items():
        (project / name).write_text(text)
    receipt = dict(schema=1, provider='sqlite-unix-appdef', status='provided',
                   linkReportSha256=sha(report_path), methods=provided,
                   files={name: sha(project / name) for name in files},
                   inputs=[dict(path=str(path), sha256=sha(path)) for path in (source, macros_path, project / report['sourceMap'], Path(__file__))],
                   runtimeMode='static translation; assembly-lifetime mutex identities', executionVerified=False)
    receipt_path.write_text(json.dumps(receipt, indent=2) + '\n')
    return receipt


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--project', type=Path, required=True)
    args = parser.parse_args()
    result = prepare(args.project.resolve())
    print(json.dumps(dict(status=result['status'], methods=len(result['methods']))))
