"""Static-assembly process callbacks using the canonical direct backend bodies.

The adapter shares callback storage and invocation with semantic static-destructor
registration through CppFinalizers. Process termination retains the direct backend body. DSO unloading and independent owners are not part
of this profile; __cxa_finalize deliberately remains an unresolved import.
"""
import re


def expression(method):
    signatures = {
        'atexit': ('int', ['delegate* managed<void>'], '__edg_register_exit((nint){0}, false)'),
        'at_quick_exit': ('int', ['delegate* managed<void>'], '__edg_register_exit((nint){0}, true)'),
        'exit': ('void', ['int'], '__edg_process_exit({0}, false)'),
        'quick_exit': ('void', ['int'], '__edg_process_exit({0}, true)'),
        '_Exit': ('void', ['int'], 'ImmediateExit({0})'),
        '__cxa_atexit': ('int', ['delegate* managed<void*, void>', 'void*', 'void*'],
                         'RegisterDestructor((nint){0}, (nint){1}, false)'),
        '__cxa_thread_atexit': ('int', ['delegate* managed<void*, void>', 'void*', 'void*'],
                                'RegisterDestructor((nint){0}, (nint){1}, true)'),
    }
    signature = signatures.get(method['symbol'])
    if signature is None:
        return None
    result, parameters, invocation = signature
    if method['variadic'] or method['result'] != result or [kind for kind, _ in method['arguments']] != parameters:
        raise ValueError('Process callback ABI does not match EDG lowering: ' + method['symbol'])
    return 'global::Edg.Runtime.DotObjServices.' + invocation.format(*(name for _, name in method['arguments']))


def member(text, name):
    candidates = [part for part in re.findall(r'// dot-gen:member-begin\n(.*?)// dot-gen:member-end', text, re.S)
                  if re.search(r'\b' + re.escape(name) + r'(?:\(| \{)', part.split('\n', 1)[0])]
    # The process-exit method has an attribute before its signature.
    if not candidates:
        candidates = [part for part in re.findall(r'// dot-gen:member-begin\n(.*?)// dot-gen:member-end', text, re.S)
                      if re.search(r'private @MOD@void ' + re.escape(name) + r'\(', part)]
    if len(candidates) != 1:
        raise ValueError('Canonical lifecycle member changed: ' + name)
    return candidates[0]


def sources(backend, groups, threads=False, has_libc=False, owned_static_registry=False):
    lifecycle = (backend / 'dot_gen_lifecycle.h').read_text()
    process = (backend / 'dot_gen_process.h').read_text()

    code = '\n'.join(member(process, name) for name in ('__edg_register_exit', '__edg_process_exit'))
    code = code.replace('@MOD@', 'static ')
    code += '\nprivate static void __edg_drain(global::System.Collections.Generic.List<__edg_finalizer> list) => CppFinalizers.Program.Drain(list' + (', &HandleFinalizerTransfer' if threads else '') + ');\n'
    if threads:
        code += 'private static bool HandleFinalizerTransfer(global::System.Exception error) => error is global::Edg.Runtime.CThreadExitTransfer exit && __edg_thread_services_value.IsValueCreated && __edg_thread_services.AcceptExitResult(exit);\n'
    code = code.replace('/*__EDG_THREAD_EXIT_CATCH__*/',
        'catch(global::Edg.Runtime.CThreadExitTransfer exit) when(__edg_thread_services_value.IsValueCreated && __edg_thread_services.AcceptExitResult(exit)) {}' if threads else '')
    code = code.replace('/*__EDG_SHUTDOWN_TERMINATE__*/', 'global::System.Environment.FailFast("Exception escaped translated finalizer", error);')
    flush = 'if(__edg_files_value.IsValueCreated)__edg_files.Fflush(null);' if 'files' in groups or 'command' in groups else ''
    code = code.replace('/*__EDG_PROCESS_FLUSH__*/', flush)
    for name in ('__edg_register_exit', '__edg_process_exit'):
        code = code.replace('private static ' + ('int ' if name.endswith('register_exit') else 'void ') + name,
                            'internal static ' + ('int ' if name.endswith('register_exit') else 'void ') + name)
    if '@' in code or '/*__EDG_' in code:
        raise ValueError('Unresolved canonical lifecycle template parameter')
    support = '''// <auto-generated />
#nullable enable
using __edg_finalizer = global::Edg.Runtime.CppFinalizers.Entry;
namespace Edg.Runtime;
internal static unsafe partial class DotObjServices
{
    // Assembly lifetime: no implicit CLR finalizer or host ProcessExit callback.
    // Source termination and explicit thread release are the only boundaries.
    private static readonly object __edg_sync = CppFinalizers.Program.Sync;
    private static int __edg_state => CppFinalizers.Program.State;
    private static int __edg_process_exit_started;
    private static readonly global::System.Collections.Generic.List<__edg_finalizer> __edg_finalizers = CppFinalizers.Program.Normal;
    private static readonly global::System.Collections.Generic.List<__edg_finalizer> __edg_quick_finalizers = CppFinalizers.Program.Quick;
    private sealed class ThreadFinalizers
    {
        internal readonly global::System.Collections.Generic.List<__edg_finalizer> Finalizers = new();
    }
    private static readonly global::System.Threading.ThreadLocal<ThreadFinalizers> __edg_threads = new(() => new());
    internal static int RegisterDestructor(nint function, nint argument, bool threadLocal)
    {
        return CppFinalizers.Program.Register(threadLocal ? __edg_threads.Value!.Finalizers : __edg_finalizers, function, argument);
    }
    internal static void ReleaseThreadFinalizers()
    {
        if (__edg_threads.IsValueCreated) __edg_drain(__edg_threads.Value!.Finalizers);
    }
    [global::System.Diagnostics.CodeAnalysis.DoesNotReturn]
    internal static void ImmediateExit(int status) => global::Edg.Runtime.LibcProcessExit.Exit(status);
'''
    hooks = '''// <auto-generated />
#nullable enable
namespace Edg.Runtime;
public static unsafe partial class ObjectProgram
{
    // Run is the source executable boundary. InitializeLibrary/ordinary exports
    // retain host-controlled lifetime and never implicitly terminate the host.
    static partial void NormalExit(int status) => DotObjServices.__edg_process_exit(status, false);
    public static void ReleaseThread() => DotObjServices.ReleaseRuntimeThread();
}
'''
    if owned_static_registry:
        hooks = hooks.replace('    public static void ReleaseThread()',
            '    static partial void FinalizeRuntimeThread() => DotObjServices.ReleaseRuntimeThread();\n'
            '    static partial void FinalizeRuntimeServices() => DotObjServices.FlushAfterLibraryFinalization();\n'
            '    public static void ReleaseThread()')
        support += '    internal static void FlushAfterLibraryFinalization() { ' + flush + ' }\n'
    if threads:
        support = support.replace('internal readonly global::System.Collections.Generic.List<__edg_finalizer> Finalizers',
                                  'internal int Depth;\n        internal readonly global::System.Collections.Generic.List<__edg_finalizer> Finalizers')
    else:
        code += '''
    [global::System.ThreadStatic] private static bool __edg_releasing_thread;
    internal static void ReleaseRuntimeThread()
    {
        if (__edg_releasing_thread) throw new global::System.InvalidOperationException("Cannot release a thread during its cleanup");
        __edg_releasing_thread = true;
        try
        {
            ReleaseThreadFinalizers();
            @TEXT_RELEASE@
            @LIBC_RELEASE@
            ObjectProgram.ReleaseThreadStorage();
            __edg_threads.Value = new ThreadFinalizers();
        }
        finally { __edg_releasing_thread = false; }
    }
'''.replace('@TEXT_RELEASE@', 'if (__edg_text_value.IsValueCreated) __edg_text.ReleaseThread();' if groups & {'text', 'files', 'command'} else '').replace(
            '@LIBC_RELEASE@', '__edg_libc.ReleaseThread();' if has_libc else '')
    return {'Runtime.Process.generated.cs': support + code + '}\n', 'Runtime.ProcessHooks.generated.cs': hooks}
