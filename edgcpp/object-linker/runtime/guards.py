"""Itanium local-static guards using the canonical managed guard algorithm."""
from process import member


def expression(method):
    target = {'__cxa_guard_acquire': ('int', '__edg_guard_acquire', ''),
              '__cxa_guard_release': ('void', '__edg_guard_finish', ', true'),
              '__cxa_guard_abort': ('void', '__edg_guard_finish', ', false')}.get(method['symbol'])
    if target is None:
        return None
    result, name, argument = target
    # The owned LP64 target uses EDG's unsigned-long-long Itanium guard ABI.
    if method['variadic'] or method['result'] != result or [kind for kind, _ in method['arguments']] != ['ulong*']:
        raise ValueError('Local-static guard ABI does not match portable Itanium lowering: ' + method['symbol'])
    return 'global::Edg.Runtime.DotObjGuards.' + name + '((byte*)' + method['arguments'][0][1] + argument + ')'


def source(backend):
    lifecycle = (backend / 'dot_gen_lifecycle.h').read_text()
    code = '\n'.join(member(lifecycle, name) for name in ('__edg_guard', '__edg_guard_acquire', '__edg_guard_finish'))
    code = code.replace('@MOD@', 'static ').replace('private static int __edg_guard_acquire', 'internal static int __edg_guard_acquire')
    code = code.replace('private static void __edg_guard_finish', 'internal static void __edg_guard_finish')
    return '''// <auto-generated />
#nullable enable
namespace Edg.Runtime;
internal static unsafe class DotObjGuards
{
    private static readonly object __edg_sync = new();
    private static readonly global::System.Collections.Generic.Dictionary<nint, __edg_guard> __edg_guards = new();
''' + code + '}\n'
