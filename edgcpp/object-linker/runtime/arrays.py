"""Itanium array construction/destruction from the direct backend template."""


def expression(method):
    symbol = method['symbol']
    if symbol not in ('__cxa_vec_ctor', '__cxa_vec_dtor'):
        return None
    callback = 'delegate* managed<void*, void>'
    parameters = ['void*', 'ulong', 'ulong', callback]
    if symbol == '__cxa_vec_ctor':
        parameters.append(callback)
    if method['variadic'] or method['result'] != 'void' or \
            [kind for kind, _ in method['arguments']] != parameters:
        raise ValueError('Array helper ABI does not match portable Itanium lowering: ' + symbol)
    name = '__edg_vec_ctor' if symbol == '__cxa_vec_ctor' else '__edg_vec_dtor'
    return 'global::Edg.Runtime.DotObjArrays.' + name + '(' + ', '.join(name for _, name in method['arguments']) + ')'


def source(backend, threads=False):
    text = (backend / 'dot_gen_arrays.h').read_text()
    code = text.split('string code=R"CS(', 1)[1].split(')CS";', 1)[0]
    jump = 'jump_check is not global::Edg.Runtime.NonlocalJump.Transfer'
    control = 'error is not global::Edg.Runtime.NonlocalJump.Transfer'
    if threads:
        control += ' && error is not global::Edg.Runtime.CThreadExitTransfer'
    for key, value in {'@MOD@': 'static ', '@CALLBACK@': 'delegate* managed<void*, void>',
                       '@OWNER@': '', '@CONTROL_TRANSFER_EXCLUSION@': control,
                       '@SOURCE_JUMP_EXCLUSION@': jump}.items():
        code = code.replace(key, value)
    if '@' in code:
        raise ValueError('Unresolved canonical array template parameter')
    for name in ('__edg_vec_ctor', '__edg_vec_dtor'):
        code = code.replace('private static void ' + name, 'internal static void ' + name)
    return '''// <auto-generated />
#nullable enable
namespace Edg.Runtime;
internal static unsafe partial class DotObjArrays
{
    // The owned C++ EH provider must supply the translated terminate handler
    // when that ABI becomes available. Until then its imports remain unresolved;
    // the default terminate action is fatal, never a swallowed cleanup error.
    static partial void Terminate(global::System.Exception error, string reason);
    [global::System.Diagnostics.CodeAnalysis.DoesNotReturn]
    private static void __edg_terminate_runtime(global::System.Exception error, string reason)
    {
        try { Terminate(error, reason); }
        catch (global::System.Exception failure)
        { global::System.Environment.FailFast("Exception escaped translated terminate handler", failure); }
        global::System.Environment.FailFast(reason, error);
    }
''' + code + '}\n'
