"""Strict adapters for the canonical C11/libc++ external thread ABI."""
import json
import re
from process import member

OWNER = 'global::Edg.Runtime.DotObjThreadOwner'
RUNTIME = 'global::Edg.Runtime.LibcxxThreads<' + OWNER + '>'
SERVICES = 'global::Edg.Runtime.DotObjServices.'


def definitions(backend):
    rows = {}
    c11 = backend / 'runtime/libc-c11-threads-bindings.def'
    cpp = backend / 'dot_gen_threads.h'
    for line in c11.read_text().splitlines():
        found = re.fullmatch(r'EDG_C11_THREAD\((.*)\)', line.strip())
        if found:
            symbol, result, parameters, expression = json.loads('[' + found.group(1) + ']')
            rows[symbol] = (result, parameters, expression)
    table = cpp.read_text().split('const binding bindings[]={', 1)[1].split('\n  };', 1)[0]
    for line in table.splitlines():
        found = re.fullmatch(r'\s*\{(.*)\},', line)
        if found:
            symbol, result, parameters, expression = json.loads('[' + found.group(1) + ']')
            if symbol in rows:
                raise ValueError('Duplicate canonical thread binding: ' + symbol)
            rows[symbol] = (result, parameters, expression)
    return rows, (c11, cpp)


def expression(method, boundaries, rows):
    row = rows.get(method['symbol'])
    if row is None:
        return None

    def classify(kind):
        token, _ = boundaries.classify(kind)
        if token == 'TIMESPEC*':
            return 'timespec*'
        callback = re.fullmatch(r'delegate\* managed<([^<>]+)>', kind)
        if callback:
            parameters = [part.strip() for part in callback.group(1).split(',')]
            return parameters[-1] + '(' + ','.join(parameters[:-1]) + ')'
        return token

    returns, parameters, expression = row
    if method['variadic'] or classify(method['result']) != returns or ','.join(classify(kind) for kind, _ in method['arguments']) != parameters:
        raise ValueError('Thread import ABI does not match canonical runtime: ' + method['symbol'])
    expression = expression.replace('@RUNTIME@', RUNTIME).replace('__edg_thread_services.', SERVICES + '__edg_thread_services.')
    arguments = [name for _, name in method['arguments']]
    expression = re.sub(r'\ba(\d+)\b', lambda match: arguments[int(match.group(1))], expression)
    stateless = method['symbol'] in ('__edg_libcpp_atomic_table', '__edg_libcpp_atomic_wait64', '__edg_libcpp_atomic_wake64')
    return expression, stateless


def sources(backend, groups):
    lifecycle = (backend / 'dot_gen_lifecycle.h').read_text()
    adapters = '\n'.join(member(lifecycle, name) for name in
        ('__edg_acquire_thread_lease', '__edg_release_thread_lease', '__edg_enter_retained_thread', '__edg_leave')).replace('@MOD@', 'static ')
    code = '''// <auto-generated />
#nullable enable
namespace Edg.Runtime;
internal sealed class DotObjThreadOwner { }
internal static unsafe partial class DotObjServices
{
    private static readonly DotObjThreadOwner __edg_thread_owner = new();
    private static readonly int __edg_shutdown_thread = 0;
    private static int __edg_active, __edg_thread_leases;
    private static readonly global::System.Lazy<LibcxxThreads<DotObjThreadOwner>> __edg_thread_services_value = new(() =>
        new(__edg_thread_owner, &RetainThread, &ReleaseThreadLease, &EnterThread, &LeaveThread, &ReleaseThreadState, &TerminateThread));
    internal static LibcxxThreads<DotObjThreadOwner> __edg_thread_services => __edg_thread_services_value.Value;
    private static void RetainThread(DotObjThreadOwner owner) => __edg_acquire_thread_lease();
    private static void ReleaseThreadLease(DotObjThreadOwner owner) => __edg_release_thread_lease();
    private static void EnterThread(DotObjThreadOwner owner) => __edg_enter_retained_thread();
    private static void LeaveThread(DotObjThreadOwner owner) => __edg_leave();
    private static void ReleaseThreadState(DotObjThreadOwner owner) => ReleaseRuntimeThread();
    private static void TerminateThread(DotObjThreadOwner owner, global::System.Exception error) =>
        global::System.Environment.FailFast("Exception escaped translated thread", error);
    private static void LastSourceThread(DotObjThreadOwner owner) => __edg_process_exit(0, false, true);
    internal static void EnterInitialThread() => __edg_thread_services.EnterInitialThread(&LastSourceThread);
    internal static void ReleaseRuntimeThread()
    {
        lock (__edg_sync)
        {
            if (__edg_threads.Value!.Depth != 0) throw new global::System.InvalidOperationException("Cannot release an active translated thread");
            ++__edg_active;
            ++__edg_threads.Value.Depth;
        }
        try
        {
            ReleaseThreadFinalizers();
            if (__edg_thread_services_value.IsValueCreated) __edg_thread_services.ReleaseThread();
            @TEXT_RELEASE@
            __edg_libc.ReleaseThread();
            ObjectProgram.ReleaseThreadStorage();
            __edg_threads.Value = new ThreadFinalizers();
        }
        finally
        {
            lock (__edg_sync) { __edg_threads.Value!.Depth = 0; --__edg_active; global::System.Threading.Monitor.PulseAll(__edg_sync); }
        }
    }
'''
    text_release = 'if (__edg_text_value.IsValueCreated) __edg_text.ReleaseThread();' if groups & {'text', 'files', 'command'} else ''
    code = code.replace('@TEXT_RELEASE@', text_release)
    hooks = '''// <auto-generated />
#nullable enable
namespace Edg.Runtime;
public static unsafe partial class ObjectProgram
{
    static partial void Enter() => DotObjServices.EnterInitialThread();
    static partial void ClassifyTransfer(global::System.Exception error, ref bool isRuntimeTransfer)
    {
        if (error is CThreadExitTransfer) isRuntimeTransfer = true;
    }
    static partial void TryHandleTransfer(global::System.Exception error, ref bool handled, ref int result)
    {
        if (error is CThreadExitTransfer exit && DotObjServices.__edg_thread_services.IsInitialThreadExit(exit))
            DotObjServices.__edg_thread_services.ExitInitialThread(exit);
    }
}
'''
    return {'Runtime.Threads.generated.cs': code + adapters + '}\n', 'Runtime.ThreadHooks.generated.cs': hooks}
