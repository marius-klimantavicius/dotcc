using System.Text;

namespace DotObj;

internal sealed partial class Emitter
{
    // Called only after the linker has selected and ordered the owned startup
    // actions. Source constructors execute outside CLR type initialization and
    // outside this state lock, so constructor-created threads may use exports.
    private void WriteStartup(string output, IReadOnlyList<Symbol> actions)
        =>WriteStartupCalls(output,actions.Select(action=>(FunctionReference(action),action.Object.GeneratedRoutineOrigins.ContainsKey(action.Entity.Id))));
    private void WriteStartupCalls(string output,IEnumerable<(string Reference,bool Generated)> actions)
    {
        string invoke = generatedMembers.Allocate("__dot_run_startup_actions", "run_startup_actions");
        var source = new StringBuilder("""
            // <auto-generated />
            #nullable enable
            namespace Edg.Runtime;

            public static unsafe partial class ObjectProgram
            {
                private static readonly object __initializationLock = new();
                private static int __initializationState;
                private static int __initializationThread;
                private static global::System.Runtime.ExceptionServices.ExceptionDispatchInfo? __initializationFailure;

                public static void InitializeLibrary()
                {
                    int thread = global::System.Environment.CurrentManagedThreadId;
                    lock (__initializationLock)
                    {
                        while (__initializationState == 1)
                        {
                            if (__initializationThread == thread) return;
                            global::System.Threading.Monitor.Wait(__initializationLock);
                        }
                        if (__initializationState == 2) return;
                        if (__initializationFailure is not null) __initializationFailure.Throw();
                        __initializationState = 1;
                        __initializationThread = thread;
                    }
                    try
                    {
            """);
        source.Append('\n').Append("            global::System.Runtime.CompilerServices.RuntimeHelpers.RunClassConstructor(typeof(")
            .Append(Owner).Append(").TypeHandle);\n");
        source.Append("            ").Append(Owner).Append('.').Append(invoke).Append("();\n");
        source.Append("""
                    }
                    catch (global::System.Exception error)
                    {
                        lock (__initializationLock)
                        {
                            __initializationFailure = global::System.Runtime.ExceptionServices.ExceptionDispatchInfo.Capture(error);
                            __initializationState = 3;
                            __initializationThread = 0;
                            global::System.Threading.Monitor.PulseAll(__initializationLock);
                        }
                        throw;
                    }
                    lock (__initializationLock)
                    {
                        __initializationState = 2;
                        __initializationThread = 0;
                        global::System.Threading.Monitor.PulseAll(__initializationLock);
                    }
                }
            }
            """);
        File.WriteAllText(Path.Combine(output, "Runtime.Startup.generated.cs"), source + "\n", new UTF8Encoding(false));
        var dispatch = new StringBuilder("// <auto-generated />\n#nullable enable\nnamespace ").Append(namespaceName)
            .Append(";\npublic static unsafe partial class ").Append(className).Append("\n{\n    internal static void ")
            .Append(invoke).Append("()\n    {\n");
        using var writer=new StreamWriter(Path.Combine(output,"Translated.Startup.generated.cs"),false,new UTF8Encoding(false));
        void Flush(){foreach(var chunk in dispatch.GetChunks())writer.Write(chunk.Span);dispatch.Clear();}
        Flush();
        foreach (var action in actions)
        {
            if (!action.Generated)
            {
                dispatch.Append("        ").Append(action.Reference).Append("();\n");
                Flush();
                continue;
            }
            // A file-scope initializer terminates if an exception escapes. This
            // is a scheduling boundary, not a fabricated noexcept routine ABI.
            dispatch.Append("        try\n        {\n            ").Append(action.Reference).Append("();\n        }\n")
                .Append("        catch (global::System.Exception error) when (!global::Edg.Runtime.ObjectProgram.IsRuntimeTransfer(error))\n")
                .Append("        {\n            global::System.Environment.FailFast(\"Exception escaped a file-scope initializer\", error);\n            throw;\n        }\n");
            Flush();
        }
        dispatch.Append("    }\n}\n");
        Flush();
    }
}
