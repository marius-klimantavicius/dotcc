using System.Text;
using System.Text.Json;

namespace DotObj;

internal sealed partial class Emitter
{
    private readonly Dictionary<string, string> exceptionDescriptorNames = new(StringComparer.Ordinal);
    private readonly Dictionary<(ObjectFile Object, long Destructor), string> exceptionDestructorNames = [];
    private const string ExceptionRuntime = "global::Edg.Runtime.CppExceptions";

    private void WriteSourceExceptionContract(string output)
    {
        if (!linker.RequiresExceptionProvider) return;
        File.WriteAllText(Path.Combine(output, "Edg.Runtime.CppExceptions.generated.cs"), """
// <auto-generated />
#nullable enable
namespace Edg.Runtime;

// Contract only. A shared provider must implement payload ownership, failure
// policy and active-handler state before this generated module can execute.
public readonly record struct CppExceptionBase(string IdentityKey, nuint ByteOffset, bool IsPublic, bool IsAmbiguous);
public sealed record CppExceptionType(string IdentityKey, string LeafIdentityKey, string LeafKind,
    global::System.ReadOnlyMemory<int> PointerQualifiers, nuint PayloadSize, nuint PayloadAlignment, bool RequiresDestruction,
    global::System.ReadOnlyMemory<CppExceptionBase> Bases);
public abstract unsafe class CppException : global::System.Exception
{
    public abstract void* ObjectAddress { get; }
}
public static unsafe partial class CppExceptions
{
    // Allocate unconstructed payload storage; the callback is armed only by
    // MarkComplete. Storage uses the descriptor's explicit size/alignment.
    public static partial CppException Allocate(CppExceptionType type, delegate* managed<void*, void> completeDestructor);
    // Idempotent, nonthrowing uncaught-exception bookkeeping, at the owned
    // start marker or immediately before MarkComplete if no marker ran.
    public static partial void EnsureStarted(CppException payload);
    public static partial void MarkComplete(CppException payload);
    // First-pass policy: ignore the payload's own propagation; terminate an
    // escaping copy failure after start; permit pre-start evaluation failure.
    // Runtime control transfers require their distinct shared classification.
    public static partial bool FilterInitializationFailure(CppException payload, global::System.Exception error);
    // Invoked only after required partial-object cleanup, without calling the
    // destructor of an incompletely constructed payload.
    public static partial void ReleaseIncomplete(CppException payload);
    [global::System.Diagnostics.CodeAnalysis.DoesNotReturn]
    public static partial global::System.Exception Rethrow();
}
""" + "\n", new UTF8Encoding(false));
        if (linker.RequiresSourceHandlers)
            File.WriteAllText(Path.Combine(output, "Edg.Runtime.CppHandlers.generated.cs"), """
// <auto-generated />
#nullable enable
namespace Edg.Runtime;
public abstract class CppCatch
{
    public abstract bool Active { get; }
}
public static unsafe partial class CppExceptions
{
    // First-pass search: preserve runtime transfer/termination policy. This
    // must not destroy objects or consume the propagating exception.
    public static partial bool FilterCatchAll(global::System.Exception error);
    // Called after unwinding the protected body's objects to its saved entry
    // cursor. The frame participates in a per-thread active-handler stack.
    // EnterCatch/MarkCaught bookkeeping must not throw; unrecoverable runtime
    // allocation failures terminate rather than abandoning payload ownership.
    public static partial CppCatch EnterCatch(global::System.Exception error);
    public static partial void MarkCaught(CppCatch frame);
    // First-pass failure classification before handler-local destruction.
    public static partial bool FilterHandlerFailure(CppCatch frame, global::System.Exception error);
    // Idempotent. Relinquish this handler's ownership after its locals die;
    // retain a rethrown object or one still owned by another active handler.
    public static partial void LeaveCatch(CppCatch frame);
}
""" + "\n", new UTF8Encoding(false));
        var code = new StringBuilder("// <auto-generated />\n#nullable enable\nnamespace " + namespaceName + ";\npublic static unsafe partial class " + className + "\n{\n");
        foreach (var group in linker.UsedExceptionTypes.OrderBy(pair => pair.Value.IdentityKey, StringComparer.Ordinal)
            .GroupBy(pair => pair.Value.IdentityKey, StringComparer.Ordinal))
        {
            var first = group.First();
            ObjectFile obj = first.Key.Object;
            ExceptionType type = first.Value;
            string name = generatedMembers.Allocate("__exception_type_" + exceptionDescriptorNames.Count, "exception_type");
            exceptionDescriptorNames.Add(type.IdentityKey, name);
            var qualifiers = new List<int>();
            SourceType current = obj.SourceTypes[type.SourceTypeId];
            while (true)
            {
                while (current.Kind is "typedef" or "qualified") current = obj.SourceTypes[current.UnderlyingTypeId!.Value];
                if (current.Kind != "pointer") break;
                current = obj.SourceTypes[current.UnderlyingTypeId!.Value];
                int flags = 0;
                while (true)
                {
                    flags |= (current.IsConst ? 1 : 0) | (current.IsVolatile ? 2 : 0);
                    if (current.Kind is not ("typedef" or "qualified")) break;
                    current = obj.SourceTypes[current.UnderlyingTypeId!.Value];
                }
                qualifiers.Add(flags);
            }
            code.Append("    private static readonly global::Edg.Runtime.CppExceptionType ").Append(name).Append(" = new(\n        ")
                .Append(JsonSerializer.Serialize(type.IdentityKey)).Append(", ").Append(JsonSerializer.Serialize(obj.ExceptionTypeIdentity(type.LeafSourceTypeId)))
                .Append(", ").Append(JsonSerializer.Serialize(obj.SourceTypes[type.LeafSourceTypeId].Kind)).Append(",\n        new int[] { ")
                .Append(string.Join(", ", qualifiers)).Append(" }, ").Append(type.PayloadSize).Append("U, ").Append(type.PayloadAlignment)
                .Append("U, ").Append(type.SourceDestructorEntityId is null ? "false" : "true").Append(", new global::Edg.Runtime.CppExceptionBase[]\n        {\n");
            foreach (ExceptionBaseConversion item in obj.ExceptionBases[type.Id])
                code.Append("            new(").Append(JsonSerializer.Serialize(obj.ExceptionTypeIdentity(item.BaseSourceTypeId)))
                    .Append(", ").Append(item.ByteOffset).Append("U, ").Append(item.IsPublic ? "true" : "false")
                    .Append(", ").Append(item.IsAmbiguous ? "true" : "false").Append("),\n");
            code.Append("        });\n");
        }
        foreach (Symbol function in linker.Definitions)
        {
            ObjectFile obj = function.Object;
            FunctionBody body = obj.ReadBody(function.Entity.Id);
            foreach (Node node in body.Nodes.Values.Where(node => node.Kind == "throw"))
            {
                ThrowExpression expression = obj.ThrowExpressions[node.Id];
                if (expression.DestructorEntityId is not long destructor || exceptionDestructorNames.ContainsKey((obj, destructor))) continue;
                string name = generatedMembers.Allocate("__destroy_exception_" + obj.Entities[destructor].SourceName, "destroy_exception");
                exceptionDestructorNames.Add((obj, destructor), name);
                Symbol callback = linker.Resolve(obj, destructor);
                code.Append("    private static void ").Append(name).Append("(void* payload) => ").Append(FunctionReference(callback))
                    .Append("((").Append(Type(obj.Parameters[destructor][0])).Append(")payload);\n");
            }
        }
        code.Append("}\n");
        File.WriteAllText(Path.Combine(output, "Translated.Exceptions.generated.cs"), code.ToString(), new UTF8Encoding(false));
    }
}
