    // Matching-adjusted source address used by EDG's selected parameter
    // initializer. Class references alias the payload's base subobject.
    // Pointer conversions require stable per-handler pointer storage, retaining
    // the original payload unchanged for rethrow. Valid through LeaveCatch.
    public abstract void* ObjectAddress { get; }
