        if (sharedExceptionProvider || linker.UsedCatchTypes.Count != 0 || linker.RequiresDynamicSpecifications)
            File.WriteAllText(Path.Combine(output, "Edg.Runtime.CppTypedHandlers.generated.cs"), """
