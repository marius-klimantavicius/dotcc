    // Required production provider; intentionally no fallback implementation.
    // The source function has completed its automatic-object unwinding. The
    // provider must enter/mark a catch for the original exception, invoke the
    // active std::unexpected handler, and preserve ownership/uncaught counts.
    // A permitted replacement is rethrown with its exact payload. Otherwise
    // replace it with std::bad_exception only if allowed by the original list;
    // else call terminate. Empty lists still call unexpected before terminate.
