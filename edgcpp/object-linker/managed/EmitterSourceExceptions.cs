        if (sharedExceptionProvider)
        {
            using Stream source = typeof(Emitter).Assembly.GetManifestResourceStream("DotObj.Runtime.CppExceptions.cs")
                ?? throw new InvalidOperationException("Missing shared C++ exception provider");
            using var reader = new StreamReader(source);
            File.WriteAllText(Path.Combine(output, "Runtime.CppExceptions.cs"), "// <auto-generated />\n" + reader.ReadToEnd(), new UTF8Encoding(false));
        }
        var code = new StringBuilder("// <auto-generated />\n#nullable enable\nnamespace " + namespaceName + ";\npublic static unsafe partial class " + className + "\n{\n");
        foreach (var group in linker.UsedExceptionTypes.OrderBy(pair => pair.Value.IdentityKey, StringComparer.Ordinal)
            .GroupBy(pair => pair.Value.IdentityKey, StringComparer.Ordinal))
        {
            var first = group.First();
            ObjectFile obj = first.Key.Object;
            ExceptionType type = first.Value;
            string name = ExceptionName("exception-type",type.IdentityKey,"__exception_type_" + exceptionDescriptorNames.Count);
            exceptionDescriptorNames.Add(type.IdentityKey, name);
            if(!EmitDescriptor("exception-type",type.IdentityKey))continue;
            var qualifiers = new List<int>();
            SourceType current = obj.SourceTypes[type.SourceTypeId];
            while (true)
            {
                while (current.Kind is "typedef" or "qualified") current = obj.SourceTypes[current.UnderlyingTypeId!.Value];
                if (current.Kind != "pointer") break;
                current = obj.SourceTypes[current.UnderlyingTypeId!.Value];
                int flags = 0;
                while (true)
                {
                    flags |= (current.IsConst ? 1 : 0) | (current.IsVolatile ? 2 : 0);
                    if (current.Kind is not ("typedef" or "qualified")) break;
                    current = obj.SourceTypes[current.UnderlyingTypeId!.Value];
                }
                qualifiers.Add(flags);
            }
            code.Append("    private static readonly global::Edg.Runtime.CppExceptionType ").Append(name).Append(" = new(\n        ")
                .Append(JsonSerializer.Serialize(type.IdentityKey)).Append(", ").Append(JsonSerializer.Serialize(obj.ExceptionTypeIdentity(type.LeafSourceTypeId)))
                .Append(", ").Append(JsonSerializer.Serialize(obj.SourceTypes[type.LeafSourceTypeId].Kind)).Append(",\n        new int[] { ")
                .Append(string.Join(", ", qualifiers)).Append(" }, ").Append(type.PayloadSize).Append("U, ").Append(type.PayloadAlignment)
                .Append("U, ").Append(type.SourceDestructorEntityId is null ? "false" : "true").Append(", new global::Edg.Runtime.CppExceptionBase[]\n        {\n");
            foreach (ExceptionBaseConversion item in obj.ExceptionBases[type.Id])
                code.Append("            new(").Append(JsonSerializer.Serialize(obj.ExceptionTypeIdentity(item.BaseSourceTypeId)))
                    .Append(", ").Append(item.ByteOffset).Append("U, ").Append(item.IsPublic ? "true" : "false")
                    .Append(", ").Append(item.IsAmbiguous ? "true" : "false").Append("),\n");
            code.Append("        });\n");
        }
        foreach (var pair in linker.UsedCatchTypes.OrderBy(pair => pair.Key.Object.ExceptionTypeIdentity(pair.Key.Id), StringComparer.Ordinal))
        {
            ObjectFile obj = pair.Key.Object; string identity = obj.ExceptionTypeIdentity(pair.Key.Id);
            if (catchDescriptorNames.ContainsKey(identity)) continue;
            string name = ExceptionName("catch-type",identity,"__catch_type_" + catchDescriptorNames.Count);
            catchDescriptorNames.Add(identity, name);
            if(!EmitDescriptor("catch-type",identity))continue;
            SourceType current = pair.Value; var qualifiers = new List<int>();
            while (true)
            {
                while (current.Kind is "typedef" or "qualified") current = obj.SourceTypes[current.UnderlyingTypeId!.Value];
                if (current.Kind != "pointer") break;
                current = obj.SourceTypes[current.UnderlyingTypeId!.Value]; int flags = 0;
                while (true)
                {
                    flags |= (current.IsConst ? 1 : 0) | (current.IsVolatile ? 2 : 0);
                    if (current.Kind is not ("typedef" or "qualified")) break;
                    current = obj.SourceTypes[current.UnderlyingTypeId!.Value];
                }
                qualifiers.Add(flags);
            }
            code.Append("    private static readonly global::Edg.Runtime.CppCatchType ").Append(name).Append(" = new(")
                .Append(JsonSerializer.Serialize(identity)).Append(", ").Append(JsonSerializer.Serialize(obj.ExceptionTypeIdentity(current.Id)))
                .Append(", ").Append(JsonSerializer.Serialize(current.Kind)).Append(", new int[] { ")
                .Append(string.Join(", ", qualifiers)).Append(" });\n");
        }
        foreach (Symbol function in linker.Definitions)
        {
            ObjectFile obj = function.Object;
            if (!obj.DynamicExceptionBoundaries.TryGetValue(function.Entity.Id, out long specificationId) ||
                dynamicSpecificationNames.ContainsKey((obj, specificationId))) continue;
            string name = generatedMembers.Allocate("__dynamic_specification_" + dynamicSpecificationNames.Count, "dynamic_specification");
            dynamicSpecificationNames.Add((obj, specificationId), name);
            code.Append("    private static readonly global::Edg.Runtime.CppCatchType[] ").Append(name).Append(" = [")
                .Append(string.Join(", ", obj.DynamicExceptionSpecifications[specificationId].Types.Select(type =>
                    catchDescriptorNames[obj.ExceptionTypeIdentity(type.MatchSourceTypeId)]))).Append("];\n");
        }
        foreach (var site in ThrowSites())
        {
                ObjectFile obj=site.Object;
                ThrowExpression expression = obj.ThrowExpressions[site.Node];
                if (expression.DestructorEntityId is not long destructor || exceptionDestructorNames.ContainsKey((obj, destructor))) continue;
                string name = generatedMembers.Allocate("__destroy_exception_" + obj.Entities[destructor].SourceName, "destroy_exception");
                exceptionDestructorNames.Add((obj, destructor), name);
                Symbol callback = linker.Resolve(obj, destructor);
                code.Append("    private static void ").Append(name).Append("(void* payload) => ").Append(FunctionReference(callback))
                    .Append("((").Append(Type(obj.Parameters[destructor][0])).Append(")payload);\n");
        }
        code.Append("}\n");
        File.WriteAllText(Path.Combine(output, UnitFile("Translated.Exceptions.generated.cs")), code.ToString(), new UTF8Encoding(false));
    }
