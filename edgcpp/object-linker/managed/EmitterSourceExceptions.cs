    public static partial CppCatch EnterCatch(global::System.Exception error);
    public static partial void MarkCaught(CppCatch frame);
    // First-pass failure classification before handler-local destruction.
    public static partial bool FilterHandlerFailure(CppCatch frame, global::System.Exception error);
