using System.Globalization;
using System.Security.Cryptography;
using System.Text;

namespace DotObj;

internal sealed partial class Emitter
{
    private readonly Dictionary<string, long> storageOffsets = new(StringComparer.Ordinal);
    private string storageBytes = "", storageBase = "", tlsBytes = "", tlsBase = "", tlsAccessor = "", tlsRelease = "";
    private string Owner => "global::" + namespaceName + "." + className;
    private string StorageReference(StorageSymbol symbol) => Owner + "." + linker.StorageNames[symbol.Key];
    private string ExternStorageName(StorageSymbol symbol) => "__dot_storage_address_" + Names.Identifier(symbol.Storage.SourceName) + "_" +
        Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(symbol.Storage.ExternalKey!)))[..12];
    private string ExternStorageReference(StorageSymbol symbol) => "global::Edg.Runtime.LibC." + ExternStorageName(symbol);
    private string StorageAddress(StorageSymbol symbol, long addend = 0) => linker.ExternStorages.ContainsKey(symbol.Key)
        ? "((byte*)" + ExternStorageReference(symbol) + "()" + (addend == 0 ? "" : " + " + addend.ToString(CultureInfo.InvariantCulture)) + ")"
        : "(" + Owner + "." +
        (symbol.Storage.IsThreadLocal ? tlsAccessor + "()" : storageBase) + " + " + (storageOffsets[symbol.Key] + addend).ToString(CultureInfo.InvariantCulture) + LiteralComment(symbol, addend) + ")";
    private bool SharedExtern(Symbol symbol)
    {
        bool Portable(string type) => ScalarTypes.IsPointer(type) ? Portable(ScalarTypes.Pointee(type))
            : RoutineTypes.IsRoutine(type) ? RoutineTypes.Signature(type).Parameters.Append(RoutineTypes.Signature(type).Result).All(Portable)
            : !ScalarTypes.IsRecord(type) && !ScalarTypes.IsArray(type);
        return symbol.Entity.ExternalKey == symbol.Entity.SourceName && Portable(symbol.Object.Type(symbol.Entity.ReturnTypeId)) &&
            symbol.Object.Parameters.GetValueOrDefault(symbol.Entity.Id, []).All(Portable);
    }
    private string ExternName(Symbol symbol) => SharedExtern(symbol)
        ? Names.OptionIdentifier(Names.Identifier(symbol.Entity.SourceName)) : linker.Names[symbol.Key];
    private readonly Dictionary<string, string> noexceptExternNames = new(StringComparer.Ordinal);
    private string ExternProviderReference(Symbol symbol) => (SharedExtern(symbol) ? "global::Edg.Runtime.LibC." : Owner + ".") + ExternName(symbol);
    private string FunctionReference(Symbol symbol)
    {
        if (!linker.Externs.ContainsKey(symbol.Key)) return Owner + "." + linker.Names[symbol.Key];
        if (symbol.Object.Routines[symbol.Entity.RoutineTypeId].ExceptionPolicy != "terminate") return ExternProviderReference(symbol);
        if (!noexceptExternNames.TryGetValue(symbol.Key, out string? name))
            noexceptExternNames.Add(symbol.Key, name = generatedMembers.Allocate("__dot_noexcept_" + symbol.Entity.SourceName, "noexcept_extern"));
        return Owner + "." + name;
    }

    private void WriteExterns(string output)
    {
        foreach (bool shared in new[] { false, true })
        {
            Symbol[] symbols = linker.Externs.Values.Where(symbol => SharedExtern(symbol) == shared).OrderBy(symbol => symbol.Key, StringComparer.Ordinal).ToArray();
            if (symbols.Length == 0 && (!shared || linker.ExternStorages.Count == 0)) continue;
            var code = new StringBuilder("// <auto-generated />\n#nullable enable\nnamespace ")
                .Append(shared ? "Edg.Runtime" : namespaceName).Append(";\n\npublic static unsafe partial class ")
                .Append(shared ? "LibC" : className).Append("\n{\n");
            foreach (Symbol symbol in symbols)
                code.Append("    public static partial ").Append(Type(symbol.Object.Type(symbol.Entity.ReturnTypeId))).Append(' ').Append(ExternName(symbol))
                    .Append('(').AppendJoin(", ", symbol.Object.Parameters.GetValueOrDefault(symbol.Entity.Id, []).Select((type, index) => Type(type) + " argument" + index).Concat(symbol.Object.Routines[symbol.Entity.RoutineTypeId].Variadic ? ["params global::System.ReadOnlySpan<global::Edg.Runtime.VaArg> arguments"] : []))
                    .Append(");\n");
            if (shared)
                foreach (StorageSymbol symbol in linker.ExternStorages.Values.OrderBy(symbol => symbol.Key, StringComparer.Ordinal))
                    code.Append("    // Provider owns this ").Append(symbol.Storage.IsThreadLocal ? "thread-local" : "global")
                        .Append(" cell: ").Append(symbol.Storage.SourceName).Append("; minimum size ")
                        .Append(linker.StorageMinimumSize(symbol)).Append(", alignment ").Append(symbol.Storage.Alignment)
                        .Append(". Address remains stable for its lifetime.\n    public static partial void* ")
                        .Append(ExternStorageName(symbol)).Append("();\n");
            code.Append("}\n");
            File.WriteAllText(Path.Combine(output, shared ? "Edg.Runtime.generated.cs" : "Translated.Runtime.generated.cs"), code.ToString(), new UTF8Encoding(false));
        }
    }

    private void WriteNoexceptExterns(string output)
    {
        Symbol[] symbols = linker.Externs.Values.Where(symbol => symbol.Object.Routines[symbol.Entity.RoutineTypeId].ExceptionPolicy == "terminate")
            .OrderBy(symbol => symbol.Key, StringComparer.Ordinal).ToArray();
        if (symbols.Length == 0) return;
        var code = new StringBuilder("// <auto-generated />\n#nullable enable\nnamespace ").Append(namespaceName)
            .Append(";\n\npublic static unsafe partial class ").Append(className).Append("\n{\n");
        foreach (Symbol symbol in symbols)
        {
            _ = FunctionReference(symbol);
            string result = symbol.Object.Type(symbol.Entity.ReturnTypeId);
            List<string> parameters = symbol.Object.Parameters.GetValueOrDefault(symbol.Entity.Id, []);
            bool variadic = symbol.Object.Routines[symbol.Entity.RoutineTypeId].Variadic;
            code.Append("    private static ").Append(Type(result)).Append(' ').Append(noexceptExternNames[symbol.Key]).Append('(')
                .AppendJoin(", ", parameters.Select((type, ordinal) => Type(type) + " argument" + ordinal).Concat(variadic ? ["params global::System.ReadOnlySpan<global::Edg.Runtime.VaArg> arguments"] : []))
                .Append(")\n    {\n        try\n        {\n            ").Append(result == "void" ? "" : "return ")
                .Append(ExternProviderReference(symbol)).Append('(').AppendJoin(", ", parameters.Select((_, ordinal) => "argument" + ordinal).Concat(variadic ? ["arguments"] : []))
                .Append(");\n        }\n        catch (global::System.Exception error) when (!global::Edg.Runtime.ObjectProgram.IsRuntimeTransfer(error))\n        {\n")
                .Append("            global::System.Environment.FailFast(\"Exception escaped noexcept external function\", error);\n            throw;\n        }\n    }\n\n");
        }
        code.Append("}\n");
        File.WriteAllText(Path.Combine(output, "Translated.NoexceptExterns.generated.cs"), code.ToString(), new UTF8Encoding(false));
    }

    private void WriteStorage(string output)
    {
        if (linker.StorageDefinitions.Count == 0 && linker.ExternStorages.Count == 0) return;
        storageBytes = generatedMembers.Allocate("__dot_storage", "storage"); storageBase = generatedMembers.Allocate("__dot_storage_base", "storage_base");
        tlsBytes = generatedMembers.Allocate("__dot_tls_storage", "tls_storage"); tlsBase = generatedMembers.Allocate("__dot_tls_base", "tls_base");
        tlsAccessor = generatedMembers.Allocate("__dot_get_tls", "get_tls");
        long globalSize = 0, tlsSize = 0; long globalAlignment = 8, tlsAlignment = 8;
        foreach (StorageSymbol symbol in linker.StorageDefinitions)
        {
            Storage storage = symbol.Storage; ref long size = ref (storage.IsThreadLocal ? ref tlsSize : ref globalSize);
            size = checked((size + storage.Alignment - 1) / storage.Alignment * storage.Alignment);
            storageOffsets.Add(symbol.Key, size); size = checked(size + symbol.Object.StorageSize(symbol.Object.Type(storage.TypeId)));
            if (storage.IsThreadLocal) tlsAlignment = Math.Max(tlsAlignment, storage.Alignment); else globalAlignment = Math.Max(globalAlignment, storage.Alignment);
        }
        if (globalSize > int.MaxValue - globalAlignment || tlsSize > int.MaxValue - tlsAlignment) throw new InvalidDataException("Pinned storage arena exceeds managed array limit");
        var code = new StringBuilder("// <auto-generated />\n#nullable enable\nnamespace ").Append(namespaceName)
            .Append(";\n\npublic static unsafe partial class ").Append(className).Append("\n{\n");
        if (globalSize != 0)
            code.Append("    private static readonly byte[] ").Append(storageBytes).Append(";\n    private static readonly byte* ").Append(storageBase).Append(";\n");
        if (tlsSize != 0)
            code.Append("    [global::System.ThreadStatic] private static byte[]? ").Append(tlsBytes)
                .Append(";\n    [global::System.ThreadStatic] private static byte* ").Append(tlsBase).Append(";\n");
        foreach (StorageSymbol symbol in linker.StorageDefinitions.Concat(linker.ExternStorages.Values.OrderBy(symbol => symbol.Key, StringComparer.Ordinal)))
            code.Append("    public static ref ").Append(Type(symbol.Object.Type(symbol.Storage.TypeId))).Append(' ').Append(linker.StorageNames[symbol.Key])
                .Append(" => ref *(").Append(Type(symbol.Object.Type(symbol.Storage.TypeId))).Append("*)").Append(StorageAddress(symbol)).Append(";\n");
        code.Append("\n    static ").Append(className).Append("()\n    {\n        if (global::System.IntPtr.Size != 8 || !global::System.BitConverter.IsLittleEndian)\n")
            .Append("            throw new global::System.PlatformNotSupportedException(\"This object requires a little-endian 64-bit process.\");\n");
        if (globalSize != 0)
        {
            Allocate(code, storageBytes, storageBase, globalSize, globalAlignment, 8);
            Initialize(code, false, storageBase, 8);
        }
        code.Append("    }\n");
        if (tlsSize != 0)
        {
            code.Append("\n    private static byte* ").Append(tlsAccessor).Append("()\n    {\n        if (").Append(tlsBytes).Append(" is null)\n        {\n");
            Allocate(code, tlsBytes, tlsBase, tlsSize, tlsAlignment, 12);
            Initialize(code, true, tlsBase, 12);
            code.Append("        }\n        return ").Append(tlsBase).Append(";\n    }\n");
            tlsRelease = generatedMembers.Allocate("__dot_release_tls_storage", "release_tls_storage");
            code.Append("\n    internal static void ").Append(tlsRelease).Append("()\n    {\n        ").Append(tlsBase).Append(" = null;\n        ")
                .Append(tlsBytes).Append(" = null;\n    }\n");
        }
        foreach (string declaration in storageDataDeclarations) code.Append(declaration);
        code.Append("}\n"); File.WriteAllText(Path.Combine(output, "Translated.Storage.generated.cs"), code.ToString(), new UTF8Encoding(false));
    }
    private static void Allocate(StringBuilder code, string bytes, string pointer, long size, long alignment, int indent)
    {
        code.Append(' ', indent).Append(bytes).Append(" = global::System.GC.AllocateArray<byte>(").Append(size + alignment - 1).Append(", pinned: true);\n");
        code.Append(' ', indent).Append(pointer).Append(" = (byte*)(((nuint)global::System.Runtime.CompilerServices.Unsafe.AsPointer(ref ")
            .Append("global::System.Runtime.InteropServices.MemoryMarshal.GetArrayDataReference(").Append(bytes).Append(")) + ")
            .Append(alignment - 1).Append(") & ~(nuint)").Append(alignment - 1).Append(");\n");
    }
    private readonly List<string> storageDataDeclarations = [];
    private void Initialize(StringBuilder code, bool tls, string pointer, int indent)
    {
        // Allocate and root the complete arena before copying bytes or applying
        // addresses: cyclic static pointers always observe their final storage.
        var structured = new HashSet<string>(StringComparer.Ordinal);
        var locals = new Names();
        foreach (StorageSymbol symbol in linker.StorageDefinitions.Where(symbol => symbol.Storage.IsThreadLocal == tls))
        {
            if (TryReadableInitialization(code, symbol, pointer, indent, locals)) { structured.Add(symbol.Key); continue; }
            foreach (StorageData data in symbol.Object.StorageData.GetValueOrDefault(symbol.Storage.Id, []))
                EmitByteData(code, data.Bytes, pointer, storageOffsets[symbol.Key] + data.ByteOffset, indent);
        }
        foreach (StorageSymbol symbol in linker.StorageDefinitions.Where(symbol => symbol.Storage.IsThreadLocal == tls && !structured.Contains(symbol.Key)))
            foreach (Relocation relocation in symbol.Object.Relocations.GetValueOrDefault(symbol.Storage.Id, []))
            {
                string value;
                if (relocation.TargetStorageId is long storageId) value = "(nuint)" + StorageAddress(linker.ResolveStorage(symbol.Object, storageId), relocation.Addend);
                else
                {
                    Symbol target = linker.Resolve(symbol.Object, relocation.TargetEntityId!.Value);
                    value = "(nuint)(" + FunctionPointerType(target.Object.EntityRoutine(target.Entity.Id)) + ")&" + FunctionReference(target);
                }
                code.Append(' ', indent).Append("global::System.Runtime.CompilerServices.Unsafe.WriteUnaligned<nuint>(").Append(pointer).Append(" + ")
                    .Append(storageOffsets[symbol.Key] + relocation.ByteOffset).Append(", ").Append(value).Append(");\n");
            }
    }
}
