    private readonly CatalogEmissionPlan? emissionPlan;
    private readonly CatalogUnitDescriptor? emissionUnit;
    internal Emitter(Linker view,string namespaceOption,string classOption,bool shared,CatalogEmissionPlan plan,CatalogUnitDescriptor unit)
        :this(view,namespaceOption,classOption,shared)
    {
        emissionPlan=plan;emissionUnit=unit;generatedMembers=plan.Members;
        foreach(var (key,definition) in view.Records)
        {
            // Unselected provider-only records can have no global definition.
            if(plan.Scalar("SELECT identity_key FROM selected_records WHERE identity_key=?",key) is null)continue;
            recordNames[key]=Names.OptionIdentifier(plan.Name("record",key).TrimStart('@'));
            foreach(var field in definition.Object.RecordFields(definition.Record.TypeId))
                fieldNames[(key,field.Ordinal)]=plan.Name("field",key,field.Ordinal);
        }
        foreach(string type in view.Objects[0].Types.Values.Where(ScalarTypes.IsArray))
        {string canonical=view.CanonicalExecutionType(type);arrayNames.TryAdd(canonical,plan.Name("array",canonical));}
        foreach(var storage in view.Objects[0].Storages.Values)
        {
            string key=new StorageSymbol(view.Objects[0],storage).Key;
            if(plan.Selected("storage",key))storageOffsets[key]=plan.StorageOffset(key);
        }
        storageBytes=CatalogSupportName("storage","__dot_storage");storageBase=CatalogSupportName("storage-base","__dot_storage_base");
        tlsBytes=CatalogSupportName("tls","__dot_tls_storage");tlsBase=CatalogSupportName("tls-base","__dot_tls_base");
        tlsAccessor=CatalogSupportName("tls-accessor","__dot_get_tls");
        if(plan.Scalar("SELECT symbol_key FROM emission_storage WHERE is_tls=1 LIMIT 1") is not null)
            tlsRelease=CatalogSupportName("tls-release","__dot_release_tls_storage");
    }
    private string CatalogSupportName(string key,string source)=>emissionPlan!.Allocate("support",key,source,key);
    private string ArrayName(string key)=>arrayNames.TryGetValue(key,out string? name)?name:emissionPlan!.Name("array",key);
    private string RecordName(string key)=>recordNames.TryGetValue(key,out string? name)?name:Names.OptionIdentifier(emissionPlan!.Name("record",key).TrimStart('@'));
    private string UnitFile(string stem)=>emissionUnit is null?stem:stem.Replace(".generated.cs","."+emissionUnit.Id.ToString(CultureInfo.InvariantCulture)+".generated.cs",StringComparison.Ordinal);
    private bool EmitExternal(Symbol symbol)=>emissionPlan is null || emissionPlan.ExternalOwner("function",symbol.Key,emissionUnit!.Id,symbol.Entity.Id);
    private bool EmitExternal(StorageSymbol symbol)=>emissionPlan is null || emissionPlan.ExternalOwner("storage",symbol.Key,emissionUnit!.Id,symbol.Storage.Id);
    private string ExceptionName(string kind,string identity,string source)=>emissionPlan?.Allocate(kind,identity,source,kind) ?? generatedMembers.Allocate(source,kind);
    private bool EmitDescriptor(string kind,string identity)=>emissionPlan?.Claim(kind,identity) ?? true;
    internal void WriteCatalogGlobals(string output,(long GlobalSize,long GlobalAlignment,long TlsSize,long TlsAlignment) arena)
    {
        if(emissionPlan is null)throw new InvalidOperationException("Catalog emitter has no plan");
        using var writer=new StreamWriter(Path.Combine(output,"Translated.Globals.generated.cs"),false,new UTF8Encoding(false));
        writer.Write("// <auto-generated />\n#nullable enable\nnamespace "+namespaceName+";\npublic static unsafe partial class "+className+"\n{\n");
        var code=new StringBuilder();
        void Flush(){foreach(var chunk in code.GetChunks())writer.Write(chunk.Span);code.Clear();}
        foreach(string array in emissionPlan.Arrays()){WriteArray(code,array);Flush();}
        code.Append("    private static readonly byte* ").Append(storageBase).Append(";\n");
        if(arena.GlobalSize!=0)code.Append("    private static readonly byte[] ").Append(storageBytes).Append(";\n");
        code.Append("    static ").Append(className).Append("()\n    {\n        if (global::System.IntPtr.Size != 8 || !global::System.BitConverter.IsLittleEndian)\n            throw new global::System.PlatformNotSupportedException(\"This object requires a little-endian 64-bit process.\");\n");
        if(arena.GlobalSize!=0)Allocate(code,storageBytes,storageBase,arena.GlobalSize,arena.GlobalAlignment,8);
        foreach(long unit in emissionPlan.StorageUnits(false))
            code.Append("        ").Append(StorageInitializer(unit,false)).Append('(').Append(storageBase).Append(");\n");
        code.Append("    }\n");Flush();
        if(tlsRelease.Length!=0)
        {
            code.Append("    [global::System.ThreadStatic] private static byte[]? ").Append(tlsBytes).Append(";\n    [global::System.ThreadStatic] private static byte* ").Append(tlsBase).Append(";\n")
                .Append("    private static byte* ").Append(tlsAccessor).Append("()\n    {\n        if (").Append(tlsBytes).Append(" is null)\n        {\n");
            // A zero-byte TLS definition still needs a stable per-thread token.
            Allocate(code,tlsBytes,tlsBase,Math.Max(1,arena.TlsSize),arena.TlsAlignment,12);
            foreach(long unit in emissionPlan.StorageUnits(true))
                code.Append("            ").Append(StorageInitializer(unit,true)).Append('(').Append(tlsBase).Append(");\n");
            code.Append("        }\n        return ").Append(tlsBase).Append(";\n    }\n    internal static void ").Append(tlsRelease)
                .Append("()\n    {\n        ").Append(tlsBase).Append(" = null;\n        ").Append(tlsBytes).Append(" = null;\n    }\n");
        }
        code.Append("}\n");Flush();
        WriteProgramHooks(output);WriteStartupCalls(output,emissionPlan.StartupCalls(Owner));
    }
    private string StorageInitializer(long unit,bool tls)=>emissionPlan!.Allocate("storage-unit",unit.ToString(CultureInfo.InvariantCulture)+(tls?":tls":":global"),"__dot_initialize_"+unit+(tls?"_tls":""),"initialize_storage");
    internal (int Count,bool Arguments) WriteCatalogEntry(string output,string key)
    {
        int matches=linker.Definitions.Count(symbol=>symbol.Entity.Linkage=="external" && (symbol.Entity.ExternalKey==key || symbol.Entity.SourceName==key));
        if(matches==0)return(0,false);
        Symbol entry=linker.Entry(key);bool arguments=entry.Object.Parameters.GetValueOrDefault(entry.Entity.Id,[]).Count==2;
        string call=Owner+"."+linker.Names[entry.Key]+"("+(arguments?"argc, argv":"")+")";
        string body=entry.Object.Type(entry.Entity.ReturnTypeId)=="void"?call+"; return 0;":"return "+call+";";
        File.WriteAllText(Path.Combine(output,"Entry.generated.cs"),"// <auto-generated />\ninternal static unsafe class __DotObjEntry\n{\n    private static int InvokeMain("+
            (arguments?"int argc, sbyte** argv":"")+") { "+body+" }\n"+(arguments
            ?"    public static int Main()\n    {\n        using var arguments = global::Edg.Runtime.ProgramArguments.FromCommandLine();\n        return global::Edg.Runtime.ObjectProgram.Run(&InvokeMain, arguments.Count, arguments.Pointer);\n    }\n"
            :"    public static int Main() => global::Edg.Runtime.ObjectProgram.Run(&InvokeMain);\n")+"}\n",new UTF8Encoding(false));
        if(arguments)WriteRuntimeSupport(output,true);
        return(matches,arguments);
    }
    internal void WriteCatalogReport()
    {
        if(emissionPlan is null || emissionUnit is null)throw new InvalidOperationException("No catalog report owner");
        foreach(var symbol in linker.Definitions)emissionPlan.Report("symbols",symbol.Key,new{unitId=symbol.Object.UnitId,entityId=symbol.Entity.Id,
            externalKey=symbol.Entity.ExternalKey,sourceName=symbol.Entity.SourceName,generatedName=linker.Names[symbol.Key],signature=symbol.Signature});
        foreach(var (key,definition) in linker.Records)
            if(emissionPlan.Scalar("SELECT identity_key FROM selected_records WHERE identity_key=? AND unit_id=? AND local_id=?",key,emissionUnit.Id,definition.Record.TypeId) is not null)
                emissionPlan.Report("records",key,new{identityKey=definition.Record.IdentityKey,sourceName=definition.Record.SourceName,generatedType=Type(key),
                    unitId=definition.Object.UnitId,typeId=definition.Record.TypeId,size=definition.Record.Size,alignment=definition.Record.Alignment});
        foreach(var symbol in linker.Externs.Values.Where(EmitExternal).Where(value=>RuntimeArrayProvider.TryGetMethod(value) is null))
            emissionPlan.Report("runtimeRequirements",symbol.Key,new{symbol.Entity.ExternalKey,symbol.Entity.SourceName,symbol.Signature,
                unitId=symbol.Object.UnitId,entityId=symbol.Entity.Id,generatedName=ExternName(symbol),functionReference=ExternProviderReference(symbol),callReference=FunctionReference(symbol),
                container=SharedExtern(symbol)?"global::Edg.Runtime.LibC":Owner,returnType=Type(symbol.Object.Type(symbol.Entity.ReturnTypeId)),
                parameters=symbol.Object.Parameters.GetValueOrDefault(symbol.Entity.Id,[]).Select((type,ordinal)=>new{ordinal,name="argument"+ordinal,type=Type(type)}).ToArray(),
                variadic=symbol.Object.Routines[symbol.Entity.RoutineTypeId].Variadic,
                variadicParameter=symbol.Object.Routines[symbol.Entity.RoutineTypeId].Variadic?new{name="arguments",type="global::System.ReadOnlySpan<global::Edg.Runtime.VaArg>"}:null,
                exceptionPolicy=symbol.Object.CallableExceptionPolicy(symbol.Entity.Id),
                executionExceptionPolicy=symbol.Object.Routines[symbol.Entity.RoutineTypeId].ExceptionPolicy});
        foreach(var symbol in linker.ExternStorages.Values.Where(EmitExternal))
            emissionPlan.Report("runtimeStorageRequirements",symbol.Key,new{symbol.Storage.ExternalKey,symbol.Storage.SourceName,
                unitId=symbol.Object.UnitId,storageId=symbol.Storage.Id,generatedName=linker.StorageNames[symbol.Key],accessorName=ExternStorageName(symbol),
                accessorReference=ExternStorageReference(symbol),container="global::Edg.Runtime.LibC",csharpType=Type(symbol.Object.Type(symbol.Storage.TypeId)),
                executionType=symbol.Object.Type(symbol.Storage.TypeId),sourceTypeId=symbol.Storage.SourceTypeId,sourceSignature=symbol.Object.StorageSourceSignature(symbol.Storage),
                size=linker.StorageMinimumSize(symbol),declaredSize=symbol.Object.StorageSize(symbol.Object.Type(symbol.Storage.TypeId)),
                extentKnown=symbol.Object.StorageSize(symbol.Object.Type(symbol.Storage.TypeId))>0,alignment=linker.StorageMinimumAlignment(symbol),
                isThreadLocal=symbol.Storage.IsThreadLocal,isConst=symbol.Storage.IsConst});
    }
    internal void WriteCatalogUnit(string output,Utf8JsonWriter lifetimes)
    {
        if(emissionPlan is null || emissionUnit is null)throw new InvalidOperationException("Catalog emitter has no active unit");
        ObjectFile obj=linker.Objects[0];
        WriteExterns(output);WriteNoexceptExterns(output);WriteSourceExceptionContract(output);
        WriteCatalogStorageUnit(output);
        lifetimes.WriteStartObject();lifetimes.WriteString("unitId",obj.UnitId);lifetimes.WriteStartArray("functions");
        using var writer=new StreamWriter(Path.Combine(output,"Translated."+emissionUnit.Id.ToString("D4",CultureInfo.InvariantCulture)+"."+Names.Identifier(Path.GetFileName(obj.PrimarySource))+".cs"),false,new UTF8Encoding(false));
        writer.Write("// <auto-generated />\n#nullable enable\n// Source: "+obj.PrimarySource.Replace('\r',' ').Replace('\n',' ')+"\nnamespace "+namespaceName+";\npublic static unsafe partial class "+className+"\n{\n");
        var code=new StringBuilder();
        foreach(var record in obj.Records.Values)
        {
            if(emissionPlan.Scalar("SELECT identity_key FROM selected_records WHERE identity_key=? AND unit_id=? AND local_id=?",record.Key,emissionUnit.Id,record.TypeId) is null)continue;
            WriteRecord(code,record.Key,obj,record);
            foreach(var chunk in code.GetChunks())writer.Write(chunk.Span);
            code.Clear();
        }
        foreach(var symbol in linker.Definitions)
        {
            Function(code,symbol,lifetimes);
            foreach(var chunk in code.GetChunks())writer.Write(chunk.Span);
            code.Clear();
        }
        writer.Write("}\n");lifetimes.WriteEndArray();lifetimes.WriteEndObject();
        WriteRuntimeSupport(output,false);
    }
    private void WriteCatalogStorageUnit(string output)
    {
        if(linker.StorageDefinitions.Count==0 && !linker.ExternStorages.Values.Any(EmitExternal))return;
        using var writer=new StreamWriter(Path.Combine(output,UnitFile("Translated.Storage.generated.cs")),false,new UTF8Encoding(false));
        using var data=new StreamWriter(Path.Combine(output,UnitFile("Translated.Storage.Data.generated.cs")),false,new UTF8Encoding(false));
        string header="// <auto-generated />\n#nullable enable\nnamespace "+namespaceName+";\npublic static unsafe partial class "+className+"\n{\n";
        writer.Write(header);data.Write(header);storageDataDeclarations.Writer=data;
        var code=new StringBuilder();
        void Flush(){foreach(var chunk in code.GetChunks())writer.Write(chunk.Span);code.Clear();}
        foreach(var symbol in linker.StorageDefinitions.Concat(linker.ExternStorages.Values.Where(EmitExternal)))
        {
            code.Append("    public static ref ").Append(Type(symbol.Object.Type(symbol.Storage.TypeId))).Append(' ').Append(linker.StorageNames[symbol.Key])
                .Append(" => ref *(").Append(Type(symbol.Object.Type(symbol.Storage.TypeId))).Append("*)").Append(StorageAddress(symbol)).Append(";\n");Flush();
        }
        foreach(bool tls in new[]{false,true})
        {
            if(!linker.StorageDefinitions.Any(value=>value.Storage.IsThreadLocal==tls))continue;
            string name=StorageInitializer(emissionUnit!.Id,tls);
            code.Append("    private static void ").Append(name).Append("(byte* arena)\n    {\n");Flush();
            Initialize(code,tls,"arena",8,Flush);code.Append("    }\n");Flush();
        }
        writer.Write("}\n");data.Write("}\n");storageDataDeclarations.Writer=null;
    }
    private void WriteArray(StringBuilder builder,string array)
    {
        if (ScalarTypes.IsAddressOnlyArray(array)) return;
        string leaf = ScalarTypes.Leaf(array);
        long count = 1;
        for (string current = array; ScalarTypes.IsArray(current); current = ScalarTypes.Element(current))
            count = checked(count * ScalarTypes.ElementCount(current));
        // Only positive extents have physical CLR array fields.
        // Zero-bound and incomplete arrays are address-only views.
        bool pointers = ScalarTypes.IsPointer(leaf);
        if (pointers) builder.Append("#pragma warning disable CS9184 // Pointer elements use address-based access, not generic span conversions.\n");
        builder.Append("    [global::System.Runtime.CompilerServices.InlineArray(").Append(count)
            .Append(")]\n    public struct ").Append(ArrayName(array))
            .Append("\n    {\n        public ").Append(leaf == "f80" ? "global::System.Runtime.Intrinsics.Vector128<byte>" : Type(leaf)).Append(" First;\n    }\n");
        if (pointers) builder.Append("#pragma warning restore CS9184\n");
        builder.Append('\n');
    }
    private void WriteRecord(StringBuilder builder,string key,ObjectFile obj,RecordType record)
    {
        builder.Append("    [global::System.Runtime.InteropServices.StructLayout(global::System.Runtime.InteropServices.LayoutKind.Explicit, Size = ")
            .Append(Math.Max(1, record.Size)).Append(", Pack = ").Append(ObjectFile.ClrRecordPack(record)).Append(")]\n    public struct ").Append(recordNames[key]).Append("\n    {\n");
        var backingNames = new Names();
        foreach (RecordField field in obj.RecordFields(record.TypeId)) backingNames.Reserve(fieldNames[(key, field.Ordinal)]);
        if (record.Alignment > 1 && record.RepresentationKind != "subobject")
            builder.Append("        [global::System.Runtime.InteropServices.FieldOffset(0)] private ")
                .Append(record.Alignment >= 16 ? "global::System.Runtime.Intrinsics.Vector128<byte>" : record.Alignment == 8 ? "long" : record.Alignment == 4 ? "int" : "short").Append(' ')
                .Append(backingNames.Allocate("__alignment", "alignment")).Append(";\n");
        foreach (RecordField field in obj.RecordFields(record.TypeId))
            if (ScalarTypes.IsAddressOnlyArray(obj.Type(field.TypeId)))
                builder.Append(ScalarTypes.IsIncompleteArray(obj.Type(field.TypeId)) ? "        // Flexible tail: " : "        // Zero-byte array member: ")
                    .Append(Type(ScalarTypes.Leaf(obj.Type(field.TypeId)))).Append(' ').Append(fieldNames[(key, field.Ordinal)])
                    .Append(" at byte offset ").Append(field.ByteOffset).Append("; original extent ").Append(obj.Type(field.TypeId)).Append(".\n");
            else if (field.BitWidth is not null) WriteBitfield(builder, obj, field, fieldNames[(key, field.Ordinal)], backingNames);
            else builder.Append(field.FieldRole == "source" ? "" : "        // Compiler-generated " + field.FieldRole + " field.\n").Append("        [global::System.Runtime.InteropServices.FieldOffset(").Append(field.ByteOffset).Append(")]\n        public ")
                .Append(IsVolatileField(obj, field) ? "volatile " : "").Append(Type(obj.Type(field.TypeId))).Append(' ').Append(fieldNames[(key, field.Ordinal)]).Append(";\n");
        builder.Append("    }\n\n");
    }

