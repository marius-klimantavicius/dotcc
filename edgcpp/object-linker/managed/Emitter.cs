using System.Text;
using System.Text.Json;

namespace DotObj;

internal sealed partial class Emitter(Linker linker, string namespaceOption, string classOption)
{
    private readonly string namespaceName = Names.Namespace(namespaceOption);
    private readonly string className = Names.OptionIdentifier(classOption);
    private readonly Names generatedMembers = new();
    private readonly Dictionary<string, string> arrayNames = new(StringComparer.Ordinal);
    private readonly Dictionary<string, string> recordNames = new(StringComparer.Ordinal);
    private readonly Dictionary<(string Record, long Ordinal), string> fieldNames = [];
    private string Type(string kind) => ScalarTypes.IsArray(kind)
        ? "global::" + namespaceName + "." + className + "." + arrayNames[kind]
        : ScalarTypes.IsRecord(kind) ? "global::" + namespaceName + "." + className + "." + recordNames[kind]
        : RoutineTypes.IsFunctionPointer(kind) ? FunctionPointerType(ScalarTypes.Pointee(kind))
        : ScalarTypes.IsPointer(kind) ? Type(ScalarTypes.Pointee(kind)) + "*" : ScalarTypes.CSharp(kind);
    private string FunctionPointerType(string kind)
    {
        var signature = RoutineTypes.Signature(kind);
        return "delegate* managed<" + string.Join(", ", signature.Parameters.Select(Type).Concat(signature.Variadic ? ["global::System.ReadOnlySpan<global::Edg.Runtime.VaArg>"] : []).Append(Type(signature.Result))) + ">";
    }

    public void Write(string output, string? entryKey)
    {
        Symbol? entry = entryKey is null ? null : linker.Entry(entryKey);
        if (Directory.Exists(output) && Directory.EnumerateFileSystemEntries(output).Any())
            throw new IOException("Output directory must be empty; existing artifacts are never overwritten");
        Directory.CreateDirectory(output);
        generatedMembers.Reserve(className);
        foreach (string name in linker.Names.Values) generatedMembers.Reserve(name);
        foreach (string name in linker.StorageNames.Values) generatedMembers.Reserve(name);
        foreach (var (key, definition) in linker.Records.OrderBy(pair => pair.Key, StringComparer.Ordinal))
        {
            string name = generatedMembers.Allocate(definition.Record.SourceName, "Record");
            // Contextual words may be ordinary method names, but record type
            // declarations need an escaped identifier in every C# context.
            recordNames.Add(key, Names.OptionIdentifier(name.TrimStart('@')));
            var fields = new Names();
            fields.Reserve(name);
            foreach (RecordField field in definition.Object.RecordFields(definition.Record.TypeId))
                fieldNames.Add((key, field.Ordinal), fields.Allocate(field.SourceName, "field_" + field.Ordinal));
        }
        foreach (string array in linker.Objects.SelectMany(obj => obj.Types.Values).Where(ScalarTypes.IsArray).Distinct().Order(StringComparer.Ordinal))
            arrayNames.Add(array, generatedMembers.Allocate(ScalarTypes.ArrayName(array), "__DotObjArray"));
        WriteStorage(output);
        WriteExterns(output);
        WriteNoexceptExterns(output);
        using var lifetimeStream = File.Create(Path.Combine(output, "lifetime-map.json"));
        using var lifetimeWriter = new Utf8JsonWriter(lifetimeStream, new JsonWriterOptions { Indented = true });
        lifetimeWriter.WriteStartObject();
        lifetimeWriter.WriteNumber("formatVersion", 1);
        lifetimeWriter.WriteString("profile", "scalar-control-v12");
        lifetimeWriter.WriteString("capture", "lexical-cleanup-activations");
        lifetimeWriter.WriteBoolean("lexicalCleanups", true);
        lifetimeWriter.WriteBoolean("lifetimes", false);
        lifetimeWriter.WriteStartArray("objects");
        foreach (ObjectFile obj in linker.Objects)
        {
            lifetimeWriter.WriteStartObject();
            lifetimeWriter.WriteString("unitId", obj.UnitId);
            lifetimeWriter.WriteStartArray("functions");
            var builder = new StringBuilder("// <auto-generated />\n#nullable enable\n");
            builder.Append("// Source: ").Append(obj.PrimarySource.Replace('\r', ' ').Replace('\n', ' ')).Append('\n');
            builder.Append("namespace ").Append(namespaceName).Append(";\n\npublic static unsafe partial class ").Append(className).Append("\n{\n");
            if (ReferenceEquals(obj, linker.Objects[0]) && linker.StorageDefinitions.Count == 0 && linker.ExternStorages.Count == 0 && linker.Objects.Any(input => input.Types.Values.Any(ScalarTypes.IsPointer)))
            {
                // The object's target ABI fixes pointer width. Do not execute its
                // layout/arithmetic contracts in an incompatible 32-bit process.
                builder.Append("    static ").Append(className).Append("()\n    {\n")
                    .Append("        if (global::System.IntPtr.Size != 8)\n")
                    .Append("            throw new global::System.PlatformNotSupportedException(\"This translated object requires a 64-bit process.\");\n")
                    .Append("    }\n\n");
            }
            if (ReferenceEquals(obj, linker.Objects[0]))
            {
                foreach (string array in linker.Objects.SelectMany(input => input.Types.Values).Where(ScalarTypes.IsArray).Distinct().Order(StringComparer.Ordinal))
                {
                    string leaf = ScalarTypes.Leaf(array);
                    long count = 1;
                    for (string current = array; ScalarTypes.IsArray(current); current = ScalarTypes.Element(current))
                        count = checked(count * ScalarTypes.ElementCount(current));
                    // Incomplete array views are address-only. Complete arrays
                    // carry real repeated CLR fields, so record copies preserve
                    // every element rather than relying on value-type padding.
                    bool pointers = ScalarTypes.IsPointer(leaf);
                    if (pointers) builder.Append("#pragma warning disable CS9184 // Pointer elements use address-based access, not generic span conversions.\n");
                    builder.Append("    [global::System.Runtime.CompilerServices.InlineArray(").Append(Math.Max(1, count))
                        .Append(")]\n    public struct ").Append(arrayNames[array])
                        .Append("\n    {\n        public ").Append(Type(leaf)).Append(" First;\n    }\n");
                    if (pointers) builder.Append("#pragma warning restore CS9184\n");
                    builder.Append('\n');
                }
                foreach (var (key, definition) in linker.Records.OrderBy(pair => pair.Key, StringComparer.Ordinal))
                {
                    RecordType record = definition.Record;
                    builder.Append("    [global::System.Runtime.InteropServices.StructLayout(global::System.Runtime.InteropServices.LayoutKind.Explicit, Size = ")
                        .Append(Math.Max(1, record.Size)).Append(", Pack = ").Append(Math.Max(1, record.Alignment)).Append(")]\n    public struct ").Append(recordNames[key]).Append("\n    {\n");
                    var backingNames = new Names();
                    foreach (RecordField field in definition.Object.RecordFields(record.TypeId)) backingNames.Reserve(fieldNames[(key, field.Ordinal)]);
                    if (record.Alignment > 1)
                        builder.Append("        [global::System.Runtime.InteropServices.FieldOffset(0)] private ")
                            .Append(record.Alignment == 8 ? "long" : record.Alignment == 4 ? "int" : "short").Append(' ')
                            .Append(backingNames.Allocate("__alignment", "alignment")).Append(";\n");
                    foreach (RecordField field in definition.Object.RecordFields(record.TypeId))
                        if (ScalarTypes.IsArray(definition.Object.Type(field.TypeId)) && ScalarTypes.ElementCount(definition.Object.Type(field.TypeId)) == 0)
                            builder.Append("        // Flexible tail: ").Append(Type(ScalarTypes.Element(definition.Object.Type(field.TypeId)))).Append(' ').Append(fieldNames[(key, field.Ordinal)]).Append("[] at byte offset ").Append(field.ByteOffset).Append(".\n");
                        else if (field.BitWidth is not null) WriteBitfield(builder, definition.Object, field, fieldNames[(key, field.Ordinal)], backingNames);
                        else builder.Append("        [global::System.Runtime.InteropServices.FieldOffset(").Append(field.ByteOffset).Append(")]\n        public ")
                            .Append(IsVolatileField(definition.Object, field) ? "volatile " : "").Append(Type(definition.Object.Type(field.TypeId))).Append(' ').Append(fieldNames[(key, field.Ordinal)]).Append(";\n");
                    builder.Append("    }\n\n");
                }
            }
            foreach (Symbol symbol in linker.Definitions.Where(symbol => ReferenceEquals(symbol.Object, obj)))
                Function(builder, symbol, lifetimeWriter);
            lifetimeWriter.WriteEndArray();
            lifetimeWriter.WriteEndObject();
            builder.Append("}\n");
            string file = $"Translated.{linker.Objects.ToList().IndexOf(obj):D4}.{Names.Identifier(Path.GetFileName(obj.PrimarySource))}.cs";
            File.WriteAllText(Path.Combine(output, file), builder.ToString(), new UTF8Encoding(false));
        }
        lifetimeWriter.WriteEndArray();
        lifetimeWriter.WriteEndObject();
        WriteRuntimeSupport(output);
        if (entry is not null)
        {
            string call = $"global::{namespaceName}.{className}.{linker.Names[entry.Key]}()";
            string body = entry.Object.Type(entry.Entity.ReturnTypeId) == "void" ? call + "; return 0;" : "return " + call + ";";
            File.WriteAllText(Path.Combine(output, "Entry.generated.cs"),
                "// <auto-generated />\ninternal static class __DotObjEntry\n{\n    public static int Main() { " + body + " }\n}\n");
        }
        string project = """
            <Project Sdk="Microsoft.NET.Sdk">
              <PropertyGroup>
                <TargetFramework>net10.0</TargetFramework>
                <AllowUnsafeBlocks>true</AllowUnsafeBlocks>
                <Nullable>enable</Nullable>
                <ImplicitUsings>disable</ImplicitUsings>
                <CheckForOverflowUnderflow>false</CheckForOverflowUnderflow>
                <IsAotCompatible>true</IsAotCompatible>
                <Deterministic>true</Deterministic>
            """ + "\n    <OutputType>" + (entry is null ? "Library" : "Exe") + "</OutputType>\n" +
            (entry is null ? "" : "    <StartupObject>__DotObjEntry</StartupObject>\n") + "  </PropertyGroup>\n</Project>\n";
        File.WriteAllText(Path.Combine(output, "Translated.csproj"), project);
        using (var stream = File.Create(Path.Combine(output, "source-map.json")))
        using (var writer = new Utf8JsonWriter(stream, new JsonWriterOptions { Indented = true }))
        {
            writer.WriteStartObject();
            writer.WriteNumber("formatVersion", 1);
            writer.WriteString("profile", "scalar-control-v12");
            writer.WriteString("capture", "scalar-declarations-before-lowering");
            writer.WriteBoolean("prelowerSource", false);
            writer.WriteStartArray("objects");
            foreach (ObjectFile obj in linker.Objects) obj.WriteSourceMap(writer);
            writer.WriteEndArray();
            writer.WriteEndObject();
        }
        using (var stream = File.Create(Path.Combine(output, "macro-map.json")))
        using (var writer = new Utf8JsonWriter(stream, new JsonWriterOptions { Indented = true }))
        {
            writer.WriteStartObject();
            writer.WriteNumber("formatVersion", 1);
            writer.WriteString("profile", "scalar-control-v12");
            writer.WriteString("capture", "preprocessor-definition-events");
            writer.WriteBoolean("macroDefinitions", true);
            writer.WriteBoolean("macros", false);
            writer.WriteStartArray("objects");
            foreach (ObjectFile obj in linker.Objects) obj.WriteMacroMap(writer);
            writer.WriteEndArray();
            writer.WriteEndObject();
        }
        File.WriteAllText(Path.Combine(output, "link-report.json"), JsonSerializer.Serialize(new
        {
            formatVersion = 1, profile = "scalar-control-v12", status = "linked",
            targetAbi = "portable-lp64-binary80-v2", runtimeAbi = "dotobj-scalar-v1",
            capabilities = new { sourceDeclarations = true, macroDefinitions = true, lexicalCleanups = true, prelowerSource = false, macros = false, lifetimes = false },
            limitations = new[] { "Project C profile with named records/unions/bitfields, static/TLS storage, function pointers, variadics, volatile operations and GNU lexical cleanup; aggregate values require complete nonvolatile POD layouts; variable-length arrays, source EH and C++ RAII are not supported; runtime extern bodies must be supplied separately", "Pre-lowering scalar/pointer/array/record declaration/type provenance and explicit lexical cleanup activations only; no complete source expression/statement view, macro expansion history or general C++ lifetime capture" },
            @namespace = namespaceOption, @class = classOption, sourceMap = "source-map.json", macroMap = "macro-map.json", lifetimeMap = "lifetime-map.json",
            runtimeRequirements = linker.Externs.Values.OrderBy(symbol => symbol.Key, StringComparer.Ordinal).Select(symbol => new
            {
                symbol.Entity.ExternalKey, symbol.Entity.SourceName, symbol.Signature,
                unitId = symbol.Object.UnitId, entityId = symbol.Entity.Id,
                generatedName = ExternName(symbol), functionReference = ExternProviderReference(symbol), callReference = FunctionReference(symbol),
                container = SharedExtern(symbol) ? "global::Edg.Runtime.LibC" : Owner,
                returnType = Type(symbol.Object.Type(symbol.Entity.ReturnTypeId)),
                parameters = symbol.Object.Parameters.GetValueOrDefault(symbol.Entity.Id, []).Select((type, ordinal) => new
                    { ordinal, name = "argument" + ordinal, type = Type(type) }),
                variadic = symbol.Object.Routines[symbol.Entity.RoutineTypeId].Variadic,
                variadicParameter = symbol.Object.Routines[symbol.Entity.RoutineTypeId].Variadic
                    ? new { name = "arguments", type = "global::System.ReadOnlySpan<global::Edg.Runtime.VaArg>" } : null,
                exceptionPolicy = symbol.Object.Routines[symbol.Entity.RoutineTypeId].ExceptionPolicy,
            }),
            runtimeStorageRequirements = linker.ExternStorages.Values.OrderBy(symbol => symbol.Key, StringComparer.Ordinal).Select(symbol => new
            {
                symbol.Storage.ExternalKey, symbol.Storage.SourceName,
                unitId = symbol.Object.UnitId, storageId = symbol.Storage.Id,
                generatedName = linker.StorageNames[symbol.Key], accessorName = ExternStorageName(symbol), accessorReference = ExternStorageReference(symbol),
                container = "global::Edg.Runtime.LibC", csharpType = Type(symbol.Object.Type(symbol.Storage.TypeId)),
                executionType = symbol.Object.Type(symbol.Storage.TypeId), sourceTypeId = symbol.Storage.SourceTypeId,
                sourceSignature = symbol.Object.StorageSourceSignature(symbol.Storage),
                size = symbol.Object.StorageSize(symbol.Object.Type(symbol.Storage.TypeId)), alignment = symbol.Storage.Alignment,
                isThreadLocal = symbol.Storage.IsThreadLocal, isConst = symbol.Storage.IsConst,
            }),
            records = linker.Records.OrderBy(pair => pair.Key, StringComparer.Ordinal).Select(pair => new
            {
                identityKey = pair.Value.Record.IdentityKey, sourceName = pair.Value.Record.SourceName,
                generatedType = Type(pair.Key), unitId = pair.Value.Object.UnitId, typeId = pair.Value.Record.TypeId,
                size = pair.Value.Record.Size, alignment = pair.Value.Record.Alignment,
            }),
            objects = linker.Objects.Select(obj => new { path = obj.Path, unitId = obj.UnitId, primarySource = obj.PrimarySource, semanticDigest = obj.Digest }),
            symbols = linker.Definitions.Select(symbol => new { unitId = symbol.Object.UnitId, entityId = symbol.Entity.Id,
                externalKey = symbol.Entity.ExternalKey, sourceName = symbol.Entity.SourceName, generatedName = linker.Names[symbol.Key], signature = symbol.Signature })
        }, new JsonSerializerOptions { WriteIndented = true }) + "\n");
    }

    private void Function(StringBuilder output, Symbol symbol, Utf8JsonWriter lifetimeWriter)
    {
        ObjectFile obj = symbol.Object;
        Entity function = symbol.Entity;
        FunctionBody body = obj.ReadBody(function.Id);
        if (body.Nodes.Values.Any(node => node.Kind == "register-cleanup"))
        {
            lifetimeWriter.WriteStartObject();
            lifetimeWriter.WriteNumber("entityId", function.Id);
            lifetimeWriter.WriteStartArray("regions");
            foreach (Node block in body.Nodes.Values.Where(node => node.Kind == "block").OrderBy(node => node.Id))
            {
                Edge[] statements = body.Children(block.Id, "statement").ToArray();
                foreach (Edge edge in statements)
                {
                    Node activation = body.Nodes[edge.ChildId];
                    if (activation.Kind != "register-cleanup") continue;
                    lifetimeWriter.WriteStartObject();
                    lifetimeWriter.WriteNumber("activationNodeId", activation.Id);
                    lifetimeWriter.WriteNumber("blockNodeId", block.Id);
                    lifetimeWriter.WriteNumber("bindingId", activation.BindingId!.Value);
                    lifetimeWriter.WriteNumber("callbackEntityId", activation.EntityId!.Value);
                    lifetimeWriter.WriteNumber("activationOrdinal", edge.Ordinal);
                    lifetimeWriter.WriteNumber("protectedSuffixStartOrdinal", edge.Ordinal + 1);
                    lifetimeWriter.WriteNumber("protectedSuffixEndExclusiveOrdinal", statements.Length);
                    lifetimeWriter.WriteEndObject();
                }
            }
            lifetimeWriter.WriteEndArray();
            lifetimeWriter.WriteEndObject();
        }
        var allocator = new Names();
        allocator.Reserve("_"); // Keep discard assignments distinct from source bindings named _.
        var bindingNames = body.Bindings.Values.OrderBy(binding => binding.Kind == "parameter" ? 0 : 1)
            .ThenBy(binding => binding.Ordinal ?? binding.Id)
            .ToDictionary(binding => binding.Id, binding => allocator.Allocate(binding.SourceName, "local_" + binding.Id));
        var initializers = new StringBuilder();
        var labelNames = body.Nodes.Values.Where(node => node.Kind == "label").OrderBy(node => node.Id)
            .ToDictionary(node => node.Id, node => allocator.Allocate(node.ConstantText!, "label_" + node.Id));
        bool variadicFunction = obj.Routines[function.RoutineTypeId].Variadic;
        bool terminate = obj.Routines[function.RoutineTypeId].ExceptionPolicy == "terminate" &&
            body.Nodes.Values.Any(node => node.Kind is not ("block" or "return"));
        int bodyIndent = terminate ? 3 : 2;
        string vaArguments = allocator.Allocate("__va_arguments", "va_arguments"), vaInput = allocator.Allocate("__va_input", "va_input");
        string vaPack = allocator.Allocate("__va_pack", "va_pack"), vaBytes = allocator.Allocate("__va_bytes", "va_bytes"), vaWorkspace = allocator.Allocate("__va_workspace", "va_workspace");
        string NodeType(Node node) => obj.Type(node.TypeId!.Value);
        string Truth(Node node)
        {
            if (node.Kind == "binary" && node.Operator is "eq" or "ne" or "lt" or "le" or "gt" or "ge")
                return Comparison(node);
            if (node.Kind == "binary" && node.Operator is "and" or "or")
                return "(" + Truth(body.Child(node.Id, "left")) + (node.Operator == "and" ? " && " : " || ") + Truth(body.Child(node.Id, "right")) + ")";
            if (node.Kind == "unary" && node.Operator == "not") return "!(" + Truth(body.Child(node.Id, "operand")) + ")";
            string expression = Expression(node);
            return NodeType(node) == "bool" ? expression : "(" + expression + (ScalarTypes.IsPointer(NodeType(node)) ? " != null)" : " != 0)");
        }
        string Comparison(Node node)
        {
            string op = node.Operator switch { "eq" => "==", "ne" => "!=", "lt" => "<", "le" => "<=", "gt" => ">", "ge" => ">=", _ => throw new InvalidDataException("Unsupported comparison") };
            return "(" + Expression(body.Child(node.Id, "left")) + " " + op + " " + Expression(body.Child(node.Id, "right")) + ")";
        }
        string Boolean(string expression, Node node) => NodeType(node) switch
        { "bool" => expression, "i32" => "(" + expression + " ? 1 : 0)", "u8" => "((byte)(" + expression + " ? 1 : 0))", _ => throw new InvalidDataException("Invalid boolean result") };
        string FromBoolean(string expression, string type) => type == "i32"
            ? "(" + expression + " ? 1 : 0)" : "((" + Type(type) + ")(" + expression + " ? 1 : 0))";
        string Expression(Node node)
        {
            Node Child(string role) => body.Child(node.Id, role);
            string Operand(string role) => Expression(Child(role));
            switch (node.Kind)
            {
                case "intrinsic": return Intrinsic(obj, node, body.Children(node.Id, "argument").Select(edge => body.Nodes[edge.ChildId]).ToArray(), Expression);
                case "sequence":
                    Node[] items = body.Children(node.Id, "item").Select(edge => body.Nodes[edge.ChildId]).ToArray();
                    string tail = Expression(items[^1]);
                    for (int index = items.Length - 2; index >= 0; index--)
                    {
                        Node item = items[index];
                        while (item.Kind == "convert" && NodeType(item) == "void") item = body.Child(item.Id, "operand");
                        if (NodeType(item) == "void") throw new InvalidDataException("Void-prefix comma expression requires statement expansion");
                        string head = Expression(item); if (ScalarTypes.IsPointer(NodeType(item))) head = "((nuint)" + head + ")";
                        tail = "(" + head + " switch { _ => " + tail + " })";
                    }
                    return tail;
                case "va-start": return "global::Edg.Runtime.VaList.Start(" + Operand("operand") + ", &" + vaArguments + ")";
                case "va-copy": return "global::Edg.Runtime.VaList.Copy(" + Operand("operand") + ", " + Operand("source") + ")";
                case "va-end": return "global::Edg.Runtime.VaList.EndList(" + Operand("operand") + ")";
                case "va-arg": return "(*(" + Type(NodeType(node)) + "*)global::Edg.Runtime.VaList.Take(" + Operand("operand") + ", " + obj.StorageSize(NodeType(node)) + "UL, " + obj.StorageAlignment(NodeType(node)) + "UL))";
                case "volatile-place": return DirectVolatile(node) ? Operand("operand") : VolatileRead(NodeType(node), Address(Child("operand")), Operand("operand"));
                case "constant":
                    return ScalarTypes.IsPointer(NodeType(node)) ? "((" + Type(NodeType(node)) + ")null)" : ScalarTypes.Literal(NodeType(node), node.ConstantText!);
                case "binding": return bindingNames[node.BindingId!.Value];
                case "storage": return StorageReference(linker.ResolveStorage(obj, node.StorageId!.Value));
                case "storage-address":
                    return "((" + Type(NodeType(node)) + ")(" + StorageAddress(linker.ResolveStorage(obj, node.StorageId!.Value), long.Parse(node.ConstantText!, System.Globalization.CultureInfo.InvariantCulture)) + "))";
                case "function-address":
                    return "((" + Type(NodeType(node)) + ")&" + FunctionReference(linker.Resolve(obj, node.EntityId!.Value)) + ")";
                case "indirect-call":
                    return (Child("operand").Kind is "binding" or "storage" or "member" ? Operand("operand") : "(" + Operand("operand") + ")") + "(" + Arguments(node, ScalarTypes.Pointee(NodeType(Child("operand")))) + ")";
                case "default-value": return "default(" + Type(NodeType(node)) + ")";
                case "member":
                    RecordField field = obj.Fields[node.FieldId!.Value];
                    string fieldName = fieldNames[(obj.Type(field.RecordTypeId), field.Ordinal)];
                    Node owner = Child("operand");
                    if (owner.Kind == "dereference") return Expression(body.Child(owner.Id, "operand")) + "->" + fieldName;
                    return Expression(owner) + "." + fieldName;
                case "array-decay": return "((" + Type(NodeType(node)) + ")" + Address(Child("operand")) + ")";
                case "address": return Address(Child("operand"));
                case "dereference":
                    Node pointer = Child("operand");
                    if (pointer.Kind == "binary" && pointer.Operator == "pointer-add" &&
                        ScalarTypes.IsPointer(NodeType(body.Child(pointer.Id, "left"))))
                        return "(" + Expression(body.Child(pointer.Id, "left")) + ")[" + Expression(body.Child(pointer.Id, "right")) + "]";
                    return "(*" + Operand("operand") + ")";
                case "call":
                    Symbol target = linker.Resolve(obj, node.EntityId!.Value);
                    return FunctionReference(target) + "(" + Arguments(node, target.Object.EntityRoutine(target.Entity.Id)) + ")";
                case "compound-assign": return "(" + Compound(node) + ")";
                case "assign":
                    if (Child("target").Kind == "member" && obj.Fields[Child("target").FieldId!.Value].BitWidth is not null)
                        return BitfieldResult(obj, obj.Fields[Child("target").FieldId!.Value], "(" + Operand("target") + " = " + Operand("value") + ")");
                    return Child("target").Kind == "volatile-place" && !DirectVolatile(Child("target"))
                    ? VolatileOperation(NodeType(node), "assign", Address(Child("target")), Operand("value")) : "(" + Operand("target") + " = " + Operand("value") + ")";
                case "mutate": return "(" + Mutation(node) + ")";
                case "convert":
                    if (NodeType(node) == NodeType(Child("operand"))) return Operand("operand");
                    if (NodeType(node) == "bool") return Truth(Child("operand"));
                    if (NodeType(Child("operand")) == "bool") return FromBoolean(Operand("operand"), NodeType(node));
                    return "unchecked((" + Type(NodeType(node)) + ")(" + Operand("operand") + "))";
                case "unary":
                    if (node.Operator == "not") return Boolean("!(" + Truth(Child("operand")) + ")", node);
                    if (node.Operator == "neg")
                        return NodeType(node) is "u32" or "u64"
                            ? "unchecked(" + (NodeType(node) == "u32" ? "0U" : "0UL") + " - " + Operand("operand") + ")"
                            : "unchecked(-" + Operand("operand") + ")";
                    return "(" + (node.Operator == "bit-not" ? "~" : "+") + Operand("operand") + ")";
                case "conditional":
                    return "(" + Truth(Child("condition")) + " ? " + Operand("then") + " : " + Operand("else") + ")";
                case "binary":
                    if (node.Operator is "and" or "or")
                        return Boolean("(" + Truth(Child("left")) + (node.Operator == "and" ? " && " : " || ") + Truth(Child("right")) + ")", node);
                    string op = node.Operator switch
                    { "add" or "pointer-add" => "+", "sub" or "pointer-subtract" or "pointer-difference" => "-", "mul" => "*", "div" => "/", "rem" => "%", "eq" => "==", "ne" => "!=", "lt" => "<", "le" => "<=", "gt" => ">", "ge" => ">=", "bit-and" => "&", "bit-or" => "|", "bit-xor" => "^", "shl" => "<<", "shr" => ">>", _ => throw new InvalidDataException("Unsupported operator") };
                    string right = node.Operator is "shl" or "shr" && NodeType(Child("right")) != "i32"
                        ? "unchecked((int)(" + Operand("right") + "))" : Operand("right");
                    string expression = "(" + Operand("left") + " " + op + " " + right + ")";
                    if (node.Operator is "eq" or "ne" or "lt" or "le" or "gt" or "ge") return Boolean(expression, node);
                    return node.Operator is "add" or "sub" or "mul" ? "unchecked" + expression : expression;
                default: throw new InvalidDataException("Unsupported expression " + node.Kind);
            }
        }
        string Arguments(Node node, string routine)
        {
            var signature = RoutineTypes.Signature(routine);
            Node[] values = body.Children(node.Id, "argument").Select(edge => body.Nodes[edge.ChildId]).ToArray();
            var arguments = values.Take(signature.Parameters.Length).Select(Expression).ToList();
            if (signature.Variadic)
            {
                string Argument(Node value) => ScalarTypes.IsPointer(NodeType(value))
                    ? "global::Edg.Runtime.VaArg.FromPointer((void*)" + Expression(value) + ")"
                    : "global::Edg.Runtime.VaArg.From(" + Expression(value) + ", " + obj.StorageSize(NodeType(value)) + ", " + obj.StorageAlignment(NodeType(value)) + ")";
                arguments.Add("[" + string.Join(", ", values.Skip(signature.Parameters.Length).Select(Argument)) + "]");
            }
            return string.Join(", ", arguments);
        }
        bool DirectVolatile(Node node) => node.Kind == "volatile-place" &&
            body.Child(node.Id, "operand") is { Kind: "member", FieldId: not null } fieldNode &&
            IsVolatileField(obj, obj.Fields[fieldNode.FieldId.Value]);
        string Address(Node node)
        {
            if (node.Kind == "volatile-place") return Address(body.Child(node.Id, "operand"));
            if (node.Kind == "storage") return "((" + Type(NodeType(node)) + "*)" + StorageAddress(linker.ResolveStorage(obj, node.StorageId!.Value)) + ")";
            if (node.Kind == "dereference") return Expression(body.Child(node.Id, "operand"));
            if (node.Kind == "member")
            {
                RecordField field = obj.Fields[node.FieldId!.Value];
                if (ScalarTypes.IsArray(obj.Type(field.TypeId)) && ScalarTypes.ElementCount(obj.Type(field.TypeId)) == 0)
                    return "((" + Type(obj.Type(field.TypeId)) + "*)((byte*)" + Address(body.Child(node.Id, "operand")) + " + " + field.ByteOffset + " /* " + field.SourceName + " */))";
                return "(&(" + Address(body.Child(node.Id, "operand")) + ")->" + fieldNames[(obj.Type(field.RecordTypeId), field.Ordinal)] + ")";
            }
            return "(&" + Expression(node) + ")";
        }
        string Mutation(Node node, bool valueNeeded = true)
        {
            Node location = body.Child(node.Id, "operand");
            if (location.Kind == "volatile-place" && !DirectVolatile(location)) return VolatileOperation(NodeType(node), node.Operator!, Address(location), null);
            if (valueNeeded && location.Kind == "member" && obj.Fields[location.FieldId!.Value].BitWidth is not null && node.Operator is "pre-inc" or "pre-dec")
                return BitfieldResult(obj, obj.Fields[location.FieldId!.Value], "(" + (node.Operator == "pre-inc" ? "++" : "--") + Expression(location) + ")");
            string operand = Expression(location);
            string operation = node.Operator is "pre-inc" or "post-inc" ? "++" : "--";
            return node.Operator is "pre-inc" or "pre-dec" ? operation + operand : operand + operation;
        }
        string Compound(Node node, bool valueNeeded = true)
        {
            string op = node.Operator switch { "add" or "pointer-add" => "+", "sub" or "pointer-subtract" => "-", "mul" => "*", "div" => "/", "rem" => "%", "bit-and" => "&", "bit-or" => "|", "bit-xor" => "^", "shl" => "<<", "shr" => ">>", _ => throw new InvalidDataException("Invalid compound operator") };
            string value = Expression(body.Child(node.Id, "value")), valueType = NodeType(body.Child(node.Id, "value"));
            if (node.Operator is "shl" or "shr") { value = "unchecked((int)(" + value + "))"; valueType = "i32"; }
            Node target = body.Child(node.Id, "target");
            if (target.Kind == "volatile-place" && (!DirectVolatile(target) || CompoundPromotionDiffers(NodeType(node), valueType, op))) return VolatileOperation(NodeType(node), op + "=", Address(target), value, valueType);
            bool promotionDiffers = CompoundPromotionDiffers(NodeType(node), valueType, op);
            if (target.Kind == "member" && obj.Fields[target.FieldId!.Value].BitWidth is not null && (valueNeeded || promotionDiffers))
                return promotionDiffers
                    ? BitfieldOperation(obj, obj.Fields[target.FieldId!.Value], op + "=", Address(body.Child(target.Id, "operand")), value, valueType)
                    : BitfieldResult(obj, obj.Fields[target.FieldId!.Value], "(" + Expression(target) + " " + op + "= " + value + ")");
            if (promotionDiffers) return CompoundOperation(NodeType(node), valueType, op, Address(target), value);
            return Expression(target) + " " + op + "= " + value;
        }
        string StatementExpression(Node node) => node.Kind switch
        {
            "assign" => body.Child(node.Id, "target").Kind == "volatile-place" && !DirectVolatile(body.Child(node.Id, "target")) ? VolatileWrite(NodeType(node), Address(body.Child(node.Id, "target")), Expression(body.Child(node.Id, "value")), Expression(body.Child(body.Child(node.Id, "target").Id, "operand"))) : Expression(body.Child(node.Id, "target")) + " = " + Expression(body.Child(node.Id, "value")),
            "mutate" => Mutation(node, false),
            "compound-assign" => Compound(node, false),
            "call" or "indirect-call" or "va-start" or "va-copy" or "va-end" => Expression(node),
            "intrinsic" when node.Operator == "unreachable" => Expression(node),
            "convert" when NodeType(node) == "void" => StatementExpression(body.Child(node.Id, "operand")),
            _ => "_ = " + Expression(node)
        };
        void Line(int indent, string text) => output.Append(' ', indent * 4).Append(text).Append('\n');
        void BlockContents(Node block, int indent)
        {
            // Registration starts a protected suffix only after initialization
            // succeeded. Each suffix nests inside the previous one, giving
            // reverse cleanup on normal exit, return, break, continue or throw.
            // The object stores semantic activation, not pre-rendered C# or
            // duplicated normal-exit cleanup calls.
            var cleanups = new Stack<Node>();
            foreach (Edge edge in body.Children(block.Id, "statement"))
            {
                Node statement = body.Nodes[edge.ChildId];
                if (statement.Kind != "register-cleanup") { Statement(statement, indent); continue; }
                cleanups.Push(statement);
                Line(indent, "try");
                Line(indent++, "{");
            }
            while (cleanups.TryPop(out Node? cleanup))
            {
                Line(--indent, "}");
                Line(indent, "finally");
                Line(indent, "{");
                Symbol callback = linker.Resolve(obj, cleanup.EntityId!.Value);
                Line(indent + 1, FunctionReference(callback) +
                    "(&" + bindingNames[cleanup.BindingId!.Value] + ");");
                Line(indent, "}");
            }
        }
        void ControlBody(Node node, int indent)
        {
            if (node.Kind == "block") Statement(node, indent);
            else { Line(indent, "{"); Statement(node, indent + 1); Line(indent, "}"); }
        }
        void Switch(Node node, int indent)
        {
            Node selector = body.Child(node.Id, "condition");
            Node switchBody = body.Child(node.Id, "body");
            Node[] items = body.Children(switchBody.Id, "statement").Select(edge => body.Nodes[edge.ChildId]).ToArray();
            Node[] declarations = items.TakeWhile(item => item.Kind == "declare").ToArray();
            // The object block owns locals across case sections. C# cannot put
            // declarations before its first case, so retain that scope outside
            // the switch; source initializer assignments stay at their positions.
            if (declarations.Length != 0)
            {
                Line(indent, "{");
                indent++;
                foreach (Node declaration in declarations) Statement(declaration, indent);
            }
            string Label(Node label)
            {
                if (!body.Children(label.Id, "value").Any()) return "default";
                Node value = body.Child(label.Id, "value");
                return "case " + ScalarTypes.Literal(NodeType(selector),
                    ScalarTypes.SwitchConstant(NodeType(value), value.ConstantText!, NodeType(selector)));
            }
            Line(indent, "switch (" + Expression(selector) + ")");
            Line(indent, "{");
            int index = declarations.Length;
            while (index < items.Length)
            {
                // Adjacent labels share a section, preserving source grouping.
                do { Line(indent + 1, Label(items[index++]) + ":"); }
                while (index < items.Length && items[index].Kind == "case");
                bool fallsThrough = true;
                while (index < items.Length && items[index].Kind != "case")
                {
                    Node statement = items[index++];
                    Statement(statement, indent + 2);
                    fallsThrough &= FallsThrough(statement);
                }
                if (fallsThrough)
                    Line(indent + 2, index < items.Length ? "goto " + Label(items[index]) + ";" : "break;");
            }
            Line(indent, "}");
            if (declarations.Length != 0) Line(indent - 1, "}");
        }
        void ArrayInitialize(Node node, int indent)
        {
            Node target = body.Child(node.Id, "target");
            string array = NodeType(target), leaf = ScalarTypes.Leaf(array);
            string name = Expression(target);
            Node[] elements = body.Children(node.Id, "element").Select(edge => body.Nodes[edge.ChildId]).ToArray();
            bool constants = ScalarTypes.IsNumeric(leaf) && elements.Length > 0 && elements.All(item => body.Child(item.Id, "value").Kind == "constant");
            if (constants)
            {
                var values = Enumerable.Repeat(ScalarTypes.Zero(leaf), checked((int)ScalarTypes.FlatCount(array))).ToArray();
                foreach (Node item in elements) values[int.Parse(item.ConstantText!, System.Globalization.CultureInfo.InvariantCulture)] = body.Child(item.Id, "value").ConstantText!;
                int prefix = Array.FindLastIndex(values, value => value != ScalarTypes.Zero(leaf)) + 1;
                if (prefix == 0) { Line(indent, name + " = default;"); return; }
                if (prefix <= Math.Max(64, elements.Length * 4))
                {
                    if (prefix < values.Length) Line(indent, name + " = default;");
                    // Collection-expression span properties embed blittable constants
                    // in assembly data; no managed array allocation or per-byte writes.
                    string property = generatedMembers.Allocate("__DotObjInitializer_" + linker.Objects.ToList().IndexOf(obj) + "_" + function.Id + "_" + node.Id, "__DotObjInitializer");
                    // Nonfinite values need exact payloads, so embed their integer
                    // representations and reinterpret the read-only data once.
                    bool bitPattern = ScalarTypes.IsFloating(leaf) && values.Take(prefix).Any(value => !ScalarTypes.IsFiniteConstant(leaf, value));
                    string dataType = bitPattern ? leaf == "f32" ? "uint" : "ulong" : Type(leaf);
                    string DataLiteral(string value) => bitPattern ? "0x" + value + (leaf == "f32" ? "U" : "UL") : ScalarTypes.Literal(leaf, value);
                    initializers.Append("    private static global::System.ReadOnlySpan<").Append(dataType).Append("> ").Append(property).Append(" => [\n");
                    for (int index = 0; index < prefix; index += 12)
                        initializers.Append("        ").Append(string.Join(", ", values.Skip(index).Take(Math.Min(12, prefix - index)).Select(DataLiteral))).Append(",\n");
                    initializers.Append("    ];\n\n");
                    string data = "global::" + namespaceName + "." + className + "." + property;
                    if (bitPattern) data = "global::System.Runtime.InteropServices.MemoryMarshal.Cast<" + dataType + ", " + Type(leaf) + ">(" + data + ")";
                    Line(indent, data + ".CopyTo(new global::System.Span<" + Type(leaf) + ">(&" + name + ", " + prefix + "));");
                    return;
                }
                // A sparse high-index initializer should not expand into thousands
                // of zero constants. The ordinary ordered stores below stay compact.
            }
            Line(indent, name + " = default;");
            if (elements.Length == 0) return;
            string targetName = target.Kind == "binding" ? body.Bindings[target.BindingId!.Value].SourceName : obj.Fields[target.FieldId!.Value].SourceName;
            string pointer = allocator.Allocate("__dotobj_" + targetName + "_elements", "__dotobj_elements");
            Line(indent, "{");
            Line(indent + 1, Type(leaf) + "* " + pointer + " = (" + Type(leaf) + "*)&" + name + ";");
            foreach (Node item in elements)
                Line(indent + 1, pointer + "[" + item.ConstantText + "] = " + Expression(body.Child(item.Id, "value")) + ";");
            Line(indent, "}");
        }
        void Discard(Node expression, int indent)
        {
            Node? volatileTarget = expression.Kind == "compound-assign" ? body.Child(expression.Id, "target")
                : expression.Kind == "mutate" ? body.Child(expression.Id, "operand") : null;
            if (volatileTarget?.Kind == "volatile-place" && !DirectVolatile(volatileTarget))
            {
                string type = NodeType(expression), address = allocator.Allocate("__volatile_address", "volatile_address"), value = allocator.Allocate("__volatile_value", "volatile_value");
                Line(indent, "{"); Line(indent + 1, Type(type) + "* " + address + " = " + Address(volatileTarget) + ";");
                if (expression.Kind == "compound-assign")
                {
                    Node right = body.Child(expression.Id, "value");
                    string argument = allocator.Allocate("__volatile_rhs", "volatile_rhs");
                    Line(indent + 1, Type(NodeType(right)) + " " + argument + " = " + Expression(right) + ";");
                    string op = expression.Operator switch { "add" or "pointer-add" => "+", "sub" or "pointer-subtract" => "-", "mul" => "*", "div" => "/", "rem" => "%", "bit-and" => "&", "bit-or" => "|", "bit-xor" => "^", "shl" => "<<", "shr" => ">>", _ => throw new InvalidDataException("Invalid compound operator") };
                    Line(indent + 1, Type(type) + " " + value + " = " + CompoundValue(type, NodeType(right), op, VolatileRead(type, address), argument) + ";");
                }
                else Line(indent + 1, Type(type) + " " + value + " = unchecked((" + Type(type) + ")(" + VolatileRead(type, address) +
                    (expression.Operator is "pre-inc" or "post-inc" ? " + 1));" : " - 1));"));
                Line(indent + 1, VolatileWrite(type, address, value) + ";"); Line(indent, "}"); return;
            }
            if (expression.Kind == "sequence")
                foreach (Edge edge in body.Children(expression.Id, "item")) Discard(body.Nodes[edge.ChildId], indent);
            else if (expression.Kind == "convert" && NodeType(expression) == "void") Discard(body.Child(expression.Id, "operand"), indent);
            else Line(indent, StatementExpression(expression) + ";");
        }
        void Statement(Node node, int indent)
        {
            Node Child(string role) => body.Child(node.Id, role);
            switch (node.Kind)
            {
                case "array-init": ArrayInitialize(node, indent); break;
                case "block":
                    Line(indent, "{");
                    BlockContents(node, indent + 1);
                    Line(indent, "}"); break;
                case "return":
                    if (!body.Children(node.Id, "value").Any()) Line(indent, "return;");
                    else if (NodeType(Child("value")) == "void") { Discard(Child("value"), indent); Line(indent, "return;"); }
                    else Line(indent, "return " + Expression(Child("value")) + ";");
                    break;
                case "expr-stmt":
                    // C# only allows a subset of expressions as statement expressions.
                    Discard(Child("value"), indent);
                    break;
                case "declare":
                    Binding binding = body.Bindings[node.BindingId!.Value];
                    Line(indent, Type(obj.Type(binding.TypeId)) + " " + bindingNames[binding.Id] + " = " +
                        (body.Children(node.Id, "initializer").Any() ? Expression(Child("initializer")) : "default") + ";"); break;
                case "if":
                    Line(indent, "if (" + Truth(Child("condition")) + ")"); ControlBody(Child("then"), indent);
                    if (body.Children(node.Id, "else").Any()) { Line(indent, "else"); ControlBody(Child("else"), indent); }
                    break;
                case "while": Line(indent, "while (" + Truth(Child("condition")) + ")"); ControlBody(Child("body"), indent); break;
                case "for":
                    string Header(string role) => body.Children(node.Id, role).Any()
                        ? role == "condition" ? Truth(Child(role)) : StatementExpression(Child(role)) : "";
                    Line(indent, "for (" + Header("initializer") + "; " + Header("condition") + "; " + Header("step") + ")");
                    ControlBody(Child("body"), indent);
                    break;
                case "do-while":
                    Line(indent, "do"); ControlBody(Child("body"), indent);
                    Line(indent, "while (" + Truth(Child("condition")) + ");");
                    break;
                case "switch": Switch(node, indent); break;
                case "label": Line(indent, labelNames[node.Id] + ":;"); break;
                case "goto": Line(indent, "goto " + labelNames[Child("target").Id] + ";"); break;
                case "break": Line(indent, "break;"); break;
                case "continue": Line(indent, "continue;"); break;
                default: throw new InvalidDataException("Unsupported statement " + node.Kind);
            }
        }
        var parameters = body.Bindings.Values.Where(binding => binding.Kind == "parameter").OrderBy(binding => binding.Ordinal);
        Line(1, (function.Linkage == "external" ? "public" : "private") + " static " + Type(obj.Type(function.ReturnTypeId)) + " " + linker.Names[symbol.Key] + "(" +
            string.Join(", ", parameters.Select(binding => Type(obj.Type(binding.TypeId)) + " " + bindingNames[binding.Id])
                .Concat(variadicFunction ? ["params global::System.ReadOnlySpan<global::Edg.Runtime.VaArg> " + vaInput] : [])) + ")");
        Line(1, "{");
        if (terminate) { Line(2, "try"); Line(2, "{"); }
        if (variadicFunction)
        {
            Line(bodyIndent, "int " + vaBytes + " = global::Edg.Runtime.VaPack.GetStackBytes(" + vaInput + ");");
            Line(bodyIndent, "byte* " + vaWorkspace + " = stackalloc byte[" + vaBytes + "];");
            Line(bodyIndent, "using var " + vaPack + " = new global::Edg.Runtime.VaPack(" + vaInput + ", " + vaWorkspace + ", " + vaBytes + ");");
            Line(bodyIndent, "global::Edg.Runtime.VaList " + vaArguments + " = " + vaPack + ".Value;");
        }
        if (body.RequiresFlatControl) FlatControl(obj, body, bodyIndent, allocator, bindingNames, Expression, Truth, Line, Statement, Discard);
        else BlockContents(body.Nodes[body.RootId], bodyIndent);
        bool SwitchFallsThrough(Node node)
        {
            Node[] items = body.Children(body.Child(node.Id, "body").Id, "statement")
                .Select(edge => body.Nodes[edge.ChildId]).ToArray();
            if (!items.Any(item => item.Kind == "case" && !body.Children(item.Id, "value").Any())) return true;
            // Explicit break paths can complete the switch. Without those,
            // every normal fallthrough ultimately enters the final section.
            if (body.Nodes.Values.Any(item => item.Kind == "break" && body.Child(item.Id, "target").Id == node.Id)) return true;
            int lastLabel = Array.FindLastIndex(items, item => item.Kind == "case");
            return items.Skip(lastLabel + 1).All(FallsThrough);
        }
        bool FallsThrough(Node node) => node.Kind switch
        {
            "return" or "break" or "continue" or "goto" => false,
            "expr-stmt" when body.Child(node.Id, "value").Kind == "intrinsic" && body.Child(node.Id, "value").Operator == "unreachable" => false,
            "switch" => SwitchFallsThrough(node),
            "block" => body.Children(node.Id, "statement").All(edge => FallsThrough(body.Nodes[edge.ChildId])),
            "if" => !body.Children(node.Id, "else").Any() || FallsThrough(body.Child(node.Id, "then")) || FallsThrough(body.Child(node.Id, "else")),
            _ => true
        };
        if (obj.Type(function.ReturnTypeId) != "void" && (body.RequiresFlatControl || FallsThrough(body.Nodes[body.RootId])))
            Line(bodyIndent, "throw new global::System.InvalidOperationException(\"Reached end of a non-void source function\");");
        if (terminate)
        {
            string error = allocator.Allocate("__noexcept_error", "noexcept_error");
            Line(2, "}"); Line(2, "catch (global::System.Exception " + error + ")"); Line(2, "{");
            Line(3, "global::System.Environment.FailFast(\"Exception escaped noexcept function\", " + error + ");");
            Line(3, "throw;"); Line(2, "}");
        }
        Line(1, "}"); Line(0, "");
        output.Append(initializers);
    }
