    private void Function(StringBuilder output, Symbol symbol, Utf8JsonWriter lifetimeWriter)
    {
        ObjectFile obj = symbol.Object;
        Entity function = symbol.Entity;
        FunctionBody body = obj.ReadBody(function.Id);
        if (body.Nodes.Values.Any(node => node.Kind == "register-cleanup") || obj.FunctionCleanupStates.ContainsKey(function.Id))
        {
            lifetimeWriter.WriteStartObject();
            lifetimeWriter.WriteNumber("entityId", function.Id);
            lifetimeWriter.WriteStartArray("regions");
            foreach (Node block in body.Nodes.Values.Where(node => node.Kind == "block").OrderBy(node => node.Id))
            {
                Edge[] statements = body.Children(block.Id, "statement").ToArray();
                foreach (Edge edge in statements)
                {
                    Node activation = body.Nodes[edge.ChildId];
                    if (activation.Kind != "register-cleanup") continue;
                    lifetimeWriter.WriteStartObject();
                    lifetimeWriter.WriteNumber("activationNodeId", activation.Id);
                    lifetimeWriter.WriteNumber("blockNodeId", block.Id);
                    lifetimeWriter.WriteNumber("bindingId", activation.BindingId!.Value);
                    lifetimeWriter.WriteNumber("callbackEntityId", activation.EntityId!.Value);
                    lifetimeWriter.WriteNumber("activationOrdinal", edge.Ordinal);
                    lifetimeWriter.WriteNumber("protectedSuffixStartOrdinal", edge.Ordinal + 1);
                    lifetimeWriter.WriteNumber("protectedSuffixEndExclusiveOrdinal", statements.Length);
                    lifetimeWriter.WriteEndObject();
                }
            }
            lifetimeWriter.WriteEndArray();
            var jsonOptions = new JsonSerializerOptions { PropertyNamingPolicy = JsonNamingPolicy.CamelCase };
            lifetimeWriter.WritePropertyName("cleanupActions");
            JsonSerializer.Serialize(lifetimeWriter, obj.FunctionCleanupActions.GetValueOrDefault(function.Id, []), jsonOptions);
            lifetimeWriter.WritePropertyName("cleanupArrays");
            JsonSerializer.Serialize(lifetimeWriter, obj.FunctionCleanupActions.GetValueOrDefault(function.Id, [])
                .Where(action => obj.CleanupArrays.ContainsKey(action.Id)).Select(action => obj.CleanupArrays[action.Id]).ToArray(), jsonOptions);
            lifetimeWriter.WritePropertyName("cleanupVttArguments");
            JsonSerializer.Serialize(lifetimeWriter, obj.FunctionCleanupActions.GetValueOrDefault(function.Id, [])
                .Where(action => obj.CleanupVttArguments.ContainsKey(action.Id)).Select(action => new { actionId = action.Id, bindingId = obj.CleanupVttArguments[action.Id] }).ToArray(), jsonOptions);
            lifetimeWriter.WritePropertyName("arrayRuntimeOperations");
            JsonSerializer.Serialize(lifetimeWriter, obj.ArrayRuntimeOperations.Values.Where(operation => body.Nodes.ContainsKey(operation.NodeId)).ToArray(), jsonOptions);
            lifetimeWriter.WritePropertyName("allocationCleanupActions");
            JsonSerializer.Serialize(lifetimeWriter, obj.AllocationCleanupActions.Values.Where(action => action.FunctionEntityId == function.Id), jsonOptions);
            lifetimeWriter.WritePropertyName("guardCleanupActions");
            JsonSerializer.Serialize(lifetimeWriter, obj.GuardCleanupActions.Values.Where(action => action.FunctionEntityId == function.Id), jsonOptions);
            lifetimeWriter.WritePropertyName("cleanupStates");
            JsonSerializer.Serialize(lifetimeWriter, obj.FunctionCleanupStates.GetValueOrDefault(function.Id, []), jsonOptions);
            lifetimeWriter.WritePropertyName("cleanupTransitions");
            JsonSerializer.Serialize(lifetimeWriter, body.Nodes.Values.Where(node => node.Kind == "cleanup-transition")
                .Select(node => obj.CleanupTransitions[node.Id]).ToArray(), jsonOptions);
            lifetimeWriter.WriteEndObject();
        }
        var allocator = new Names();
        allocator.Reserve("_"); // Keep discard assignments distinct from source bindings named _.
        var bindingNames = body.Bindings.Values.OrderBy(binding => binding.Kind == "parameter" ? 0 : 1)
            .ThenBy(binding => binding.Ordinal ?? binding.Id)
            .ToDictionary(binding => binding.Id, binding => allocator.Allocate(
                binding.Kind == "parameter" && binding.Ordinal is long ordinal ? obj.ParameterRoles[(function.Id, ordinal)].Role switch
                {
                    "this" => "this", "result-buffer" => "__result", _ => binding.SourceName,
                } : binding.SourceName,
                "local_" + binding.Id));
        Node SequenceTail(Node node) => body.Nodes[body.Children(node.Id, "item").Last().ChildId];
        bool RecordPlace(Node node) => node.ValueCategory == "place" && node.TypeId is long type && ScalarTypes.IsRecord(obj.Type(type));
        Node PlaceLeaf(Node node)
        {
            while (node.Kind is "lifetime-scope" or "sequence")
                node = node.Kind == "sequence" ? SequenceTail(node) : body.Child(node.Id, "operand");
            return node;
        }
        var materializedNames = body.Nodes.Values.Where(node => node.Kind == "materialize").OrderBy(node => node.Id)
            .ToDictionary(node => node.Id, node => allocator.Allocate("__materialized", "materialized"));
        var materializedPointers = materializedNames.Keys.Where(id => obj.StorageAlignment(obj.Type(body.Nodes[id].TypeId!.Value)) > 8)
            .ToDictionary(id => id, id => allocator.Allocate("__materialized_storage", "materialized_storage"));
        var accessAlignment = new AccessAlignment(obj, body);
        var addressTaken = new HashSet<long>();
        void AddressRoot(Node place)
        {
            if (place.Kind == "binding") addressTaken.Add(place.BindingId!.Value);
            else if (place.Kind == "sequence") AddressRoot(SequenceTail(place));
            else if (place.Kind is "virtual-base-adjustment" or "member" or "base-subobject" or "virtual-base-subobject" or "lifetime-scope" or "volatile-place") AddressRoot(body.Child(place.Id, "operand"));
        }
        foreach (Node node in body.Nodes.Values)
            if (node.Kind is "address" or "array-decay" or "volatile-place") AddressRoot(body.Child(node.Id, "operand"));
            else if (node.Kind == "register-cleanup") addressTaken.Add(node.BindingId!.Value);
            else if (node.Kind == "block-copy") { AddressRoot(body.Child(node.Id, "target")); AddressRoot(body.Child(node.Id, "source")); }
        foreach (Node parent in body.Nodes.Values)
            foreach (Edge edge in body.Edges.GetValueOrDefault(parent.Id, []))
            {
                Node child = body.Nodes[edge.ChildId];
                if (RecordPlace(child) &&
                    (parent.Kind == "sequence" && child.Id != SequenceTail(parent).Id ||
                     parent.Kind == "convert" && NodeType(parent) == "void" && edge.Role == "operand" ||
                     parent.Kind == "expr-stmt" && edge.Role == "value")) AddressRoot(child);
            }
        foreach (Node node in body.Nodes.Values)
            if (node.TypeId is not null && accessAlignment.NeedsUnaligned(node)) AddressRoot(node);
        var alignedPointers = body.Bindings.Values.Where(binding => addressTaken.Contains(binding.Id) && (obj.StorageAlignment(obj.Type(binding.TypeId)) > 8 || obj.Records.TryGetValue(binding.TypeId, out RecordType? view) && view.RepresentationKind == "subobject"))
            .OrderBy(binding => binding.Id).ToDictionary(binding => binding.Id, binding => allocator.Allocate("__storage_" + binding.SourceName, "aligned_storage"));
        var parameterNames = body.Bindings.Values.Where(binding => binding.Kind == "parameter").ToDictionary(binding => binding.Id,
            binding => alignedPointers.ContainsKey(binding.Id) ? allocator.Allocate("__incoming_" + binding.SourceName, "incoming_parameter") : bindingNames[binding.Id]);
        string LocalDeclaration(Binding binding) => alignedPointers.TryGetValue(binding.Id, out string? pointer)
            ? "ref " + Type(obj.Type(binding.TypeId)) + " " + bindingNames[binding.Id] + " = ref *" + pointer + "; " + bindingNames[binding.Id] + " = default;"
            : Type(obj.Type(binding.TypeId)) + " " + bindingNames[binding.Id] + " = default;";
        var throwCarrierNames = body.Nodes.Values.Where(node => node.Kind == "throw")
            .ToDictionary(node => node.Id, node => allocator.Allocate("__thrown", "thrown"));
        var initializers = new StringBuilder();
        var labelNames = body.Nodes.Values.Where(node => node.Kind == "label").OrderBy(node => node.Id)
            .ToDictionary(node => node.Id, node => allocator.Allocate(node.ConstantText!, "label_" + node.Id));
        bool variadicFunction = obj.Routines[function.RoutineTypeId].Variadic;
        bool terminate = obj.Routines[function.RoutineTypeId].ExceptionPolicy == "terminate" &&
            body.Nodes.Values.Any(node => node.Kind is not ("block" or "return"));
        var cleanupPayloadNames = obj.FunctionCleanupActions.GetValueOrDefault(function.Id, [])
            .Where(action => obj.CleanupPayloadOwners.ContainsKey(action.Id))
            .Select(action => obj.CleanupPayloadOwners[action.Id]).Distinct()
            .ToDictionary(id => id, id => allocator.Allocate("__payload_address", "payload_address"));
        var cleanupPayloadComplete = cleanupPayloadNames.Keys.ToDictionary(id => id,
            id => allocator.Allocate("__payload_complete", "payload_complete"));
        var tryNames = body.Nodes.Values.Where(node => node.Kind == "try").ToDictionary(node => node.Id,
            node => allocator.Allocate("__try_active", "try_active"));
        var handlerNames = body.Nodes.Values.Where(node => node.Kind == "catch").ToDictionary(node => node.Id,
            node => allocator.Allocate("__catch_frame", "catch_frame"));
        bool hasCleanup = obj.FunctionCleanupStates.ContainsKey(function.Id);
        string cleanupState = hasCleanup ? allocator.Allocate("__cleanup_state", "cleanup_state") : "";
        string cleanupUnwinding = hasCleanup ? allocator.Allocate("__cleanup_unwinding", "cleanup_unwinding") : "";
        int outerBodyIndent = terminate ? 3 : 2;
        int bodyIndent = outerBodyIndent + (hasCleanup ? 1 : 0);
        string vaArguments = allocator.Allocate("__va_arguments", "va_arguments"), vaInput = allocator.Allocate("__va_input", "va_input");
        string vaPack = allocator.Allocate("__va_pack", "va_pack"), vaBytes = allocator.Allocate("__va_bytes", "va_bytes"), vaWorkspace = allocator.Allocate("__va_workspace", "va_workspace");
        var liftedExpressions = new Dictionary<long, string>();
        var expansionCache = new Dictionary<long, bool>();
        var purityCache = new Dictionary<long, bool>();
        var continueLabels = new Dictionary<long, string>();
        string NodeType(Node node) => obj.Type(node.TypeId!.Value);
        string PointerIndex(Node node) => ScalarTypes.IsWideInteger(NodeType(node)) ? "unchecked((long)(" + Expression(node) + "))" : Expression(node);
        string Truth(Node node)
        {
            if (liftedExpressions.TryGetValue(node.Id, out string? liftedTruth)) return TruthText(liftedTruth, node);
            if (node.Kind == "binary" && node.Operator is "eq" or "ne" or "lt" or "le" or "gt" or "ge")
                return Comparison(node);
            if (node.Kind == "binary" && node.Operator is "and" or "or")
                return "(" + Truth(body.Child(node.Id, "left")) + (node.Operator == "and" ? " && " : " || ") + Truth(body.Child(node.Id, "right")) + ")";
            if (node.Kind == "unary" && node.Operator == "not") return "!(" + Truth(body.Child(node.Id, "operand")) + ")";
            string expression = Expression(node);
            return NodeType(node) == "bool" ? expression : "(" + expression + (ScalarTypes.IsPointer(NodeType(node)) ? " != null)" : " != 0)");
        }
        string TruthText(string value, Node node) => NodeType(node) == "bool" ? value : "(" + value + (ScalarTypes.IsPointer(NodeType(node)) ? " != null)" : " != 0)");
        string Comparison(Node node)
        {
            string op = node.Operator switch { "eq" => "==", "ne" => "!=", "lt" => "<", "le" => "<=", "gt" => ">", "ge" => ">=", _ => throw new InvalidDataException("Unsupported comparison") };
            return "(" + Expression(body.Child(node.Id, "left")) + " " + op + " " + Expression(body.Child(node.Id, "right")) + ")";
        }
        string Boolean(string expression, Node node) => NodeType(node) switch
        { "bool" => expression, "i32" => "(" + expression + " ? 1 : 0)", "u8" => "((byte)(" + expression + " ? 1 : 0))", _ => throw new InvalidDataException("Invalid boolean result") };
        string FromBoolean(string expression, string type) => type == "i32"
            ? "(" + expression + " ? 1 : 0)" : "((" + Type(type) + ")(" + expression + " ? 1 : 0))";
        string UnalignedRead(string type, string address) => ScalarTypes.IsPointer(type)
            ? "((" + Type(type) + ")global::System.Runtime.CompilerServices.Unsafe.ReadUnaligned<nuint>(" + address + "))"
            : "global::System.Runtime.CompilerServices.Unsafe.ReadUnaligned<" + Type(type) + ">(" + address + ")";
        string UnalignedWrite(string type, string address, string value) =>
            "global::System.Runtime.CompilerServices.Unsafe.WriteUnaligned<" + (ScalarTypes.IsPointer(type) ? "nuint" : Type(type)) + ">(" + address + ", " +
                (ScalarTypes.IsPointer(type) ? "(nuint)(" + value + ")" : value) + ")";
        string Expression(Node node)
        {
            if (liftedExpressions.TryGetValue(node.Id, out string? lifted)) return lifted;
            if (node.Kind == "lifetime-scope") return Expression(body.Child(node.Id, "operand"));
            return accessAlignment.NeedsUnaligned(node) ? UnalignedRead(NodeType(node), Address(node)) : Location(node);
        }
        string Location(Node node)
        {
            if (liftedExpressions.TryGetValue(node.Id, out string? lifted)) return lifted;
            Node Child(string role) => body.Child(node.Id, role);
            string Operand(string role) => Expression(Child(role));
            switch (node.Kind)
            {
                case "virtual-base-adjustment":
                case "lifetime-scope": return Location(Child("operand"));
                case "intrinsic": return Intrinsic(obj, node, body.Children(node.Id, "argument").Select(edge => body.Nodes[edge.ChildId]).ToArray(), Expression);
                case "materialize": return materializedNames[node.Id];
                case "sequence" when node.ValueCategory == "place": return Location(SequenceTail(node));
                case "sequence":
                    Node[] items = body.Children(node.Id, "item").Select(edge => body.Nodes[edge.ChildId]).ToArray();
                    string tail = Expression(items[^1]);
                    for (int index = items.Length - 2; index >= 0; index--)
                    {
                        Node item = items[index];
                        while (item.Kind == "convert" && NodeType(item) == "void") item = body.Child(item.Id, "operand");
                        if (NodeType(item) == "void") throw new InvalidDataException("Void-prefix comma expression requires statement expansion at " + node.Id + " in " + function.SourceName);
                        string head = RecordPlace(item) ? "((nuint)" + Address(item) + ")" : Expression(item);
                        if (!RecordPlace(item) && ScalarTypes.IsPointer(NodeType(item))) head = "((nuint)" + head + ")";
                        tail = "(" + head + " switch { _ => " + tail + " })";
                    }
                    return tail;
                case "va-start": return "global::Edg.Runtime.VaList.Start(" + Operand("operand") + ", &" + vaArguments + ")";
                case "va-copy": return "global::Edg.Runtime.VaList.Copy(" + Operand("operand") + ", " + Operand("source") + ")";
                case "va-end": return "global::Edg.Runtime.VaList.EndList(" + Operand("operand") + ")";
                case "va-arg": return "(*(" + Type(NodeType(node)) + "*)global::Edg.Runtime.VaList.Take(" + Operand("operand") + ", " + obj.StorageSize(NodeType(node)) + "UL, " + obj.StorageAlignment(NodeType(node)) + "UL))";
                case "volatile-place": return DirectVolatile(node) ? Operand("operand") : VolatileRead(NodeType(node), Address(Child("operand")), Operand("operand"));
                case "constant":
                    return ScalarTypes.IsPointer(NodeType(node)) ? "((" + Type(NodeType(node)) + ")null)" : ScalarTypes.Literal(NodeType(node), node.ConstantText!);
                case "binding": return bindingNames[node.BindingId!.Value];
                case "storage": return StorageReference(linker.ResolveStorage(obj, node.StorageId!.Value));
                case "storage-address":
                    return "((" + Type(NodeType(node)) + ")(" + StorageAddress(linker.ResolveStorage(obj, node.StorageId!.Value), long.Parse(node.ConstantText!, System.Globalization.CultureInfo.InvariantCulture)) + "))";
                case "function-address":
                    return "((" + Type(NodeType(node)) + ")&" + FunctionReference(linker.Resolve(obj, node.EntityId!.Value)) + ")";
                case "indirect-call":
                    return (Child("operand").Kind is "binding" or "storage" or "member" ? Operand("operand") : "(" + Operand("operand") + ")") + "(" + Arguments(node, ScalarTypes.Pointee(NodeType(Child("operand")))) + ")";
                case "default-value": return "default(" + Type(NodeType(node)) + ")";
                case "member":
                    RecordField field = obj.Fields[node.FieldId!.Value];
                    string fieldName = fieldNames[(obj.Type(field.RecordTypeId), field.Ordinal)];
                    Node owner = Child("operand");
                    if (owner.Kind == "dereference" && !liftedExpressions.ContainsKey(owner.Id)) return Expression(body.Child(owner.Id, "operand")) + "->" + fieldName;
                    return (owner.ValueCategory == "place" ? Location(owner) : Expression(owner)) + "." + fieldName;
                case "array-decay": return "((" + Type(NodeType(node)) + ")" + Address(Child("operand")) + ")";
                case "address": return Address(Child("operand"));
                case "dereference":
                    Node pointer = Child("operand");
                    if (pointer.Kind == "binary" && pointer.Operator == "pointer-add" && !liftedExpressions.ContainsKey(pointer.Id) &&
                        ScalarTypes.IsPointer(NodeType(body.Child(pointer.Id, "left"))))
                        return "(" + Expression(body.Child(pointer.Id, "left")) + ")[" + PointerIndex(body.Child(pointer.Id, "right")) + "]";
                    return "(*" + Operand("operand") + ")";
                case "static-destruction-register":
                    return "global::Edg.Runtime.ObjectProgram.RegisterStaticDestructor((delegate* managed<void*, void>)(" + Operand("callback") + "), (void*)(" + Operand("object") + "))";
                case "guard-operation":
                    string guardMethod = obj.GuardOperations[node.Id].Kind switch { "probe" => "NeedsInitialization", "acquire" => "Acquire", "release" => "Release", _ => throw new InvalidDataException("Invalid guard operation") };
                    return "global::Edg.Runtime.CppGuards." + guardMethod + "(" + Operand("guard") + ")";
                case "call":
                    Symbol target = linker.Resolve(obj, node.EntityId!.Value);
                    return FunctionReference(target) + "(" + Arguments(node, target.Object.EntityRoutine(target.Entity.Id)) + ")";
                case "block-copy": return "global::System.Runtime.InteropServices.NativeMemory.Copy(" + Address(Child("source")) + ", " + Address(Child("target")) + ", (nuint)" + node.ConstantText + ")";
                case "compound-assign": return "(" + Compound(node) + ")";
                case "cleanup-payload-address": return "((" + Type(NodeType(node)) + ")" + cleanupPayloadNames[obj.CleanupPayloadTargets[node.Id].ThrowNodeId] + ")";
                case "caught-object-address": return "((global::Edg.Runtime.CppTypedCatch)" + handlerNames[obj.CaughtObjectAddresses[node.Id]] + "!).ObjectAddress";
                case "thrown-object-address": return throwCarrierNames[obj.ThrowObjectAddresses[node.Id]] + ".ObjectAddress";
                case "record-constant-init":
                case "record-transfer":
                case "assign": return Assignment(node, true);
                case "mutate": return "(" + Mutation(node) + ")";
                case "convert":
                    if (NodeType(node) == NodeType(Child("operand"))) return Operand("operand");
                    if (NodeType(node) == "bool") return Truth(Child("operand"));
                    if (NodeType(Child("operand")) == "bool") return FromBoolean(Operand("operand"), NodeType(node));
                    // The selected LP64 target sign-extends pointers when converting
                    // to 128-bit integers; the reverse conversion keeps low pointer bits.
                    if (ScalarTypes.IsWideInteger(NodeType(node)) && ScalarTypes.IsPointer(NodeType(Child("operand"))))
                        return "unchecked((" + Type(NodeType(node)) + ")(nint)(" + Operand("operand") + "))";
                    if (ScalarTypes.IsPointer(NodeType(node)) && ScalarTypes.IsWideInteger(NodeType(Child("operand"))))
                        return "unchecked((" + Type(NodeType(node)) + ")(nuint)(" + Operand("operand") + "))";
                    return "unchecked((" + Type(NodeType(node)) + ")(" + Operand("operand") + "))";
                case "unary":
                    if (node.Operator == "not") return Boolean("!(" + Truth(Child("operand")) + ")", node);
                    if (node.Operator == "neg")
                        return NodeType(node) is "u32" or "u64" or "u128"
                            ? "unchecked(" + (NodeType(node) == "u32" ? "0U" : NodeType(node) == "u64" ? "0UL" : "global::System.UInt128.Zero") + " - " + Operand("operand") + ")"
                            : "unchecked(-" + Operand("operand") + ")";
                    return "(" + (node.Operator == "bit-not" ? "~" : "+") + Operand("operand") + ")";
                case "conditional":
                    return "(" + Truth(Child("condition")) + " ? " + Operand("then") + " : " + Operand("else") + ")";
                case "binary":
                    if (node.Operator is "and" or "or")
                        return Boolean("(" + Truth(Child("left")) + (node.Operator == "and" ? " && " : " || ") + Truth(Child("right")) + ")", node);
                    string op = node.Operator switch
                    { "add" or "pointer-add" => "+", "sub" or "pointer-subtract" or "pointer-difference" => "-", "mul" => "*", "div" => "/", "rem" => "%", "eq" => "==", "ne" => "!=", "lt" => "<", "le" => "<=", "gt" => ">", "ge" => ">=", "bit-and" => "&", "bit-or" => "|", "bit-xor" => "^", "shl" => "<<", "shr" => ">>", _ => throw new InvalidDataException("Unsupported operator") };
                    string right = node.Operator is "shl" or "shr" && NodeType(Child("right")) != "i32"
                        ? "unchecked((int)(" + Operand("right") + "))" : Operand("right");
                    string left = Operand("left");
                    if (node.Operator is "pointer-add" or "pointer-subtract")
                    {
                        if (ScalarTypes.IsWideInteger(NodeType(Child("left")))) left = PointerIndex(Child("left"));
                        if (ScalarTypes.IsWideInteger(NodeType(Child("right")))) right = PointerIndex(Child("right"));
                        if (ScalarTypes.IsZeroStridePointer(NodeType(node)))
                        {
                            if (ScalarTypes.IsPointer(NodeType(Child("left")))) right = "(" + right + " * 0 /* zero-size array stride */)";
                            else left = "(" + left + " * 0 /* zero-size array stride */)";
                        }
                    }
                    string expression = "(" + left + " " + op + " " + right + ")";
                    if (node.Operator is "eq" or "ne" or "lt" or "le" or "gt" or "ge") return Boolean(expression, node);
                    return node.Operator is "add" or "sub" or "mul" ? "unchecked" + expression : expression;
                default: throw new InvalidDataException("Unsupported expression " + node.Kind);
            }
        }
        string Arguments(Node node, string routine)
        {
            var signature = RoutineTypes.Signature(routine);
            Node[] values = body.Children(node.Id, "argument").Select(edge => body.Nodes[edge.ChildId]).ToArray();
            var arguments = values.Take(signature.Parameters.Length).Select(Expression).ToList();
            if (signature.Variadic)
            {
                string Argument(Node value) => ScalarTypes.IsPointer(NodeType(value))
                    ? "global::Edg.Runtime.VaArg.FromPointer((void*)" + Expression(value) + ")"
                    : "global::Edg.Runtime.VaArg.From(" + Expression(value) + ", " + obj.StorageSize(NodeType(value)) + ", " + obj.StorageAlignment(NodeType(value)) + ")";
                arguments.Add("[" + string.Join(", ", values.Skip(signature.Parameters.Length).Select(Argument)) + "]");
            }
            return string.Join(", ", arguments);
        }
        bool DirectVolatile(Node node) => node.Kind == "volatile-place" &&
            body.Child(node.Id, "operand") is { Kind: "member", FieldId: not null } fieldNode &&
            IsVolatileField(obj, obj.Fields[fieldNode.FieldId.Value]);
        string Address(Node node)
        {
            if (node.Kind == "binding" && alignedPointers.TryGetValue(node.BindingId!.Value, out string? aligned)) return aligned;
            if (node.Kind == "materialize" && materializedPointers.TryGetValue(node.Id, out string? materialized)) return materialized;
            if (node.Kind == "sequence") return Address(SequenceTail(node));
            if (node.Kind is "virtual-base-adjustment" or "volatile-place" or "lifetime-scope") return Address(body.Child(node.Id, "operand"));
            if (node.Kind == "storage") return "((" + Type(NodeType(node)) + "*)" + StorageAddress(linker.ResolveStorage(obj, node.StorageId!.Value)) + ")";
            if (node.Kind == "dereference") return Expression(body.Child(node.Id, "operand"));
            if (node.Kind == "virtual-base-subobject")
            {
                Node containing = body.Child(node.Id, "operand");
                VirtualBaseSubobject view = obj.VirtualBaseSubobjects[(containing.TypeId!.Value, obj.VirtualBaseExpressions[node.Id])];
                string address = Address(containing);
                return "((" + Type(NodeType(node)) + "*)" + (view.ByteOffset == 0 ? address : "((byte*)" + address + " + " + view.ByteOffset + " /* virtual base */)") + ")";
            }
            if (node.Kind == "base-subobject")
            {
                Node containing = body.Child(node.Id, "operand");
                RecordBaseSubobject view = obj.BaseSubobjects[(containing.TypeId!.Value, obj.BaseSubobjectExpressions[node.Id])];
                string address = Address(containing);
                return "((" + Type(NodeType(node)) + "*)" + (view.ByteOffset == 0 ? address : "((byte*)" + address + " + " + view.ByteOffset + " /* empty base */)") + ")";
            }
            if (node.Kind == "member")
            {
                RecordField field = obj.Fields[node.FieldId!.Value];
                if (ScalarTypes.IsAddressOnlyArray(obj.Type(field.TypeId)))
                    return "((" + Type(obj.Type(field.TypeId)) + "*)((byte*)" + Address(body.Child(node.Id, "operand")) + " + " + field.ByteOffset + " /* " + field.SourceName + " */))";
                return "(&(" + Address(body.Child(node.Id, "operand")) + ")->" + fieldNames[(obj.Type(field.RecordTypeId), field.Ordinal)] + ")";
            }
            return "(&" + Location(node) + ")";
        }
        string Assignment(Node node, bool valueNeeded)
        {
            Node target = body.Child(node.Id, "target"), leaf = PlaceLeaf(target);
            string value = node.Kind == "record-constant-init" && obj.RecordConstantInitializations[node.Id].AllBitsZero
                ? "default" : Expression(body.Child(node.Id, "value"));
            if (leaf.Kind == "volatile-place" && !DirectVolatile(leaf))
                return valueNeeded ? VolatileOperation(NodeType(node), "assign", Address(target), value)
                    : VolatileWrite(NodeType(node), Address(target), value, Location(body.Child(leaf.Id, "operand")));
            string result = Location(target) + " = " + value;
            if (!valueNeeded) return result;
            return leaf.Kind == "member" && obj.Fields[leaf.FieldId!.Value].BitWidth is not null
                ? BitfieldResult(obj, obj.Fields[leaf.FieldId.Value], "(" + result + ")") : "(" + result + ")";
        }
        string Mutation(Node node, bool valueNeeded = true)
        {
            Node location = body.Child(node.Id, "operand"), leaf = PlaceLeaf(location);
            if (leaf.Kind == "volatile-place" && !DirectVolatile(leaf)) return VolatileOperation(NodeType(node), node.Operator!, Address(location), null);
            if (valueNeeded && leaf.Kind == "member" && obj.Fields[leaf.FieldId!.Value].BitWidth is not null && node.Operator is "pre-inc" or "pre-dec")
                return BitfieldResult(obj, obj.Fields[leaf.FieldId!.Value], "(" + (node.Operator == "pre-inc" ? "++" : "--") + Location(location) + ")");
            string operand = Location(location);
            if (ScalarTypes.IsZeroStridePointer(NodeType(node))) return operand + " += 0 /* zero-size array stride */";
            string operation = node.Operator is "pre-inc" or "post-inc" ? "++" : "--";
            return node.Operator is "pre-inc" or "pre-dec" ? operation + operand : operand + operation;
        }
        string Compound(Node node, bool valueNeeded = true)
        {
            string op = node.Operator switch { "add" or "pointer-add" => "+", "sub" or "pointer-subtract" => "-", "mul" => "*", "div" => "/", "rem" => "%", "bit-and" => "&", "bit-or" => "|", "bit-xor" => "^", "shl" => "<<", "shr" => ">>", _ => throw new InvalidDataException("Invalid compound operator") };
            string value = Expression(body.Child(node.Id, "value")), valueType = NodeType(body.Child(node.Id, "value"));
            if (node.Operator is "shl" or "shr") { value = "unchecked((int)(" + value + "))"; valueType = "i32"; }
            if (node.Operator is "pointer-add" or "pointer-subtract" && ScalarTypes.IsWideInteger(valueType))
            { value = "unchecked((long)(" + value + "))"; valueType = "i64"; }
            // Integer modular operations depend only on the stored low bits.
            // Narrowing the RHS lets C# retain the original compound assignment
            // without evaluating its receiver twice or introducing a helper.
            if (ModularIntegerOperation(NodeType(node), valueType, op) && !ImplicitNumericConversion(valueType, NodeType(node)))
            {
                value = "unchecked((" + Type(NodeType(node)) + ")(" + value + "))";
                valueType = NodeType(node);
            }
            if (ScalarTypes.IsZeroStridePointer(NodeType(node))) value = "(" + value + " * 0 /* zero-size array stride */)";
            Node target = body.Child(node.Id, "target"), leaf = PlaceLeaf(target);
            if (leaf.Kind == "volatile-place" && (!DirectVolatile(leaf) || CompoundPromotionDiffers(NodeType(node), valueType, op))) return VolatileOperation(NodeType(node), op + "=", Address(target), value, valueType);
            bool promotionDiffers = CompoundPromotionDiffers(NodeType(node), valueType, op);
            if (leaf.Kind == "member" && obj.Fields[leaf.FieldId!.Value].BitWidth is not null && (valueNeeded || promotionDiffers))
                return promotionDiffers
                    ? BitfieldOperation(obj, obj.Fields[leaf.FieldId!.Value], op + "=", Address(body.Child(leaf.Id, "operand")), value, valueType)
                    : BitfieldResult(obj, obj.Fields[leaf.FieldId!.Value], "(" + Location(target) + " " + op + "= " + value + ")");
            if (promotionDiffers) return CompoundOperation(NodeType(node), valueType, op, Address(target), value);
            return Location(target) + " " + op + "= " + value;
        }
        string StatementExpression(Node node) => node.Kind switch
        {
            "lifetime-scope" => StatementExpression(body.Child(node.Id, "operand")),
            "assign" or "record-transfer" or "record-constant-init" => Assignment(node, false),
            "mutate" => Mutation(node, false),
            "compound-assign" => Compound(node, false),
            "static-destruction-register" or "guard-operation" or "call" or "indirect-call" or "va-start" or "va-copy" or "va-end" or "block-copy" => Expression(node),
            "intrinsic" when node.Operator == "unreachable" => Expression(node),
            "convert" when NodeType(node) == "void" => StatementExpression(body.Child(node.Id, "operand")),
            _ when RecordPlace(node) => "_ = (nuint)" + Address(node),
            _ => "_ = " + Expression(node)
        };
        void Line(int indent, string text) => output.Append(' ', indent * 4).Append(text).Append('\n');
        void BlockContents(Node block, int indent)
        {
            // Registration starts a protected suffix only after initialization
            // succeeded. Each suffix nests inside the previous one, giving
            // reverse cleanup on normal exit, return, break, continue or throw.
            // The object stores semantic activation, not pre-rendered C# or
            // duplicated normal-exit cleanup calls.
            var cleanups = new Stack<Node>();
            foreach (Edge edge in body.Children(block.Id, "statement"))
            {
                Node statement = body.Nodes[edge.ChildId];
                if (statement.Kind != "register-cleanup") { Statement(statement, indent); continue; }
                cleanups.Push(statement);
                Line(indent, "try");
                Line(indent++, "{");
            }
            while (cleanups.TryPop(out Node? cleanup))
            {
                Line(--indent, "}");
                Line(indent, "finally");
                Line(indent, "{");
                Symbol callback = linker.Resolve(obj, cleanup.EntityId!.Value);
                Line(indent + 1, FunctionReference(callback) +
                    "(" + (alignedPointers.TryGetValue(cleanup.BindingId!.Value, out string? cleanupAddress) ? cleanupAddress : "&" + bindingNames[cleanup.BindingId.Value]) + ");");
                Line(indent, "}");
            }
        }
        void ControlBody(Node node, int indent)
        {
            if (node.Kind == "block") Statement(node, indent);
            else { Line(indent, "{"); Statement(node, indent + 1); Line(indent, "}"); }
        }
        void Switch(Node node, int indent)
        {
            Node selector = body.Child(node.Id, "condition");
            Node switchBody = body.Child(node.Id, "body");
            Node[] items = body.Children(switchBody.Id, "statement").Select(edge => body.Nodes[edge.ChildId]).ToArray();
            Node[] declarations = items.TakeWhile(item => item.Kind == "declare").ToArray();
            // The object block owns locals across case sections. C# cannot put
            // declarations before its first case, so retain that scope outside
            // the switch; source initializer assignments stay at their positions.
            if (declarations.Length != 0)
            {
                Line(indent, "{");
                indent++;
                foreach (Node declaration in declarations) Statement(declaration, indent);
            }
            string Label(Node label)
            {
                if (!body.Children(label.Id, "value").Any()) return "default";
                Node value = body.Child(label.Id, "value");
                return "case " + ScalarTypes.Literal(NodeType(selector),
                    ScalarTypes.SwitchConstant(NodeType(value), value.ConstantText!, NodeType(selector)));
            }
            Line(indent, "switch (" + ExpandedValue(selector, indent) + ")");
            Line(indent, "{");
            int index = declarations.Length;
            while (index < items.Length)
            {
                // Adjacent labels share a section, preserving source grouping.
                do { Line(indent + 1, Label(items[index++]) + ":"); }
                while (index < items.Length && items[index].Kind == "case");
                bool fallsThrough = true;
                while (index < items.Length && items[index].Kind != "case")
                {
                    Node statement = items[index++];
                    Statement(statement, indent + 2);
                    fallsThrough &= FallsThrough(statement);
                }
                if (fallsThrough)
                    Line(indent + 2, index < items.Length ? "goto " + Label(items[index]) + ";" : "break;");
            }
            Line(indent, "}");
            if (declarations.Length != 0) Line(indent - 1, "}");
        }
        void ArrayInitialize(Node node, int indent)
        {
            Node target = body.Child(node.Id, "target");
            string array = NodeType(target), leaf = ScalarTypes.Leaf(array);
            string name = Location(target);
