            foreach (Node item in elements)
                Line(indent + 1, (accessAlignment.Place(target) < obj.AccessAlignment(leaf) ? UnalignedWrite(leaf, pointer + " + " + item.ConstantText, ExpandedValue(body.Child(item.Id, "value"), indent + 1)) : pointer + "[" + item.ConstantText + "] = " + ExpandedValue(body.Child(item.Id, "value"), indent + 1)) + ";");
            Line(indent, "}");
        }
        bool Pure(Node node)
        {
            if (purityCache.TryGetValue(node.Id, out bool cached)) return cached;
            bool result = node.Kind is not ("static-destruction-register" or "guard-operation" or "internal-try-expression" or "throw" or "throw-marker" or "rethrow" or "materialize" or "cleanup-transition" or "call" or "indirect-call" or "assign" or "record-transfer" or "record-constant-init" or "compound-assign" or "block-copy" or "mutate" or "volatile-place" or "va-start" or "va-copy" or "va-end" or "va-arg") &&
                !(node.Kind == "intrinsic" && (node.Operator == "unreachable" || node.Operator!.Contains("overflow", StringComparison.Ordinal))) &&
                body.Edges.GetValueOrDefault(node.Id, []).All(edge => Pure(body.Nodes[edge.ChildId]));
            purityCache[node.Id] = result;
            return result;
        }
        // An address rooted in owned stack storage with constant offsets cannot
        // change while the RHS runs, even if the RHS calls or mutates values.
        bool StablePlace(Node node, int depth = 0) => depth <= 1024 &&
            (node.Kind is "binding" or "storage" || node.Kind is "virtual-base-adjustment" or "member" or "lifetime-scope" or "volatile-place" && StablePlace(body.Child(node.Id, "operand"), depth + 1) ||
                node.Kind == "dereference" && StablePointer(body.Child(node.Id, "operand"), depth + 1));
        bool StablePointer(Node node, int depth = 0)
        {
            if (depth > 1024) return false;
            if (node.Kind == "lifetime-scope") return StablePointer(body.Child(node.Id, "operand"), depth + 1);
            if (node.Kind is "storage-address" or "function-address" || node.Kind == "constant" && ScalarTypes.IsPointer(NodeType(node))) return true;
            if (node.Kind is "address" or "array-decay") return StablePlace(body.Child(node.Id, "operand"), depth + 1);
            if (node.Kind == "convert" && ScalarTypes.IsPointer(NodeType(node)) && ScalarTypes.IsPointer(NodeType(body.Child(node.Id, "operand"))))
                return StablePointer(body.Child(node.Id, "operand"), depth + 1);
            if (node.Kind == "binary" && node.Operator is "pointer-add" or "pointer-subtract")
            {
                Node left = body.Child(node.Id, "left"), right = body.Child(node.Id, "right");
                return right.Kind == "constant" && ScalarTypes.IsInteger(NodeType(right)) && StablePointer(left, depth + 1) ||
                    node.Operator == "pointer-add" && left.Kind == "constant" && ScalarTypes.IsInteger(NodeType(left)) && StablePointer(right, depth + 1);
            }
            return false;
        }
        // Expand only operations whose evaluation order or void operands cannot
        // be expressed directly in C#. Preserve lazy branches and evaluate
        // earlier operands before the lifted statements of later operands.
        bool NeedsExpansion(Node node)
        {
            if (liftedExpressions.ContainsKey(node.Id)) return false;
            if (expansionCache.TryGetValue(node.Id, out bool cached)) return cached;
            bool result = node.Kind == "materialize" || node.Kind == "sequence" && (node.ValueCategory == "place" || body.Children(node.Id, "item").SkipLast(1)
                .Any(edge => NodeType(body.Nodes[edge.ChildId]) == "void"));
            if (node.Kind is "internal-try-expression" or "throw" or "throw-marker" or "rethrow") result = true;
            if (node.Kind == "conditional" && NodeType(node) == "void") result = true;
            if (node.Kind is "assign" or "record-transfer" or "record-constant-init" or "compound-assign") result |= accessAlignment.NeedsUnaligned(body.Child(node.Id, "target"));
            if (node.Kind == "mutate") result |= accessAlignment.NeedsUnaligned(body.Child(node.Id, "operand"));
            if (node.Kind == "block-copy") result |= !Pure(body.Child(node.Id, "target")) || !Pure(body.Child(node.Id, "source"));
            if (node.Kind is "assign" or "record-transfer" or "record-constant-init" or "compound-assign" && node.EvaluationOrder == "right-to-left")
            {
                Node target = body.Child(node.Id, "target"), value = body.Child(node.Id, "value");
                // C# compound assignment reads the old destination before its
                // RHS; C++17 reads it afterwards, even for a simple local.
                result |= (node.Kind == "compound-assign" || !StablePlace(target)) && (!Pure(target) || !Pure(value));
            }
            result |= body.Edges.GetValueOrDefault(node.Id, []).Any(edge =>
                (edge.Role != "target" || node.Kind is "assign" or "record-transfer" or "record-constant-init" or "compound-assign" or "block-copy") &&
                body.Nodes[edge.ChildId].TypeId != null && NeedsExpansion(body.Nodes[edge.ChildId]));
            expansionCache[node.Id] = result;
            return result;
        }
        bool TerminalThrow(Node node) => node.Kind is "throw" or "rethrow" ||
            node.Kind == "lifetime-scope" && TerminalThrow(body.Child(node.Id, "operand")) ||
            node.Kind == "sequence" && body.Children(node.Id, "item").Any(edge => TerminalThrow(body.Nodes[edge.ChildId])) ||
            node.Kind == "conditional" && TerminalThrow(body.Child(node.Id, "then")) && TerminalThrow(body.Child(node.Id, "else"));
        void EmitTerminalThrow(Node node, int indent)
        {
            if (node.Kind == "lifetime-scope") { EmitTerminalThrow(body.Child(node.Id, "operand"), indent); return; }
            if (node.Kind == "sequence")
            {
                foreach (Edge edge in body.Children(node.Id, "item"))
                {
                    Node item = body.Nodes[edge.ChildId];
                    if (TerminalThrow(item)) { EmitTerminalThrow(item, indent); return; }
                    Discard(item, indent);
                }
                throw new InvalidDataException("Terminal throw sequence lacks its owned throwing operation");
            }
            Discard(node, indent);
        }
        string ExpandedValue(Node node, int indent) => NeedsExpansion(node) ? Lift(node, indent) : Expression(node);
        string ExpandedTruth(Node node, int indent) => NeedsExpansion(node) ? TruthText(Lift(node, indent), node) : Truth(node);
        string Lift(Node node, int indent, bool discard = false)
        {
            if (node.Kind is "internal-try-expression" or "cleanup-transition" or "cleanup-frame" or "throw" or "throw-marker" or "rethrow") { Discard(node, indent); return ""; }
            if (node.Kind == "materialize")
            {
                string value = ExpandedValue(body.Child(node.Id, "operand"), indent);
                Line(indent, materializedNames[node.Id] + " = " + value + ";");
                return discard ? "" : materializedNames[node.Id];
            }
            if (node.Kind is "virtual-base-adjustment" or "lifetime-scope") return Lift(body.Child(node.Id, "operand"), indent, discard);
            if (node.Kind == "sequence")
            {
                Node[] items = body.Children(node.Id, "item").Select(edge => body.Nodes[edge.ChildId]).ToArray();
                foreach (Node item in items.SkipLast(1)) Discard(item, indent);
                if (discard) { Discard(items[^1], indent); return ""; }
                return Lift(items[^1], indent);
            }
            if (node.Kind == "convert" && NodeType(node) == "void") { Discard(body.Child(node.Id, "operand"), indent); return ""; }
            string result = allocator.Allocate("__expression", "expression");
            if (NeedsExpansion(node) && (node.Kind == "conditional" || node.Kind == "binary" && node.Operator is "and" or "or"))
            {
                bool conditional = node.Kind == "conditional";
                Node condition = body.Child(node.Id, conditional ? "condition" : "left");
                string test = ExpandedTruth(condition, indent);
                bool isVoid = discard || NodeType(node) == "void";
                if (!isVoid) Line(indent, Type(NodeType(node)) + " " + result + ";");
                Line(indent, "if (" + test + ")"); Line(indent, "{");
                Branch(conditional ? body.Child(node.Id, "then") : node.Operator == "and" ? body.Child(node.Id, "right") : null, true);
                Line(indent, "}"); Line(indent, "else"); Line(indent, "{");
                Branch(conditional ? body.Child(node.Id, "else") : node.Operator == "or" ? body.Child(node.Id, "right") : null, false);
                Line(indent, "}"); return isVoid ? "" : result;
                void Branch(Node? value, bool fallback)
                {
                    // Stock wrap_throw supplies a typed unreachable tail for
                    // C conditional typing. Preserve the owned tree, but emit
                    // only its effects through the terminal throw operation.
                    if (value is not null && TerminalThrow(value)) { EmitTerminalThrow(value, indent + 1); return; }
                    if (isVoid) { if (value != null) Discard(value, indent + 1); return; }
                    string text = conditional ? ExpandedValue(value!, indent + 1)
                        : Boolean(value == null ? fallback ? "true" : "false" : ExpandedTruth(value, indent + 1), node);
                    Line(indent + 1, result + " = " + text + ";");
                }
            }
            var changed = new List<long>();
            void Value(Node child)
            {
                if (child.Kind is "constant" or "default-value" or "function-address") return;
                string value = Lift(child, indent);
                liftedExpressions.Add(child.Id, value); changed.Add(child.Id);
            }
            void Place(Node place)
            {
                if (place.Kind is "binding" or "storage") return;
                if (place.Kind == "sequence")
                {
                    Node[] items = body.Children(place.Id, "item").Select(edge => body.Nodes[edge.ChildId]).ToArray();
                    foreach (Node item in items.SkipLast(1)) Discard(item, indent);
                    Place(items[^1]); return;
                }
                if (place.Kind == "materialize") { Lift(place, indent); return; }
                if (place.Kind is "virtual-base-adjustment" or "member" or "lifetime-scope" or "volatile-place")
                {
                    Place(body.Child(place.Id, "operand")); return;
                }
                if (place.Kind == "dereference") { Value(body.Child(place.Id, "operand")); return; }
                throw new InvalidDataException("Unsupported lifted place " + place.Kind);
            }
            if (NeedsExpansion(node))
            {
                if (node.Kind == "block-copy")
                {
                    if (node.EvaluationOrder == "right-to-left") { Place(body.Child(node.Id, "source")); Place(body.Child(node.Id, "target")); }
                    else { Place(body.Child(node.Id, "target")); Place(body.Child(node.Id, "source")); }
                }
                else if (node.Kind is "assign" or "record-transfer" or "record-constant-init" or "compound-assign")
                {
                    if (node.EvaluationOrder == "right-to-left") { Value(body.Child(node.Id, "value")); Place(body.Child(node.Id, "target")); }
                    else { Place(body.Child(node.Id, "target")); Value(body.Child(node.Id, "value")); }
                }
                else if (node.Kind is "address" or "array-decay" or "volatile-place" or "mutate") Place(body.Child(node.Id, "operand"));
                else if (node.Kind == "member") Place(body.Child(node.Id, "operand"));
                else
                {
                    IEnumerable<Edge> children = body.Edges.GetValueOrDefault(node.Id, []).Where(edge => body.Nodes[edge.ChildId].TypeId != null)
                        .OrderBy(edge => edge.Role switch { "operand" or "left" => 0, "right" => 1, "argument" => 2, _ => 3 }).ThenBy(edge => edge.Ordinal);
                    if (node.EvaluationOrder == "right-to-left") children = children.Reverse();
                    foreach (Edge edge in children) Value(body.Nodes[edge.ChildId]);
                }
            }
            Node? unalignedTarget = node.Kind is "assign" or "record-transfer" or "record-constant-init" or "compound-assign" ? body.Child(node.Id, "target")
                : node.Kind == "mutate" ? body.Child(node.Id, "operand") : null;
            if (unalignedTarget is not null && accessAlignment.NeedsUnaligned(unalignedTarget))
            {
                string type = NodeType(node), address = allocator.Allocate("__unaligned_address", "address");
                Line(indent, "void* " + address + " = " + Address(unalignedTarget) + ";");
                string value;
                if (node.Kind is "assign" or "record-transfer" or "record-constant-init") value = Expression(body.Child(node.Id, "value"));
                else
                {
                    string old = allocator.Allocate("__previous", "previous");
                    Line(indent, Type(type) + " " + old + " = " + UnalignedRead(type, address) + ";");
                    if (node.Kind == "mutate")
                    {
                        value = "unchecked((" + Type(type) + ")(" + old + (node.Operator is "pre-inc" or "post-inc" ? " + " : " - ") + (ScalarTypes.IsZeroStridePointer(type) ? "0))" : "1))");
                        if (node.Operator is "post-inc" or "post-dec" && !discard)
                            Line(indent, Type(type) + " " + result + " = " + old + ";");
                    }
                    else
                    {
                        Node rhs = body.Child(node.Id, "value");
                        string op = node.Operator switch { "add" or "pointer-add" => "+", "sub" or "pointer-subtract" => "-", "mul" => "*", "div" => "/", "rem" => "%", "bit-and" => "&", "bit-or" => "|", "bit-xor" => "^", "shl" => "<<", "shr" => ">>", _ => throw new InvalidDataException("Invalid compound operator") };
                        value = CompoundValue(type, NodeType(rhs), op, old, Expression(rhs));
                    }
                }
                string stored = node.Kind == "mutate" && node.Operator is "post-inc" or "post-dec" ? allocator.Allocate("__updated", "updated") : result;
                Line(indent, Type(type) + " " + stored + " = " + value + ";");
                Line(indent, UnalignedWrite(type, address, stored) + ";");
                foreach (long id in changed) liftedExpressions.Remove(id);
                return discard ? "" : result;
            }
            string rendered = discard || NodeType(node) == "void" ? StatementExpression(node) : Expression(node);
            foreach (long id in changed) liftedExpressions.Remove(id);
            if (discard || NodeType(node) == "void") { Line(indent, rendered + ";"); return ""; }
            Line(indent, Type(NodeType(node)) + " " + result + " = " + rendered + ";");
            return result;
        }
        // Reuse the same verified action chain for function exit and a failed
        // throw initializer. Advancing before the callback prevents double cleanup.
        void UnwindCleanup(int indent, string boundary)
        {
            string secondary = allocator.Allocate("__cleanup_failure", "cleanup_failure");
            string transfer = allocator.Allocate("__cleanup_transfer", "cleanup_transfer");
            string pending = allocator.Allocate("__pending_transfer", "pending_transfer");
            Line(indent, "global::System.Exception? " + pending + " = null;");
            Line(indent, "try"); Line(indent, "{");
            Line(indent + 1, "while (" + cleanupState + " != " + boundary + ")"); Line(indent + 1, "{");
            Line(indent + 2, "try"); Line(indent + 2, "{");
            Line(indent + 3, "switch (" + cleanupState + ")"); Line(indent + 3, "{");
            foreach (CleanupState state in obj.FunctionCleanupStates[function.Id].OrderBy(state => state.Id))
            {
                Line(indent + 4, "case " + state.Id + "L:");
                Line(indent + 5, cleanupState + " = " + (state.NextStateId ?? 0) + "L;");
                if (state.HandlerNodeId is long handlerId)
                {
                    Line(indent + 5, ExceptionRuntime + ".LeaveCatch(" + handlerNames[handlerId] + "!);");
                    Line(indent + 5, "break;"); continue;
                }
                if (state.GuardActionId is long guardActionId)
                {
                    GuardCleanupAction guardAction = obj.GuardCleanupActions[guardActionId];
                    Line(indent + 5, "global::Edg.Runtime.CppGuards.Abort(" + Expression(body.Nodes[guardAction.TargetNodeId]) + ");");
                    Line(indent + 5, "break;"); continue;
                }
                if (state.AllocationActionId is long allocationActionId)
                {
                    AllocationCleanupAction allocation = obj.AllocationCleanupActions[allocationActionId];
                    int allocationIndent = indent + 5;
                    Line(allocationIndent, "{"); ++allocationIndent;
                    if (allocation.ConditionBindingId is long condition)
                    {
                        Line(allocationIndent, "if (" + bindingNames[condition] + " != 0)"); Line(allocationIndent, "{"); ++allocationIndent;
                    }
                    string pointer = allocator.Allocate("__allocation_rollback", "allocation_rollback");
                    Line(allocationIndent, "void* " + pointer + " = " + Expression(body.Nodes[allocation.TargetNodeId]) + ";");
                    string size = allocation.AllocationSize is long extent ? ", " + extent + "UL" : "";
                    Line(allocationIndent, "if (" + pointer + " != null) " + FunctionReference(linker.Resolve(obj, allocation.CallbackEntityId)) + "(" + pointer + size + ");");
                    if (allocation.ConditionBindingId is not null) Line(--allocationIndent, "}");
                    Line(--allocationIndent, "}"); Line(indent + 5, "break;"); continue;
                }
                CleanupAction action = obj.CleanupActions[state.ActionId!.Value];
                int actionIndent = indent + 5;
                if (obj.CleanupPayloadOwners.TryGetValue(action.Id, out long payloadOwner))
                {
                    Line(actionIndent, "if (!" + cleanupPayloadComplete[payloadOwner] + ")"); Line(actionIndent, "{");
                    ++actionIndent;
                }
                if (obj.CleanupConditions.TryGetValue(action.Id, out long flag))
                {
                    Line(actionIndent, "if (" + bindingNames[flag] + " != 0)"); Line(actionIndent, "{");
                    ++actionIndent;
                }
                string callback = FunctionReference(linker.Resolve(obj, action.CallbackEntityId));
                string target = Expression(body.Nodes[action.TargetNodeId]);
                if (obj.CleanupArrays.TryGetValue(action.Id, out CleanupArray? array))
                {
                    string callbackType = FunctionPointerType(obj.Type(obj.Entities[action.CallbackEntityId].RoutineTypeId));
                    Line(actionIndent, "global::Edg.Runtime.CppArrays.Cleanup(" + target + ", " + array.ElementCount + "UL, " + array.ElementSize +
                        "UL, (delegate* managed<void*, void>)(" + callbackType + ")(&" + callback + "));");
                }
                else
                {
                    string vtt = obj.CleanupVttArguments.TryGetValue(action.Id, out long binding) ? ", " + bindingNames[binding] : "";
                    Line(actionIndent, callback + "(" + target + vtt + ");");
                }
                if (obj.CleanupConditions.ContainsKey(action.Id)) Line(--actionIndent, "}");
                if (obj.CleanupPayloadOwners.ContainsKey(action.Id)) Line(--actionIndent, "}");
                Line(indent + 5, "break;");
            }
            Line(indent + 4, "default:");
            Line(indent + 5, "global::System.Environment.FailFast(\"Invalid owned cleanup state\");");
            Line(indent + 5, "break;");
            Line(indent + 3, "}"); Line(indent + 2, "}");
            Line(indent + 2, "catch (global::System.Exception " + transfer + ") when (global::Edg.Runtime.ObjectProgram.IsRuntimeTransfer(" + transfer + "))");
            Line(indent + 2, "{"); Line(indent + 3, pending + " = " + transfer + ";"); Line(indent + 2, "}");
            Line(indent + 1, "}");
            Line(indent + 1, "if (" + pending + " != null) throw " + pending + ";");
            Line(indent, "}");
            Line(indent, "catch (global::System.Exception " + secondary + ") when (global::Edg.Runtime.ObjectProgram.TerminateCleanupFailure(" + secondary + "))");
            Line(indent, "{"); Line(indent + 1, "throw;"); Line(indent, "}");
        }
        void Discard(Node expression, int indent)
        {
            if (expression.Kind is "virtual-base-adjustment" or "lifetime-scope") { Discard(body.Child(expression.Id, "operand"), indent); return; }
            if (expression.Kind == "internal-try-expression")
            {
                string boundary = hasCleanup ? allocator.Allocate("__initialization_boundary", "initialization_boundary") : "0L";
                string error = allocator.Allocate("__initialization_error", "initialization_error");
                Line(indent, "{");
                if (hasCleanup) Line(indent + 1, "long " + boundary + " = " + cleanupState + ";");
                Line(indent + 1, "try"); Line(indent + 1, "{");
                Discard(body.Child(expression.Id, "attempt"), indent + 2);
                Line(indent + 1, "}");
                Line(indent + 1, "catch (global::System.Exception " + error + ") when (!global::Edg.Runtime.ObjectProgram.IsRuntimeTransfer(" + error + "))");
                Line(indent + 1, "{");
                if (hasCleanup) UnwindCleanup(indent + 2, boundary);
                Discard(body.Child(expression.Id, "cleanup"), indent + 2);
                Line(indent + 2, "throw;"); Line(indent + 1, "}");
                Line(indent, "}"); return;
            }
            if (expression.Kind == "throw")
            {
                ThrowExpression thrown = obj.ThrowExpressions[expression.Id];
                ExceptionType descriptor = obj.ExceptionTypes[thrown.ExceptionTypeId];
                string carrier = throwCarrierNames[expression.Id], error = allocator.Allocate("__throw_error", "throw_error");
                string destructor = thrown.DestructorEntityId is long callback
                    ? "&" + exceptionDestructorNames[(obj, callback)] : "(delegate* managed<void*, void>)0";
                string boundary = hasCleanup ? allocator.Allocate("__throw_cleanup_boundary", "throw_cleanup_boundary") : "0L";
                Line(indent, "{");
                if (hasCleanup) Line(indent + 1, "long " + boundary + " = " + cleanupState + ";");
                Line(indent + 1, "var " + carrier + " = " + ExceptionRuntime + ".Allocate(" + exceptionDescriptorNames[descriptor.IdentityKey] + ", " + destructor + ");");
                if (cleanupPayloadNames.TryGetValue(expression.Id, out string? payloadAddress))
                {
                    Line(indent + 1, payloadAddress + " = " + carrier + ".ObjectAddress;");
                    Line(indent + 1, cleanupPayloadComplete[expression.Id] + " = false;");
                }
                Line(indent + 1, "try"); Line(indent + 1, "{");
                if (thrown.InitializationKind == "expression") Discard(body.Child(expression.Id, "initializer"), indent + 2);
                Line(indent + 2, ExceptionRuntime + ".EnsureStarted(" + carrier + ");");
                Line(indent + 2, ExceptionRuntime + ".MarkComplete(" + carrier + ");");
                if (payloadAddress is not null) Line(indent + 2, cleanupPayloadComplete[expression.Id] + " = true;");
                Line(indent + 2, "throw " + carrier + ";");
                Line(indent + 1, "}");
                Line(indent + 1, "catch (global::System.Exception " + error + ") when (" + ExceptionRuntime + ".FilterInitializationFailure(" + carrier + ", " + error + "))");
                Line(indent + 1, "{");
                if (hasCleanup) UnwindCleanup(indent + 2, boundary);
                Line(indent + 2, ExceptionRuntime + ".ReleaseIncomplete(" + carrier + ");");
                if (payloadAddress is not null) Line(indent + 2, payloadAddress + " = null;");
                Line(indent + 2, "throw;"); Line(indent + 1, "}");
                Line(indent + 1, "finally { global::System.GC.KeepAlive(" + carrier + "); }");
                Line(indent, "}"); return;
            }
            if (expression.Kind == "throw-marker")
            {
                Line(indent, ExceptionRuntime + ".EnsureStarted(" + throwCarrierNames[obj.ThrowMarkers[expression.Id]] + ");"); return;
            }
            if (expression.Kind == "handler-marker")
            {
                HandlerMarker marker = obj.HandlerMarkers[expression.Id];
                Line(indent, marker.Kind == "try-exit" ? tryNames[marker.OwnerNodeId] + " = false;"
                    : ExceptionRuntime + (marker.Kind == "caught" ? ".MarkCaught(" : ".LeaveCatch(") + handlerNames[marker.OwnerNodeId] + "!);");
                return;
            }
            if (expression.Kind == "rethrow") { Line(indent, "throw " + ExceptionRuntime + ".Rethrow();"); return; }
            if (expression.Kind == "cleanup-frame") return;
            if (expression.Kind == "cleanup-transition")
            {
                CleanupTransition transition = obj.CleanupTransitions[expression.Id];
                if (!transition.IsUnreachable && hasCleanup)
                    Line(indent, cleanupState + " = " + (transition.StateId ?? 0) + "L;");
                return;
            }
            if (NeedsExpansion(expression)) { Lift(expression, indent, true); return; }
            Node? volatileTarget = expression.Kind == "compound-assign" ? body.Child(expression.Id, "target")
                : expression.Kind == "mutate" ? body.Child(expression.Id, "operand") : null;
            if (volatileTarget?.Kind == "volatile-place" && !DirectVolatile(volatileTarget))
            {
                string type = NodeType(expression), address = allocator.Allocate("__volatile_address", "volatile_address"), value = allocator.Allocate("__volatile_value", "volatile_value");
                Line(indent, "{"); Line(indent + 1, Type(type) + "* " + address + " = " + Address(volatileTarget) + ";");
                if (expression.Kind == "compound-assign")
                {
                    Node right = body.Child(expression.Id, "value");
                    string argument = allocator.Allocate("__volatile_rhs", "volatile_rhs");
                    Line(indent + 1, Type(NodeType(right)) + " " + argument + " = " + Expression(right) + ";");
                    string op = expression.Operator switch { "add" or "pointer-add" => "+", "sub" or "pointer-subtract" => "-", "mul" => "*", "div" => "/", "rem" => "%", "bit-and" => "&", "bit-or" => "|", "bit-xor" => "^", "shl" => "<<", "shr" => ">>", _ => throw new InvalidDataException("Invalid compound operator") };
                    Line(indent + 1, Type(type) + " " + value + " = " + CompoundValue(type, NodeType(right), op, VolatileRead(type, address), argument) + ";");
                }
                else Line(indent + 1, Type(type) + " " + value + " = unchecked((" + Type(type) + ")(" + VolatileRead(type, address) +
                    (expression.Operator is "pre-inc" or "post-inc" ? " + " : " - ") + (ScalarTypes.IsZeroStridePointer(type) ? "0));" : "1));"));
                Line(indent + 1, VolatileWrite(type, address, value) + ";"); Line(indent, "}"); return;
            }
            if (expression.Kind == "sequence")
                foreach (Edge edge in body.Children(expression.Id, "item")) Discard(body.Nodes[edge.ChildId], indent);
            else if (expression.Kind == "convert" && NodeType(expression) == "void") Discard(body.Child(expression.Id, "operand"), indent);
            else Line(indent, StatementExpression(expression) + ";");
        }
        void Statement(Node node, int indent)
        {
            Node Child(string role) => body.Child(node.Id, role);
            switch (node.Kind)
            {
                case "compile-time-if":
                {
                    CompileTimeSelection selection = obj.CompileTimeSelections[node.Id];
                    Line(indent, "// if constexpr: " + (selection.ConditionValue ? "then" : selection.HasElse ? "else" : "no") + " branch selected by C++ semantic analysis.");
                    Statement(Child("body"), indent);
                    break;
                }
                case "try":
                {
                    string active = tryNames[node.Id], boundary = allocator.Allocate("__try_boundary", "try_boundary");
                    string error = allocator.Allocate("__caught_error", "caught_error");
                    Line(indent, "{"); Line(indent + 1, active + " = true;");
                    Line(indent + 1, "long " + boundary + " = " + cleanupState + ";");
                    Line(indent + 1, "try"); Statement(Child("body"), indent + 1);
                    foreach (var edge in body.Children(node.Id, "handler"))
                    {
                        Node handler = body.Nodes[edge.ChildId]; string frame = handlerNames[handler.Id];
                        long? match = obj.SourceHandlers[handler.Id].MatchTypeId;
                        string? descriptor = match is long type ? catchDescriptorNames[obj.ExceptionTypeIdentity(type)] : null;
                        Line(indent + 1, "catch (global::System.Exception " + error + ") when (" + active + " && " + ExceptionRuntime +
                            (descriptor is null ? ".FilterCatchAll(" + error : ".FilterTypedCatch(" + error + ", " + descriptor) + "))");
                        Line(indent + 1, "{"); UnwindCleanup(indent + 2, boundary);
                        Line(indent + 2, frame + " = " + ExceptionRuntime + (descriptor is null ? ".EnterCatch(" + error : ".EnterTypedCatch(" + error + ", " + descriptor) + ");");
                        Line(indent + 2, "try"); Statement(body.Child(handler.Id, "body"), indent + 2);
                        string failure = allocator.Allocate("__handler_error", "handler_error");
                        Line(indent + 2, "catch (global::System.Exception " + failure + ") when (" + ExceptionRuntime + ".FilterHandlerFailure(" + frame + "!, " + failure + ")) { throw; }");
                        Line(indent + 2, "finally"); Line(indent + 2, "{");
                        Line(indent + 3, "if (" + frame + "!.Active)"); Line(indent + 3, "{");
                        UnwindCleanup(indent + 4, boundary);
                        Line(indent + 4, ExceptionRuntime + ".LeaveCatch(" + frame + ");");
                        Line(indent + 3, "}"); Line(indent + 2, "}"); Line(indent + 1, "}");
                    }
                    Line(indent, "}");
                    break;
                }
                case "memory-barrier":
                    Line(indent, "// Empty GNU memory assembly: evaluate operands, then preserve memory ordering.");
                    Node[] addresses = body.Children(node.Id, "address").Select(edge => body.Nodes[edge.ChildId]).ToArray();
                    Node[] extents = body.Children(node.Id, "extent").Select(edge => body.Nodes[edge.ChildId]).ToArray();
                    for (int index = 0; index < addresses.Length; index++)
                    {
                        Line(indent, "_ = (nuint)(" + ExpandedValue(addresses[index], indent) + ");");
                        Line(indent, "_ = " + ExpandedValue(extents[index], indent) + ";");
                    }
                    Line(indent, "global::System.Threading.Thread.MemoryBarrier();");
                    break;
                case "record-storage-init":
                    if (obj.RecordStorageInitializations[node.Id].ZeroStorage)
                        Line(indent, Location(Child("target")) + " = default;");
                    BlockContents(Child("body"), indent);
                    break;
                case "array-init": ArrayInitialize(node, indent); break;
                case "block":
                    Line(indent, "{");
                    BlockContents(node, indent + 1);
                    Line(indent, "}"); break;
                case "return":
                    if (!body.Children(node.Id, "value").Any()) Line(indent, "return;");
                    else if (NodeType(Child("value")) == "void") { Discard(Child("value"), indent); Line(indent, "return;"); }
                    else Line(indent, "return " + ExpandedValue(Child("value"), indent) + ";");
                    break;
                case "expr-stmt":
                    // C# only allows a subset of expressions as statement expressions.
                    Discard(Child("value"), indent);
                    break;
                case "declare":
                    Binding binding = body.Bindings[node.BindingId!.Value];
                    if (body.CleanupCapturedBindings.Contains(binding.Id))
                    {
                        if (body.Children(node.Id, "initializer").Any())
                            Line(indent, bindingNames[binding.Id] + " = " + ExpandedValue(Child("initializer"), indent) + ";");
                        break;
                    }
                    if (alignedPointers.ContainsKey(binding.Id))
                    {
                        Line(indent, "ref " + Type(obj.Type(binding.TypeId)) + " " + bindingNames[binding.Id] + " = ref *" + alignedPointers[binding.Id] + ";");
                        Line(indent, bindingNames[binding.Id] + " = " + (body.Children(node.Id, "initializer").Any() ? ExpandedValue(Child("initializer"), indent) : "default") + ";");
                        break;
                    }
                    Line(indent, Type(obj.Type(binding.TypeId)) + " " + bindingNames[binding.Id] + " = " +
                        (body.Children(node.Id, "initializer").Any() ? ExpandedValue(Child("initializer"), indent) : "default") + ";"); break;
                case "if":
                    Line(indent, "if (" + ExpandedTruth(Child("condition"), indent) + ")"); ControlBody(Child("then"), indent);
                    if (body.Children(node.Id, "else").Any()) { Line(indent, "else"); ControlBody(Child("else"), indent); }
                    break;
                case "while":
                    if (!NeedsExpansion(Child("condition"))) { Line(indent, "while (" + Truth(Child("condition")) + ")"); ControlBody(Child("body"), indent); break; }
                    Line(indent, "while (true)"); Line(indent, "{");
                    Line(indent + 1, "if (!(" + ExpandedTruth(Child("condition"), indent + 1) + ")) break;");
                    ControlBody(Child("body"), indent + 1); Line(indent, "}"); break;
                case "for":
                    if (new[] { "initializer", "condition", "step" }.Any(role => body.Children(node.Id, role).Any() && NeedsExpansion(Child(role))))
                    {
                        if (body.Children(node.Id, "initializer").Any()) Discard(Child("initializer"), indent);
                        string stepLabel = allocator.Allocate("__for_step", "for_step"); continueLabels.Add(node.Id, stepLabel);
                        Line(indent, "for (;;)"); Line(indent, "{");
                        if (body.Children(node.Id, "condition").Any()) Line(indent + 1, "if (!(" + ExpandedTruth(Child("condition"), indent + 1) + ")) break;");
                        ControlBody(Child("body"), indent + 1); Line(indent + 1, stepLabel + ":;");
                        if (body.Children(node.Id, "step").Any()) Discard(Child("step"), indent + 1);
                        Line(indent, "}"); continueLabels.Remove(node.Id); break;
                    }
                    string Header(string role) => body.Children(node.Id, role).Any()
                        ? role == "condition" ? Truth(Child(role)) : StatementExpression(Child(role)) : "";
                    Line(indent, "for (" + Header("initializer") + "; " + Header("condition") + "; " + Header("step") + ")");
                    ControlBody(Child("body"), indent);
                    break;
                case "do-while":
                    if (NeedsExpansion(Child("condition")))
                    {
                        string conditionLabel = allocator.Allocate("__do_condition", "do_condition"), conditionValue = allocator.Allocate("__do_again", "do_again");
                        continueLabels.Add(node.Id, conditionLabel); Line(indent, "bool " + conditionValue + ";");
                        Line(indent, "do"); Line(indent, "{"); ControlBody(Child("body"), indent + 1);
                        Line(indent + 1, conditionLabel + ":;");
                        Line(indent + 1, conditionValue + " = " + ExpandedTruth(Child("condition"), indent + 1) + ";");
                        Line(indent, "}"); Line(indent, "while (" + conditionValue + ");"); continueLabels.Remove(node.Id); break;
                    }
                    Line(indent, "do"); ControlBody(Child("body"), indent);
                    Line(indent, "while (" + Truth(Child("condition")) + ");");
                    break;
                case "switch": Switch(node, indent); break;
                case "label": Line(indent, labelNames[node.Id] + ":;"); break;
                case "goto": Line(indent, "goto " + labelNames[Child("target").Id] + ";"); break;
                case "break": Line(indent, "break;"); break;
                case "continue": Line(indent, continueLabels.TryGetValue(Child("target").Id, out string? continuation) ? "goto " + continuation + ";" : "continue;"); break;
                default: throw new InvalidDataException("Unsupported statement " + node.Kind);
            }
        }
        var parameters = body.Bindings.Values.Where(binding => binding.Kind == "parameter").OrderBy(binding => binding.Ordinal);
        Line(1, (function.Linkage == "external" ? "public" : "private") + " static " + Type(obj.Type(function.ReturnTypeId)) + " " + linker.Names[symbol.Key] + "(" +
            string.Join(", ", parameters.Select(binding => Type(obj.Type(binding.TypeId)) + " " + parameterNames[binding.Id])
                .Concat(variadicFunction ? ["params global::System.ReadOnlySpan<global::Edg.Runtime.VaArg> " + vaInput] : [])) + ")");
        Line(1, "{");
        if (terminate) { Line(2, "try"); Line(2, "{"); }
        foreach (var (id, pointer) in alignedPointers)
        {
            Binding binding = body.Bindings[id]; string type = obj.Type(binding.TypeId);
            long alignment = obj.StorageAlignment(type);
            if (obj.StorageSize(type) > int.MaxValue - alignment + 1) throw new InvalidDataException("Aligned local allocation exceeds supported stack extent");
            string raw = allocator.Allocate("__allocation_" + binding.SourceName, "aligned_allocation");
            Line(outerBodyIndent, "byte* " + raw + " = stackalloc byte[" + checked(obj.StorageSize(type) + alignment - 1) + "];");
            Line(outerBodyIndent, Type(type) + "* " + pointer + " = (" + Type(type) + "*)(((nuint)" + raw + " + " + (alignment - 1) + ") & ~(nuint)" + (alignment - 1) + ");");
            if (binding.Kind == "parameter")
            {
                Line(outerBodyIndent, "ref " + Type(type) + " " + bindingNames[id] + " = ref *" + pointer + ";");
                Line(outerBodyIndent, bindingNames[id] + " = " + parameterNames[id] + ";");
            }
        }
        foreach (var (id, name) in materializedNames)
        {
            string type = NodeType(body.Nodes[id]);
            if (materializedPointers.TryGetValue(id, out string? pointer))
            {
                long alignment = obj.StorageAlignment(type), size = obj.StorageSize(type);
                if (size > int.MaxValue - alignment + 1) throw new InvalidDataException("Materialized record exceeds supported aligned stack extent");
                string raw = allocator.Allocate("__materialized_allocation", "materialized_allocation");
                Line(outerBodyIndent, "byte* " + raw + " = stackalloc byte[" + checked(size + alignment - 1) + "];");
                Line(outerBodyIndent, Type(type) + "* " + pointer + " = (" + Type(type) + "*)(((nuint)" + raw + " + " + (alignment - 1) + ") & ~(nuint)" + (alignment - 1) + ");");
                Line(outerBodyIndent, "ref " + Type(type) + " " + name + " = ref *" + pointer + ";");
            }
            else Line(outerBodyIndent, Type(type) + " " + name + " = default;");
        }
        if (variadicFunction)
        {
            Line(outerBodyIndent, "int " + vaBytes + " = global::Edg.Runtime.VaPack.GetStackBytes(" + vaInput + ");");
            Line(outerBodyIndent, "byte* " + vaWorkspace + " = stackalloc byte[" + vaBytes + "];");
            Line(outerBodyIndent, "using var " + vaPack + " = new global::Edg.Runtime.VaPack(" + vaInput + ", " + vaWorkspace + ", " + vaBytes + ");");
            Line(outerBodyIndent, "global::Edg.Runtime.VaList " + vaArguments + " = " + vaPack + ".Value;");
        }
        if (hasCleanup)
        {
            foreach (string active in tryNames.Values) Line(outerBodyIndent, "bool " + active + " = false;");
            foreach (string frame in handlerNames.Values) Line(outerBodyIndent, "global::Edg.Runtime.CppCatch? " + frame + " = null;");
            foreach (long id in body.CleanupCapturedBindings.Order())
            {
                Binding binding = body.Bindings[id];
                if (binding.Kind == "local") Line(outerBodyIndent, LocalDeclaration(binding));
            }
            foreach (string address in cleanupPayloadNames.Values)
                Line(outerBodyIndent, "void* " + address + " = null;");
            foreach (string complete in cleanupPayloadComplete.Values)
                Line(outerBodyIndent, "bool " + complete + " = false;");
            Line(outerBodyIndent, "long " + cleanupState + " = 0L;");
            Line(outerBodyIndent, "bool " + cleanupUnwinding + " = false;");
            Line(outerBodyIndent, "try"); Line(outerBodyIndent, "{");
        }
        if (body.RequiresFlatControl) FlatControl(obj, body, bodyIndent, allocator, bindingNames, LocalDeclaration, node => ExpandedValue(node, bodyIndent), node => ExpandedTruth(node, bodyIndent), Line, Statement, Discard);
        else BlockContents(body.Nodes[body.RootId], bodyIndent);
        bool SwitchFallsThrough(Node node)
        {
            Node[] items = body.Children(body.Child(node.Id, "body").Id, "statement")
                .Select(edge => body.Nodes[edge.ChildId]).ToArray();
            if (!items.Any(item => item.Kind == "case" && !body.Children(item.Id, "value").Any())) return true;
            // Explicit break paths can complete the switch. Without those,
            // every normal fallthrough ultimately enters the final section.
            if (body.Nodes.Values.Any(item => item.Kind == "break" && body.Child(item.Id, "target").Id == node.Id)) return true;
            int lastLabel = Array.FindLastIndex(items, item => item.Kind == "case");
            return items.Skip(lastLabel + 1).All(FallsThrough);
        }
        bool FallsThrough(Node node) => node.Kind switch
        {
            "return" or "break" or "continue" or "goto" => false,
            "expr-stmt" when TerminalThrow(body.Child(node.Id, "value")) => false,
            "expr-stmt" when body.Child(node.Id, "value").Kind == "intrinsic" && body.Child(node.Id, "value").Operator == "unreachable" => false,
            "switch" => SwitchFallsThrough(node),
            "block" => body.Children(node.Id, "statement").All(edge => FallsThrough(body.Nodes[edge.ChildId])),
            "if" => !body.Children(node.Id, "else").Any() || FallsThrough(body.Child(node.Id, "then")) || FallsThrough(body.Child(node.Id, "else")),
            _ => true
        };
        if (obj.Type(function.ReturnTypeId) != "void" && (body.RequiresFlatControl || FallsThrough(body.Nodes[body.RootId])))
            Line(bodyIndent, "throw new global::System.InvalidOperationException(\"Reached end of a non-void source function\");");
        if (hasCleanup)
        {
            string error = allocator.Allocate("__cleanup_error", "cleanup_error");
            Line(outerBodyIndent, "}");
            Line(outerBodyIndent, "catch (global::System.Exception " + error + ") when (global::Edg.Runtime.ObjectProgram.BeginUnwind(" + error + ", ref " + cleanupUnwinding + "))");
            Line(outerBodyIndent, "{"); Line(outerBodyIndent + 1, "throw;"); Line(outerBodyIndent, "}");
            Line(outerBodyIndent, "finally"); Line(outerBodyIndent, "{");
            Line(outerBodyIndent + 1, "if (" + cleanupUnwinding + ")"); Line(outerBodyIndent + 1, "{");
            UnwindCleanup(outerBodyIndent + 2, "0L");
            Line(outerBodyIndent + 1, "}"); Line(outerBodyIndent, "}");
        }
        if (terminate)
        {
            string error = allocator.Allocate("__noexcept_error", "noexcept_error");
            Line(2, "}"); Line(2, "catch (global::System.Exception " + error + ") when (!global::Edg.Runtime.ObjectProgram.IsRuntimeTransfer(" + error + "))"); Line(2, "{");
            Line(3, "global::System.Environment.FailFast(\"Exception escaped noexcept function\", " + error + ");");
            Line(3, "throw;"); Line(2, "}");
        }
        Line(1, "}"); Line(0, "");
        output.Append(initializers);
    }
