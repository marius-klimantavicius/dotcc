                externalKey = symbol.Entity.ExternalKey, sourceName = symbol.Entity.SourceName, generatedName = linker.Names[symbol.Key], signature = symbol.Signature })
        }, new JsonSerializerOptions { WriteIndented = true }) + "\n");
