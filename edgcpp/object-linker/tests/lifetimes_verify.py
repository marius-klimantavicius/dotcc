"""Bounded lexical cleanup acceptance, called by the full object suite."""
import json
import sqlite3


def verify(inputs, out, tool, run, check, compile_source, link, execute):
    objects = []
    for language, standard, suffix, extension, native in [
        ('cpp', 'c++17', '', '.cpp', 'c++'), ('c', 'c11', '-c', '.c', 'cc')]:
        provider_name, consumer_name = 'lifetime-provider' + suffix, 'lifetimes' + suffix
        provider = compile_source(provider_name, inputs / (provider_name + extension), std=standard)
        consumer = compile_source(consumer_name, inputs / (consumer_name + extension), std=standard)
        run('native-lifetimes-' + language + '-build', [native, '-std=' + standard,
            inputs / (provider_name + extension), inputs / (consumer_name + extension),
            '-o', out / ('native-lifetimes-' + language)])
        run('native-lifetimes-' + language + '-run', [out / ('native-lifetimes-' + language)])
        directory = link('link-lifetimes-' + language, [provider, consumer])
        execute('lifetimes-' + language, directory)
        objects.append((provider, consumer))
        with sqlite3.connect(consumer) as db:
            check('cleanup-activation-count-' + language, db.execute(
                "SELECT count(*) FROM nodes WHERE kind='register-cleanup'").fetchone()[0] >= 16)
            check('cleanup-lexical-block-ownership-' + language, db.execute(
                "SELECT count(*) FROM nodes n JOIN bindings b ON b.id=n.binding_id "
                "JOIN edges e ON e.child_id=n.id WHERE n.kind='register-cleanup' "
                "AND (e.parent_id<>b.scope_node_id OR e.role<>'statement')").fetchone()[0] == 0)
            check('cleanup-callee-is-owned-entity-' + language, db.execute(
                "SELECT count(*) FROM nodes n JOIN entities e ON e.id=n.entity_id "
                "WHERE n.kind='register-cleanup' AND e.definition='declaration'").fetchone()[0] >= 16)
        cs = '\n'.join(p.read_text() for p in directory.glob('Translated.*.cs'))
        check('cleanup-structured-finally-' + language, 'finally' in cs and 'try' in cs
              and 'goto ' not in cs and '__edg_' not in cs and 'GC.Allocate' not in cs)
        report = json.loads((directory / 'link-report.json').read_text())
        check('bounded-lifetime-capabilities-' + language,
              report['capabilities']['lexicalCleanups'] and not report['capabilities']['lifetimes'])
        lifetime_map = json.loads((directory / 'lifetime-map.json').read_text())
        regions = [region for obj in lifetime_map['objects'] for function in obj['functions']
                   for region in function['regions']]
        check('lifetime-map-published-' + language, len(regions) >= 16
              and all(region['protectedSuffixStartOrdinal'] == region['activationOrdinal'] + 1
                      and region['protectedSuffixEndExclusiveOrdinal'] >= region['protectedSuffixStartOrdinal']
                      for region in regions))

    provider, consumer = objects[0]
    # Inject CLR exceptions via integral division. Zero-divisor source execution
    # is deliberately not compared with C/C++ (where it is undefined); this tests
    # the emitted finally mechanism and successful-initialization boundary only.
    exceptional = link('link-lifetimes-managed-failure', [provider, consumer])
    program = exceptional / 'Entry.generated.cs'
    if not program.exists():
        raise RuntimeError('Expected generated host filename for lifetime injection')
    program.write_text('''// <auto-generated />
using System;
internal static unsafe class __DotObjEntry
{
    private static int Main()
    {
        int trace = 0;
        try { Tests.Linked.Core.lifetime_failure(&trace, 0, 1); return 1; }
        catch (DivideByZeroException) { if (trace != 1) return 2; }
        trace = 0;
        try { Tests.Linked.Core.lifetime_failure(&trace, 0, 0); return 3; }
        catch (DivideByZeroException) { if (trace != 21) return 4; }
        return 0;
    }
}
''')
    execute('lifetimes-managed-failure', exceptional)

    missing = inputs / 'cleanup-missing.cpp'
    missing.write_text('void missing(int**); int main(){int x=0; '
                       'int* guard __attribute__((cleanup(missing)))=&x;return 0;}\n')
    missing_object = compile_source('cleanup-missing', missing)
    link('link-cleanup-missing', [missing_object], expected=None, contains='Unresolved function')

    # Same-spelled TU-local callbacks must not alias during linking.
    internal_objects = []
    for name, digit in [('left', 1), ('right', 2)]:
        source = inputs / ('cleanup-internal-' + name + '.cpp')
        source.write_text('static void local_cleanup(int** value){**value=**value*10+'
            + str(digit) + ';}\nvoid ' + name + '(int* trace){int* guard '
            '__attribute__((cleanup(local_cleanup)))=trace;}\n')
        internal_objects.append(compile_source('cleanup-internal-' + name, source))
    main = inputs / 'cleanup-internal-main.cpp'
    main.write_text('void left(int*);void right(int*);int main(){int trace=0;'
                    'left(&trace);right(&trace);return trace==12?0:1;}\n')
    internal_objects.append(compile_source('cleanup-internal-main', main))
    execute('cleanup-internal', link('link-cleanup-internal', internal_objects))

    # With source exceptions disabled EDG has already materialized this normal
    # destructor call. Receiver support now lets us preserve and execute it;
    # Exact normal destruction provenance accounts for the source obligation
    # without adding exception cleanup to a no-exceptions translation.
    normal_destructor = inputs / 'cleanup-cpp-normal-destructor.cpp'
    normal_destructor.write_text('struct Guard{int* p;~Guard(){++*p;}}; '
        'int f(){int value=0;{Guard g{&value};}return value;} '
        'int main(){return f()==1?0:1;}\n')
    normal_object = compile_source('cleanup-cpp-normal-destructor', normal_destructor)
    run('cleanup-cpp-normal-destructor-native-build', ['c++', '-std=c++17', '-fno-exceptions',
        normal_destructor, '-o', out / 'cleanup-cpp-normal-destructor-native'])
    run('cleanup-cpp-normal-destructor-native', [out / 'cleanup-cpp-normal-destructor-native'])
    execute('cleanup-cpp-normal-destructor', link('link-cleanup-cpp-normal-destructor', [normal_object]))

    exceptional_destructor = inputs / 'cleanup-cpp-exceptional-destructor.cpp'
    exceptional_destructor.write_text('extern void may_throw(); struct Guard{int* p;~Guard(){++*p;}}; '
        'int f(){int value=0;{Guard g{&value};may_throw();}return value;}\n')
    exceptional = compile_source('cleanup-cpp-exceptional-destructor', exceptional_destructor,
                                  extra=['--exceptions', '--rtti'])
    run('cleanup-exceptional-destructor-verify', ['dotnet', tool, 'verify', exceptional])
    with sqlite3.connect(normal_object) as db:
        check('cleanup-normal-destruction-provenance', db.execute('SELECT count(*) FROM normal_destructions').fetchone()[0] > 0)
    with sqlite3.connect(exceptional) as db:
        check('cleanup-exceptional-destruction-provenance', db.execute('SELECT count(*) FROM cleanup_actions').fetchone()[0] > 0)

    for name, standard, code in [
        ('mixed-uninitialized', 'c++17', 'void drop(int*); int f(){int guard __attribute__((cleanup(drop))), value=1;return value;}'),
        ('split-array-initialization', 'c++17', 'void drop(int (*)[3]); int next(); int f(){int values[3] __attribute__((cleanup(drop)))={next(),next()};return values[0];}'),
        ('switch-dispatch', 'c11', 'void drop(int**); int f(int choice,int* p){switch(choice){case 1:; int* guard __attribute__((cleanup(drop)))=p;return 1;default:return 0;}}'),
    ]:
        source = inputs / ('cleanup-unsupported-' + name + ('.c' if standard == 'c11' else '.cpp'))
        source.write_text(code + '\n')
        obj = compile_source('cleanup-unsupported-' + name, source, std=standard, expected=None)
        check('cleanup-not-published-' + name, not obj.exists())
    return consumer


def malformed(consumer, tool, run, mutate):
    with sqlite3.connect(consumer) as db:
        ids = db.execute("SELECT n.id,n.binding_id,n.entity_id FROM nodes n JOIN entities e "
                         "ON e.id=n.function_id WHERE n.kind='register-cleanup' "
                         "AND e.source_name='lifetime_return' ORDER BY n.id").fetchall()
        first, second = ids
        wrong_callback = db.execute("SELECT id FROM entities WHERE source_name='return_event'").fetchone()[0]
        root = db.execute("SELECT scope_node_id FROM bindings WHERE id=?", (first[1],)).fetchone()[0]
        foreign_binding = db.execute("SELECT id FROM bindings WHERE function_id<>"
                                    "(SELECT function_id FROM nodes WHERE id=?) LIMIT 1", (first[0],)).fetchone()[0]
    for name, statements in [
        ('cleanup-duplicate-activation', [("UPDATE nodes SET binding_id=? WHERE id=?", (first[1], second[0]))]),
        ('cleanup-invalid-callback', [("UPDATE nodes SET entity_id=? WHERE id=?", (wrong_callback, first[0]))]),
        ('cleanup-foreign-binding', [("UPDATE nodes SET binding_id=? WHERE id=?", (foreign_binding, first[0]))]),
        ('cleanup-payload', [("UPDATE nodes SET constant_text='0' WHERE id=?", (first[0],))]),
        ('cleanup-wrong-scope', [("UPDATE bindings SET scope_node_id=(SELECT id FROM nodes WHERE kind='block' AND id<>? LIMIT 1) WHERE id=?", (root, first[1]))]),
    ]:
        obj = mutate(name, consumer, statements)
        run('reject-' + name, ['dotnet', tool, 'verify', obj], None)
