#!/usr/bin/env python3
"""Run the established SQLite host tests against a fully bound dotobj library.

The static dotobj ABI has no independent engine owners yet. Reuse the canonical
host's API tests, excluding owner-isolation and direct-backend-only VFS counters.
No translated engine or runtime implementation is patched by this runner.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
from xml.sax.saxutils import escape

EDG = Path(__file__).resolve().parents[2]
CANONICAL = EDG / 'backend/tests/sqlite_host/Program.cs'


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def consumer():
    source = CANONICAL.read_text()
    # Whole canonical test methods, bounded by stable next-method declarations.
    first = source[:source.index('    private static void IndependentOwners(')]
    second = source[source.index('    private static void Persistence('):source.index('    private static void FileTemporaryStorage(')]
    code = first + second
    line = '            Require(core.Mutexes.DynamicMutexCount == 0, "initialization mutexes released");\n'
    if code.count(line) != 1:
        raise ValueError('Canonical host counter assertion changed')
    code = code.replace(line, '')
    code = code.replace('SqliteCore core, ', '').replace('SqliteCore core', '')
    code = code.replace('core.', '').replace('(core, ', '(').replace('(core)', '()')
    if 'core' in code or 'SqliteCore first' in code:
        raise ValueError('Unadapted owner reference in static test consumer')
    code = '// <auto-generated />\n#nullable enable\nusing System;\nusing System.IO;\nusing System.Linq;\nusing System.Threading;\n' + code
    code += '''
    public static int Main(string[] args)
    {
        try
        {
            string directory = Path.GetFullPath(args.Single());
            Directory.CreateDirectory(directory);
            global::Edg.Runtime.ObjectProgram.InitializeLibrary();
            Initialization();
            Mutexes();
            SharedConnection();
            Persistence(directory);
            SeparateConnections(Path.Combine(directory, "rollback.db"), false);
            SeparateConnections(Path.Combine(directory, "wal.db"), true);
            BackupBlobAndSerialization(directory);
            sqlite3* db = Open(":memory:");
            try
            {
                Require(Query(db, "SELECT datetime(0,'unixepoch','localtime')") == "1970-01-01 00:00:00",
                    "translated musl timezone/environment startup");
                GC.Collect(); GC.WaitForPendingFinalizers(); GC.Collect();
                Require(Query(db, "SELECT 40+2") == "42", "engine globals survive full GC");
            }
            finally { Require(sqlite3_close(db) == 0, "timezone close"); }
            Require(sqlite3_shutdown() == 0, "final shutdown");
            ParallelWorkers(_ => Require(sqlite3_initialize() == 0, "final concurrent restart"));
            Require(sqlite3_shutdown() == 0, "final restarted shutdown");
            Console.WriteLine("PASS dotobj SQLite engine, shared runtime, timezone, GC and restart");
            return 0;
        }
        catch (Exception error) { Console.Error.WriteLine(error); return 1; }
    }
}
'''
    return code


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--project', required=True, type=Path)
    parser.add_argument('--output-dir', required=True, type=Path)
    parser.add_argument('--nativeaot', action='store_true')
    parser.add_argument('--rid', default='linux-x64')
    args = parser.parse_args()
    project, out = args.project.resolve(), args.output_dir.resolve()
    out.mkdir(parents=True, exist_ok=False)
    checks, commands = [], []
    import os
    environment = dict(os.environ, TZ='UTC')

    def run(name, command, timeout=600):
        command = [str(item) for item in command]
        log = out / (name + '.log')
        with log.open('w') as stream:
            result = subprocess.run(command, cwd=out, env=environment, text=True,
                                    stdout=stream, stderr=subprocess.STDOUT, timeout=timeout)
        commands.append(dict(name=name, command=command, exitCode=result.returncode, path=str(log), sha256=sha(log)))
        checks.append(dict(name=name, passed=result.returncode == 0))
        if result.returncode:
            raise ValueError(name + ' failed: ' + str(log))
        return log.read_text()

    failure = None
    try:
        bindings = json.loads((project / 'runtime-bindings.json').read_text())
        if bindings['status'] != 'bound' or bindings['unresolved']:
            raise ValueError('Engine acceptance requires complete real runtime providers')
        for name, digest in bindings['files'].items():
            if sha(project / name) != digest:
                raise ValueError('Runtime output changed: ' + name)
        (out / 'Program.cs').write_text(consumer())
        (out / 'SqliteObjectTests.csproj').write_text('<Project Sdk="Microsoft.NET.Sdk"><PropertyGroup><TargetFramework>net10.0</TargetFramework><OutputType>Exe</OutputType><AllowUnsafeBlocks>true</AllowUnsafeBlocks><Nullable>enable</Nullable><IsAotCompatible>true</IsAotCompatible><DefineConstants>EDG_SQLITE_UNIX</DefineConstants></PropertyGroup><ItemGroup><ProjectReference Include="' + escape(str(project / 'Translated.csproj'), {'"': '&quot;'}) + '" /></ItemGroup></Project>\n')
        run('build', ['dotnet', 'build', out / 'SqliteObjectTests.csproj', '--nologo', '-v:q'])
        output = run('jit', ['dotnet', out / 'bin/Debug/net10.0/SqliteObjectTests.dll', out / 'jit-data'])
        if args.nativeaot:
            run('publish', ['dotnet', 'publish', out / 'SqliteObjectTests.csproj', '-r', args.rid, '-p:PublishAot=true', '-o', out / 'aot', '--nologo', '-v:q'], 1200)
            aot = run('nativeaot', [out / 'aot/SqliteObjectTests', out / 'aot-data'])
            checks.append(dict(name='jit-nativeaot-output-parity', passed=output == aot))
            if output != aot:
                raise ValueError('JIT and NativeAOT outputs differ')
    except Exception as error:
        failure = str(error)
    result = dict(schema=1, status='failed' if failure else 'passed', error=failure,
                  checks=checks, commands=commands, canonicalConsumer=dict(path=str(CANONICAL), sha256=sha(CANONICAL)),
                  providerReceipt=dict(path=str(project / 'runtime-bindings.json'), sha256=sha(project / 'runtime-bindings.json')),
                  nativeAotVerified=args.nativeaot and not failure, timezone='UTC',
                  scope='Actual SQLite engine integration; static per-assembly mode, no independent owner claim')
    (out / 'results.json').write_text(json.dumps(result, indent=2) + '\n')
    print(json.dumps(dict(status=result['status'], error=failure, checks=len(checks))))
    return 1 if failure else 0


if __name__ == '__main__':
    raise SystemExit(main())
