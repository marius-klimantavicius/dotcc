#!/usr/bin/env python3
"""Native/JIT/NativeAOT process termination and finalizer-order comparison."""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
EDG = ROOT.parent
LIBRARY_HOST = '''// <auto-generated />
#nullable enable
using System;
using System.Collections.Generic;
using System.Threading;
using Runtime = Edg.Runtime.LibC;
using ProgramLifetime = Edg.Runtime.ObjectProgram;
internal static unsafe class Host
{
    [ThreadStatic] private static List<int>? events;
    private static int globalCalls;
    private static void Global(void* unused) { Interlocked.Increment(ref globalCalls); Console.Error.Write("unexpected host global drain"); }
    private static void Record(void* value)
    {
        int number = (int)(nint)value;
        (events ??= new()).Add(number);
        if (number == 99)
        {
            if (Runtime.__cxa_thread_atexit(&Record, (void*)3, null) != 0) throw new Exception("register during drain");
            Exception? failure = null;
            var child = new Thread(() => {
                try {
                    if (Runtime.__cxa_thread_atexit(&Record, (void*)8, null) != 0) throw new Exception("child registration");
                    ProgramLifetime.ReleaseThread();
                    if (string.Join(",", events!) != "8") throw new Exception("child finalizers");
                } catch (Exception error) { failure = error; }
            });
            child.Start();
            if (!child.Join(5000)) throw new Exception("runtime held registry lock across callback");
            if (failure != null) throw failure;
        }
    }
    private static void Worker()
    {
        foreach (int value in new[] { 1, 2, 99 })
            if (Runtime.__cxa_thread_atexit(&Record, (void*)value, null) != 0) throw new Exception("registration");
        ProgramLifetime.ReleaseThread();
        ProgramLifetime.ReleaseThread();
        if (string.Join(",", events!) != "99,3,2,1") throw new Exception("TLS order/isolation");
    }
    public static int Main()
    {
        ProgramLifetime.InitializeLibrary();
        if (Runtime.__cxa_atexit(&Global, null, null) != 0 || Runtime.__cxa_thread_atexit(&Record, (void*)5, null) != 0) return 1;
        Exception? failure = null;
        var workers = new Thread[4];
        for (int i = 0; i < workers.Length; ++i) {
            workers[i] = new Thread(() => { try { Worker(); } catch (Exception error) { failure = error; } });
            workers[i].Start();
        }
        foreach (var worker in workers) if (!worker.Join(10000)) return 2;
        if (failure != null) throw failure;
        if (events != null) return 3;
        ProgramLifetime.ReleaseThread();
        if (string.Join(",", events!) != "5" || globalCalls != 0) return 4;
        Console.WriteLine("library host retained; TLS callbacks isolated, reentrant and outside locks");
        return 0;
    }
}
'''


def sha(path):
    with Path(path).open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-dir', type=Path, required=True)
    parser.add_argument('--compiler', type=Path, required=True)
    parser.add_argument('--linker', type=Path, required=True)
    parser.add_argument('--packager', type=Path, default=ROOT / 'compile.py')
    parser.add_argument('--nativeaot', action='store_true')
    parser.add_argument('--rid', default='linux-x64')
    args = parser.parse_args()
    out = args.output_dir.resolve()
    out.mkdir(parents=True, exist_ok=False)
    checks, commands = [], []

    def check(name, condition):
        checks.append(dict(name=name, passed=bool(condition)))
        if not condition:
            raise AssertionError(name)

    def run(name, command, *, cwd=None, input=None, expected=0):
        command = list(map(str, command))
        p = subprocess.run(command, cwd=cwd or out, input=input, capture_output=True, timeout=300)
        stdout, stderr = out / (name + '.stdout'), out / (name + '.stderr')
        stdout.write_bytes(p.stdout)
        stderr.write_bytes(p.stderr)
        commands.append(dict(name=name, command=command, cwd=str(cwd or out), stdin=None if input is None else input.decode(), exitCode=p.returncode,
                             stdout=dict(path=str(stdout), sha256=sha(stdout)), stderr=dict(path=str(stderr), sha256=sha(stderr))))
        check(name + '-exit', p.returncode == expected)
        print(name + ': passed', flush=True)
        return p

    def modes(name, command):
        for mode in range(6):
            normal = 'T' + ('U' if mode == 5 else '') + 'X' + ('R' * 40 if mode == 4 else '') + 'BCGA'
            stderr = 'yzx' if mode == 2 else '' if mode == 3 else normal
            status = {1: 18, 2: 19, 3: 20}.get(mode, 17)
            directory = out / (name + '-' + str(mode))
            directory.mkdir()
            destination = directory / 'process.bin'
            result = run(name + '-' + str(mode), command, cwd=directory, input=str(mode).encode(), expected=status)
            check(name + '-' + str(mode) + '-order', result.stdout == b'' and result.stderr == stderr.encode())
            check(name + '-' + str(mode) + '-flush', destination.read_bytes() == (b'' if mode in (2, 3) else ('body:' + normal).encode()))

    failure = None
    fixture = out / 'runtime_process.c'
    shutil.copy2(ROOT / 'tests/runtime_process.c', fixture)
    try:
        run('native-build', ['cc', '-std=c11', '-DNATIVE_ORACLE', '-O2', fixture, '-o', out / 'native'])
        modes('native', [out / 'native'])
        obj = out / 'process.dotobj'
        run('compile', [sys.executable, '-B', args.packager.resolve(), fixture, '--output', obj,
            '--work-dir', out / 'work', '--compiler', args.compiler.resolve(), '--std', 'c11',
            '-I', EDG / 'backend/runtime/posix/include', '-I', EDG / 'backend/runtime/libc/include'])
        generated = out / 'generated'
        run('link', ['dotnet', args.linker.resolve(), 'link', '--out', generated, '--entry', 'main', '--allow-externs', obj])
        run('bind', [sys.executable, '-B', ROOT / 'runtime/bind.py', '--project', generated])
        receipt = json.loads((generated / 'runtime-bindings.json').read_text())
        check('complete-binding', receipt['status'] == 'bound' and not receipt['unresolved'])
        check('canonical-algorithms-hashed', {'dot_gen_lifecycle.h', 'dot_gen_process.h'} <= {Path(item['path']).name for item in receipt['bindingInputs']})
        check('canonical-inputs-unchanged', all(sha(item['path']) == item['sha256'] for item in receipt['bindingInputs'] + receipt['implementationInputs']))
        run('jit-build', ['dotnet', 'build', generated / 'Translated.csproj', '--nologo', '-v:q', '-p:TreatWarningsAsErrors=true'])
        modes('jit', ['dotnet', generated / 'bin/Debug/net10.0/Translated.dll'])
        if args.nativeaot:
            run('aot-build', ['dotnet', 'publish', generated / 'Translated.csproj', '-r', args.rid, '-p:PublishAot=true',
                '-p:IlcTreatWarningsAsErrors=true', '-o', out / 'aot', '--nologo', '-v:q'])
            modes('aot', [out / 'aot/Translated'])

        library = out / 'library'
        run('library-link', ['dotnet', args.linker.resolve(), 'link', '--out', library, '--allow-externs', obj])
        run('library-bind', [sys.executable, '-B', ROOT / 'runtime/bind.py', '--project', library])
        host = out / 'host'
        host.mkdir()
        (host / 'Host.cs').write_text(LIBRARY_HOST)
        project = host / 'Host.csproj'
        project.write_text('<Project Sdk="Microsoft.NET.Sdk"><PropertyGroup><OutputType>Exe</OutputType>'
            '<TargetFramework>net10.0</TargetFramework><AllowUnsafeBlocks>true</AllowUnsafeBlocks><Nullable>enable</Nullable>'
            '<IsAotCompatible>true</IsAotCompatible></PropertyGroup><ItemGroup>'
            '<ProjectReference Include="../library/Translated.csproj" /></ItemGroup></Project>\n')
        run('host-build', ['dotnet', 'build', project, '--nologo', '-v:q', '-p:TreatWarningsAsErrors=true'])
        host_result = run('host-jit', ['dotnet', host / 'bin/Debug/net10.0/Host.dll'])
        check('host-lifetime-and-concurrency', b'library host retained;' in host_result.stdout and host_result.stderr == b'')
        if args.nativeaot:
            run('host-aot-build', ['dotnet', 'publish', project, '-r', args.rid, '-p:PublishAot=true',
                '-p:IlcTreatWarningsAsErrors=true', '-o', out / 'host-aot', '--nologo', '-v:q'])
            result = run('host-aot', [out / 'host-aot/Host'])
            check('host-aot-parity', (result.stdout, result.stderr) == (host_result.stdout, host_result.stderr))

        plain = out / 'plain_return.c'
        plain.write_text('#include <stdio.h>\nint main(void) { FILE *f=fopen("main-return.bin", "wb"); '
                         'if (!f || setvbuf(f,0,_IOFBF,8192)) return 1; fputs("normal-main-return",f); return 0; }\n')
        plain_obj = out / 'plain_return.dotobj'
        run('plain-compile', [sys.executable, '-B', args.packager.resolve(), plain, '--output', plain_obj,
            '--work-dir', out / 'plain-work', '--compiler', args.compiler.resolve(), '--std', 'c11',
            '-I', EDG / 'backend/runtime/libc/include'])
        plain_project = out / 'plain-generated'
        run('plain-link', ['dotnet', args.linker.resolve(), 'link', '--out', plain_project, '--entry', 'main', '--allow-externs', plain_obj])
        run('plain-bind', [sys.executable, '-B', ROOT / 'runtime/bind.py', '--project', plain_project])
        plain_receipt = json.loads((plain_project / 'runtime-bindings.json').read_text())
        check('plain-no-explicit-exit-import', not {'exit', 'atexit', '__cxa_atexit'} & {row['name'] for row in plain_receipt['bound']})
        run('plain-build', ['dotnet', 'build', plain_project / 'Translated.csproj', '--nologo', '-v:q', '-p:TreatWarningsAsErrors=true'])
        plain_jit = out / 'plain-jit'
        plain_jit.mkdir()
        run('plain-jit', ['dotnet', plain_project / 'bin/Debug/net10.0/Translated.dll'], cwd=plain_jit)
        check('plain-normal-return-flushed', (plain_jit / 'main-return.bin').read_bytes() == b'normal-main-return')
        if args.nativeaot:
            run('plain-aot-build', ['dotnet', 'publish', plain_project / 'Translated.csproj', '-r', args.rid, '-p:PublishAot=true',
                '-p:IlcTreatWarningsAsErrors=true', '-o', out / 'plain-aot-build', '--nologo', '-v:q'])
            plain_aot = out / 'plain-aot'
            plain_aot.mkdir()
            run('plain-aot', [out / 'plain-aot-build/Translated'], cwd=plain_aot)
            check('plain-aot-return-flushed', (plain_aot / 'main-return.bin').read_bytes() == b'normal-main-return')

        # Fail closed rather than accepting a same-spelled import with the wrong
        # callback ABI. No generated provider may survive this failed binding.
        bad = out / 'bad.c'
        bad.write_text('int atexit(int (*callback)(int)); int f(int x) { return x; } int main(void) { return atexit(f); }\n')
        bad_obj = out / 'bad.dotobj'
        run('bad-compile', [sys.executable, '-B', args.packager.resolve(), bad, '--output', bad_obj,
            '--work-dir', out / 'bad-work', '--compiler', args.compiler.resolve(), '--std', 'c11'])
        bad_project = out / 'bad-generated'
        run('bad-link', ['dotnet', args.linker.resolve(), 'link', '--out', bad_project, '--entry', 'main', '--allow-externs', bad_obj])
        rejection = run('bad-bind', [sys.executable, '-B', ROOT / 'runtime/bind.py', '--project', bad_project], expected=1)
        check('bad-signature-rejected', b'Process callback ABI does not match' in rejection.stderr)
        check('bad-no-providers', not list(bad_project.glob('Runtime.Process*.cs')) and not list(bad_project.glob('Runtime.Bindings.*.cs')))
    except Exception as error:
        failure = str(error)
    result = dict(schema=1, status='failed' if failure else 'passed', error=failure, checks=checks, commands=commands,
                  fixture=dict(path=str(fixture), sha256=sha(fixture)), nativeAotVerified=args.nativeaot and not failure,
                  compiler=dict(path=str(args.compiler.resolve()), sha256=sha(args.compiler)),
                  linker=dict(path=str(args.linker.resolve()), sha256=sha(args.linker)),
                  scope='Static assembly atexit/quick exit/C++ destructor-registration ABI; no source RAII, DSO unloading or full DuckDB claim')
    (out / 'results.json').write_text(json.dumps(result, indent=2) + '\n')
    print(json.dumps(dict(status=result['status'], checks=len(checks), error=failure)))
    return 1 if failure else 0


if __name__ == '__main__':
    raise SystemExit(main())
