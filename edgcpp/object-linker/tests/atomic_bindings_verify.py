#!/usr/bin/env python3
"""Verify dotobj GNU atomic ABI adapters against native C and shared AtomicOps."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
NATIVE = '''#include <pthread.h>
#include <stdio.h>
int atomic_cases(void); void atomic_increment(void); unsigned long atomic_counter(void);
static void *worker(void *unused) { (void)unused; for(int i=0;i<10000;i++) atomic_increment(); return 0; }
int main(void) {
 int result=atomic_cases(); if(result) return result;
 pthread_t threads[4];
 for(int i=0;i<4;i++) if(pthread_create(&threads[i],0,worker,0)) return 200;
 for(int i=0;i<4;i++) pthread_join(threads[i],0);
 if(atomic_counter()!=40000) return 201;
 puts("atomic ABI and shared-counter concurrency OK"); return 0;
}
'''
HOST = '''// <auto-generated />
using System;
using System.Threading;
public static class AtomicRunner {
 public static int Main() {
  int result=global::Translated.Program.atomic_cases(); if(result!=0) return result;
  var threads=new Thread[4];
  for(int i=0;i<threads.Length;i++) threads[i]=new Thread(() => {
   for(int j=0;j<10000;j++) global::Translated.Program.atomic_increment();
  });
  foreach(var thread in threads) thread.Start();
  foreach(var thread in threads) thread.Join();
  if(global::Translated.Program.atomic_counter()!=40000) return 201;
  Console.WriteLine("atomic ABI and shared-counter concurrency OK"); return 0;
 }
}
'''


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-dir', type=Path, required=True)
    parser.add_argument('--compiler', type=Path, required=True)
    parser.add_argument('--linker', type=Path, required=True)
    parser.add_argument('--packager', type=Path, default=ROOT / 'compile.py')
    parser.add_argument('--without-int128', action='store_true', help='explicit reduced fixture while scalar128 graph support is pending; generic 16/600-byte atomics remain tested')
    parser.add_argument('--nativeaot', action='store_true')
    parser.add_argument('--rid', default='linux-x64')
    args = parser.parse_args()
    out = args.output_dir.resolve()
    out.mkdir(parents=True, exist_ok=False)
    commands, checks = [], []

    def check(name, value):
        checks.append(dict(name=name, passed=bool(value)))
        if not value:
            raise AssertionError(name)

    def run(name, command):
        command = list(map(str, command))
        process = subprocess.run(command, cwd=out, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, timeout=300)
        log = out / (name + '.log'); log.write_text(process.stdout)
        commands.append(dict(name=name, command=command, exitCode=process.returncode, path=str(log), sha256=sha(log)))
        check(name, process.returncode == 0)
        return process.stdout

    failure = None
    fixture = ROOT.parent / 'backend/tests/atomic_builtins.c'
    try:
        text = fixture.read_text()
        if args.without_int128:
            anchor = '  CHECK_WIDTH(unsigned __int128);'
            if text.count(anchor) != 1:
                raise ValueError('Canonical atomic fixture changed')
            text = text.replace(anchor, '  /* Explicit reduced profile: scalar128 graph support pending. */')
        source = out / 'input.c'; source.write_text(text)
        native = out / 'native.c'; native.write_text(NATIVE)
        run('native-build', ['cc', '-std=c11', '-O2', source, native, '-latomic', '-pthread', '-o', out / 'native'])
        expected = run('native-run', [out / 'native'])
        obj = out / 'input.dotobj'
        run('compile', [sys.executable, '-B', args.packager.resolve(), source, '--output', obj, '--work-dir', out / 'work',
                        '--compiler', args.compiler.resolve(), '--std', 'c11'])
        project = out / 'generated'
        run('link', ['dotnet', args.linker.resolve(), 'link', '--allow-externs', '--out', project, obj])
        run('bind', [sys.executable, '-B', ROOT / 'runtime/bind.py', '--project', project])
        bindings = json.loads((project / 'runtime-bindings.json').read_text())
        check('only-canonical-atomic-implementation', not bindings['unresolved'] and
              all(row['target'] == 'global::Edg.Runtime.AtomicOps' for row in bindings['bound']))
        (project / 'AtomicRunner.cs').write_text(HOST)
        csproj = project / 'Translated.csproj'
        csproj.write_text(csproj.read_text().replace('<OutputType>Library</OutputType>', '<OutputType>Exe</OutputType><StartupObject>AtomicRunner</StartupObject>'))
        run('managed-build', ['dotnet', 'build', csproj, '--nologo', '-v:q'])
        check('jit-native-parity', run('jit', ['dotnet', project / 'bin/Debug/net10.0/Translated.dll']) == expected)
        if args.nativeaot:
            aot = out / 'aot'
            run('publish', ['dotnet', 'publish', csproj, '-r', args.rid, '-p:PublishAot=true', '-o', aot, '--nologo', '-v:q'])
            check('aot-native-parity', run('aot', [aot / 'Translated']) == expected)
    except Exception as error:
        failure = str(error)
    result = dict(schema=1, status='failed' if failure else 'passed', error=failure, checks=checks, commands=commands,
                  scalar128Tested=not args.without_int128, nativeAotVerified=args.nativeaot and not failure,
                  compiler=dict(path=str(args.compiler.resolve()), sha256=sha(args.compiler)),
                  linker=dict(path=str(args.linker.resolve()), sha256=sha(args.linker)),
                  fixture=dict(path=str(fixture), sha256=sha(fixture)),
                  generatedFixture=dict(path=str(out / 'input.c'), sha256=sha(out / 'input.c')))
    (out / 'results.json').write_text(json.dumps(result, indent=2) + '\n')
    print(json.dumps(dict(status=result['status'], checks=len(checks), error=failure)))
    return 1 if failure else 0


if __name__ == '__main__':
    raise SystemExit(main())
