#!/usr/bin/env python3
"""Verify owned-object libc bindings against native C, JIT and NativeAOT.

The native oracle uses POSIX system headers. Runtime implementation code is
copied from the canonical shared BCL source, never from this test runner.
"""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
EDG = ROOT.parent
HOST = '''// <auto-generated />
using System;
using System.Threading;
public static unsafe class RuntimeCheckRunner {
    public static int Main() {
        int result = global::Translated.Program.main();
        if (result != 0) return result;
        int* mainError = global::Edg.Runtime.LibC.__errno_location();
        *mainError = 711;
        nint first = 0, second = 0;
        bool one = false, two = false;
        using var ready = new CountdownEvent(2);
        using var release = new ManualResetEventSlim(false);
        var a = new Thread(() => {
            int* cell = global::Edg.Runtime.LibC.__errno_location();
            first = (nint)cell; *cell = 811; ready.Signal(); release.Wait();
            one = *cell == 811 && cell == global::Edg.Runtime.LibC.__errno_location();
        });
        var b = new Thread(() => {
            int* cell = global::Edg.Runtime.LibC.__errno_location();
            second = (nint)cell; *cell = 911; ready.Signal(); release.Wait();
            two = *cell == 911 && cell == global::Edg.Runtime.LibC.__errno_location();
        });
        a.Start(); b.Start(); ready.Wait();
        GC.Collect(); GC.WaitForPendingFinalizers(); GC.Collect();
        release.Set(); a.Join(); b.Join();
        if (!one || !two || first == second || first == (nint)mainError || second == (nint)mainError || *mainError != 711)
            return 100;
        Console.WriteLine("canonical libc binding + TLS + GC OK");
        return 0;
    }
}
'''


def sha(path):
    with Path(path).open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-dir', type=Path, required=True)
    parser.add_argument('--compiler', type=Path, required=True)
    parser.add_argument('--linker', type=Path, required=True)
    parser.add_argument('--packager', type=Path, default=ROOT / 'compile.py')
    parser.add_argument('--nativeaot', action='store_true')
    parser.add_argument('--rid', default='linux-x64')
    args = parser.parse_args()
    out = args.output_dir.resolve()
    out.mkdir(parents=True, exist_ok=False)
    checks, logs, fixtures = [], [], []

    def check(name, condition):
        checks.append(dict(name=name, passed=bool(condition)))
        if not condition:
            raise AssertionError(name)

    def run(name, command, cwd=None, expected=0):
        command = [str(item) for item in command]
        process = subprocess.run(command, cwd=cwd or out, text=True, stdout=subprocess.PIPE,
                                 stderr=subprocess.STDOUT, timeout=300)
        log = out / (name + '.log')
        log.write_text(process.stdout)
        logs.append(dict(name=name, command=command, cwd=str(cwd or out), exitCode=process.returncode,
                         path=str(log), sha256=sha(log)))
        check(name, process.returncode == expected)
        return process.stdout

    def compile_source(name, source):
        obj = out / (name + '.dotobj')
        run(name + '-compile', [sys.executable, '-B', args.packager.resolve(), source,
            '--output', obj, '--work-dir', out / (name + '-work'), '--compiler', args.compiler.resolve(), '--std', 'c11',
            '-I', EDG / 'backend/runtime/posix/include', '-I', EDG / 'backend/runtime/libc/include'])
        return obj

    def link(name, obj):
        project = out / (name + '-generated')
        run(name + '-link', ['dotnet', args.linker.resolve(), 'link', '--out', project, '--entry', 'main', '--allow-externs', obj])
        return project

    failure = None
    try:
        for name in ('runtime_memory', 'runtime_stdio_posix', 'runtime_sessions', 'runtime_timezone', 'runtime_relative_posix'):
            source = out / (name + '.c')
            shutil.copy2(ROOT / 'tests' / source.name, source)
            fixtures.append(dict(path=str(source), sha256=sha(source)))
            run(name + '-native-build', ['cc', '-std=c11', '-D_POSIX_C_SOURCE=200809L', '-DNATIVE_ORACLE', '-O2', source, '-o', out / (name + '-native')])
            run(name + '-native-run', [out / (name + '-native')])
            obj = compile_source(name, source)
            project = link(name, obj)
            run(name + '-bind', [sys.executable, '-B', ROOT / 'runtime/bind.py', '--project', project])
            bindings = json.loads((project / 'runtime-bindings.json').read_text())
            check(name + '-complete-binding', bindings['status'] == 'bound' and not bindings['unresolved'])
            check(name + '-source-hashes', all(sha(item['path']) == item['sha256'] for item in bindings['implementationInputs']))
            if name == 'runtime_stdio_posix':
                check(name + '-three-shared-cells', {item['name'] for item in bindings['bound'] if item.get('storage')} == {'stdin', 'stdout', 'stderr'})
                check(name + '-va-source-reused', any(item['path'].endswith('Runtime.VaArg.cs') for item in bindings['reusedFiles']))
            project_file = project / 'Translated.csproj'
            if name in ('runtime_memory', 'runtime_stdio_posix'):
                host = HOST
                if name == 'runtime_stdio_posix':
                    host = host.replace('int* mainError =', 'if (global::Edg.Runtime.LibC.sysconf(84) != Environment.ProcessorCount) return 101;\n        int* mainError =')
                    check('online-processor-query-bound', any(row['name'] == 'sysconf' for row in bindings['bound']))
                (project / 'RuntimeCheckRunner.cs').write_text(host)
                project_file.write_text(project_file.read_text().replace('<StartupObject>__DotObjEntry</StartupObject>', '<StartupObject>RuntimeCheckRunner</StartupObject>'))
            elif name == 'runtime_sessions':
                names = {item['name'] for item in bindings['bound']}
                check('all-file-sessions-bound', {'__edg_with_file_lock', '__edg_with_file_read_lock', '__edg_with_file_wide_lock', '__edg_with_file_wide_read_lock'} <= names)
                check('locale-record-boundaries', {'newlocale', 'duplocale', 'uselocale', 'freelocale', 'localeconv'} <= names)
            elif name == 'runtime_timezone':
                names = {item['name'] for item in bindings['bound']}
                check('timezone-boundaries', {'__edg_timezone_enter', '__edg_timezone_exit', '__edg_timezone_map', '__edg_timezone_unmap'} <= names)
                check('timezone-hashed-assets', len(bindings['runtimeAssets']) == 4 and all(sha(project / key) == value['sha256'] for key, value in bindings['runtimeAssets'].items()))
                check('timezone-embedded-resource', 'Edg.Runtime.Tzdb.bin' in (project / 'Directory.Build.targets').read_text())
            elif name == 'runtime_relative_posix':
                names = {item['name'] for item in bindings['bound']}
                check('relative-filesystem-boundaries', {'openat', 'unlinkat', 'fdopendir', 'link', 'symlink', 'truncate', 'pathconf'} <= names)
            run(name + '-build', ['dotnet', 'build', project_file, '--nologo', '-v:q'])
            output = run(name + '-jit', ['dotnet', project / 'bin/Debug/net10.0/Translated.dll'])
            if name in ('runtime_memory', 'runtime_stdio_posix'):
                check(name + '-tls-and-gc', 'canonical libc binding + TLS + GC OK' in output)
            if args.nativeaot:
                aot = out / (name + '-aot')
                run(name + '-publish', ['dotnet', 'publish', project_file, '-r', args.rid, '-p:PublishAot=true', '-o', aot, '--nologo', '-v:q'])
                check(name + '-aot-parity', run(name + '-aot', [aot / 'Translated']) == output)

        # Same tag name with an incompatible layout must not be pointer-cast to
        # the portable POSIX ABI merely because the symbol is named fstat.
        bad = out / 'foreign_abi.c'
        bad.write_text('struct stat { int wrong; }; int fstat(int, struct stat*);\nint main(void) { struct stat s; return fstat(0, &s); }\n')
        obj = compile_source('foreign-abi', bad)
        project = link('foreign-abi', obj)
        run('foreign-abi-rejected', [sys.executable, '-B', ROOT / 'runtime/bind.py', '--project', project], expected=1)
        receipt = json.loads((project / 'runtime-bindings.json').read_text())
        check('foreign-abi-explicit-unresolved', receipt['status'] == 'unresolved' and receipt['unresolved'][0]['name'] == 'fstat')
        check('foreign-abi-no-provider-body', not list(project.glob('Runtime.Bindings.*.cs')))
        bad_nested = out / 'foreign_nested_abi.c'
        bad_nested.write_text('''struct timespec { unsigned long tv_sec; long tv_nsec; };
struct stat { unsigned long st_dev,st_ino; unsigned int st_mode; unsigned long st_nlink;
unsigned int st_uid,st_gid; long st_size; struct timespec st_atim,st_mtim,st_ctim;
unsigned long st_rdev; long st_blksize,st_blocks; };
int fstat(int,struct stat*); int main(void){struct stat value;return fstat(0,&value);}
''')
        obj = compile_source('foreign-nested-abi', bad_nested)
        project = link('foreign-nested-abi', obj)
        run('foreign-nested-abi-rejected', [sys.executable, '-B', ROOT / 'runtime/bind.py', '--project', project], expected=1)
        receipt = json.loads((project / 'runtime-bindings.json').read_text())
        check('foreign-nested-abi-explicit-unresolved', receipt['status'] == 'unresolved' and receipt['unresolved'][0]['name'] == 'fstat')
        check('foreign-nested-abi-no-provider-body', not list(project.glob('Runtime.Bindings.*.cs')))
    except Exception as error:
        failure = str(error)
    result = dict(schema=1, status='failed' if failure else 'passed', error=failure,
                  checks=checks, commands=logs, fixtures=fixtures, nativeAotVerified=args.nativeaot and not failure,
                  compiler=dict(path=str(args.compiler.resolve()), sha256=sha(args.compiler)),
                  linker=dict(path=str(args.linker.resolve()), sha256=sha(args.linker)),
                  binder=dict(path=str(ROOT / 'runtime/bind.py'), sha256=sha(ROOT / 'runtime/bind.py')),
                  scope='Shared libc provider boundary only; no full SQLite/DuckDB claim')
    (out / 'results.json').write_text(json.dumps(result, indent=2) + '\n')
    print(json.dumps(dict(status=result['status'], checks=len(checks), error=failure)))
    return 1 if failure else 0


if __name__ == '__main__':
    raise SystemExit(main())
