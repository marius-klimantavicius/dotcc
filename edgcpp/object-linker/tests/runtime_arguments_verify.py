#!/usr/bin/env python3
"""Verify owned UTF-8 argv storage and the translated C executable entry ABI."""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
EDG = ROOT.parent


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-dir', type=Path, required=True)
    parser.add_argument('--compiler', type=Path, required=True)
    parser.add_argument('--linker', type=Path, required=True)
    parser.add_argument('--packager', type=Path, default=ROOT / 'compile.py')
    parser.add_argument('--nativeaot', action='store_true')
    parser.add_argument('--rid', default='linux-x64')
    args = parser.parse_args()
    out = args.output_dir.resolve()
    out.mkdir(parents=True, exist_ok=False)
    checks, commands = [], []

    def check(name, condition):
        if not condition:
            raise AssertionError(name)
        checks.append(name)

    def run(name, command, expected=0):
        command = list(map(str, command))
        result = subprocess.run(command, cwd=out, capture_output=True, timeout=300)
        (out / (name + '.stdout')).write_bytes(result.stdout)
        (out / (name + '.stderr')).write_bytes(result.stderr)
        commands.append(dict(name=name, command=command, exitCode=result.returncode))
        check(name, result.returncode == expected)
        return result

    def compile_source(name, source):
        obj = out / (name + '.dotobj')
        run(name + '-compile', [sys.executable, '-B', args.packager.resolve(), source,
            '--output', obj, '--work-dir', out / (name + '-work'), '--compiler', args.compiler.resolve(),
            '--std', 'c11', '-I', EDG / 'backend/runtime/libc/include'])
        run(name + '-verify', ['dotnet', args.linker.resolve(), 'verify', obj])
        return obj

    failure = None
    try:
        helper = out / 'helper'
        helper.mkdir()
        shutil.copy2(EDG / 'backend/runtime/ProgramArguments.cs', helper / 'ProgramArguments.cs')
        shutil.copy2(ROOT / 'tests/runtime_arguments.cs', helper / 'Probe.cs')
        (helper / 'Arguments.csproj').write_text('<Project Sdk="Microsoft.NET.Sdk"><PropertyGroup>'
            '<OutputType>Exe</OutputType><TargetFramework>net10.0</TargetFramework>'
            '<AllowUnsafeBlocks>true</AllowUnsafeBlocks><Nullable>enable</Nullable>'
            '<IsAotCompatible>true</IsAotCompatible><TreatWarningsAsErrors>true</TreatWarningsAsErrors>'
            '</PropertyGroup></Project>\n')
        run('helper-build', ['dotnet', 'build', helper / 'Arguments.csproj', '--nologo', '-v:q'])
        probe = run('helper-jit', ['dotnet', helper / 'bin/Debug/net10.0/Arguments.dll'])
        check('helper-storage-checks', len(probe.stdout.splitlines()) == 11 and not probe.stderr)

        source = out / 'arguments.c'
        shutil.copy2(ROOT / 'tests/project_main_arguments.c', source)
        values = ['mutable', '', 'žąsis', '🦆']
        run('native-build', ['cc', '-std=c11', '-O2', source, '-o', out / 'native'])
        native = run('native', [out / 'native', *values], expected=17)
        check('native-finalizer', native.stdout == b'argv survived normal exit\n' and not native.stderr)
        obj = compile_source('arguments', source)
        source.rename(out / 'retained-arguments.c')
        generated = out / 'generated'
        run('link', ['dotnet', args.linker.resolve(), 'link', '--out', generated, '--entry', 'main', '--allow-externs', obj])
        check('canonical-helper', (generated / 'Runtime.ProgramArguments.cs').read_text() ==
              '// <auto-generated />\n' + (helper / 'ProgramArguments.cs').read_text())
        run('bind', [sys.executable, '-B', ROOT / 'runtime/bind.py', '--project', generated])
        run('build', ['dotnet', 'build', generated / 'Translated.csproj', '--nologo', '-v:q', '-p:TreatWarningsAsErrors=true'])
        jit = run('jit', ['dotnet', generated / 'bin/Debug/net10.0/Translated.dll', *values], expected=17)
        check('jit-native-parity', (jit.stdout, jit.stderr) == (native.stdout, native.stderr))
        if args.nativeaot:
            for label, project, binary, arguments, expected, oracle in [
                ('helper', helper / 'Arguments.csproj', 'Arguments', [], 0, probe),
                ('program', generated / 'Translated.csproj', 'Translated', values, 17, native),
            ]:
                destination = out / (label + '-aot')
                run(label + '-publish', ['dotnet', 'publish', project, '-r', args.rid, '-p:PublishAot=true',
                    '-p:IlcTreatWarningsAsErrors=true', '-o', destination, '--nologo', '-v:q'])
                result = run(label + '-aot', [destination / binary, *arguments], expected=expected)
                check(label + '-aot-parity', (result.stdout, result.stderr) == (oracle.stdout, oracle.stderr))

        bad = out / 'bad_entries.c'
        bad.write_text('int wrong_count(long count, char **arguments) { return 0; }\n'
                       'int wrong_pointer(int count, void **arguments) { return 0; }\n'
                       'void wrong_return(int count, char **arguments) {}\n'
                       'int variadic(int count, char **arguments, ...) { return 0; }\n')
        bad_obj = compile_source('bad', bad)
        for entry in ('wrong_count', 'wrong_pointer', 'wrong_return', 'variadic'):
            result = run('reject-' + entry, ['dotnet', args.linker.resolve(), 'link', '--out', out / entry,
                '--entry', entry, bad_obj], expected=1)
            check('diagnostic-' + entry, b'Executable entry must be' in result.stderr)
    except Exception as error:
        failure = str(error)
    result = dict(status='failed' if failure else 'passed', error=failure, checks=checks, commands=commands,
                  compiler=dict(path=str(args.compiler.resolve()), sha256=sha(args.compiler)),
                  linker=dict(path=str(args.linker.resolve()), sha256=sha(args.linker)),
                  nativeAotVerified=args.nativeaot and not failure,
                  scope='Standard argc/argv executable entry, writable UTF-8 storage through normal-exit callbacks; no envp extension')
    (out / 'results.json').write_text(json.dumps(result, indent=2) + '\n')
    print(json.dumps(dict(status=result['status'], checks=len(checks), error=failure)))
    return 1 if failure else 0


if __name__ == '__main__':
    raise SystemExit(main())
