#!/usr/bin/env python3
"""Run the separately packaged LLVM libc++ new_handler.cpp implementation."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

HOST = '''// <auto-generated />
using System;
using System.Threading;
using System.Threading.Tasks;
using Core = Edg.Libcxx.Core;
internal static unsafe class Host {
    private static long calls;
    private static void First() => Interlocked.Increment(ref calls);
    private static void Second() => Interlocked.Add(ref calls, 2);
    private static delegate* managed<void> FirstAddress => &First;
    private static delegate* managed<void> SecondAddress => &Second;
    public static int Main() {
        Edg.Runtime.ObjectProgram.InitializeLibrary();
        if (Core.get_new_handler() != null || Core.set_new_handler(&First) != null || (nint)Core.get_new_handler() != (nint)FirstAddress) return 1;
        Core.get_new_handler()();
        if ((nint)Core.set_new_handler(&Second) != (nint)FirstAddress || (nint)Core.get_new_handler() != (nint)SecondAddress) return 2;
        Core.get_new_handler()();
        if (calls != 3) return 3;
        Parallel.For(0, 8, worker => {
            for (int i = 0; i != 10000; ++i) {
                var previous = Core.set_new_handler((i & 1) == 0 ? &First : &Second);
                if ((nint)previous != (nint)FirstAddress && (nint)previous != (nint)SecondAddress) throw new Exception("torn exchange");
                var current = Core.get_new_handler();
                if ((nint)current != (nint)FirstAddress && (nint)current != (nint)SecondAddress) throw new Exception("torn load");
                current();
                if (i == 1000) GC.Collect();
            }
        });
        if (calls < 80003 || calls > 160003 || Core.set_new_handler(null) == null || Core.get_new_handler() != null) return 4;
        Console.WriteLine("LLVM libc++ new_handler: callback exchange/load, contention and GC passed");
        return 0;
    }
}
'''


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--project', type=Path, required=True)
    parser.add_argument('--output-dir', type=Path, required=True)
    parser.add_argument('--nativeaot', action='store_true')
    parser.add_argument('--rid', default='linux-x64')
    args = parser.parse_args()
    project = args.project.resolve()
    out = args.output_dir.resolve()
    out.mkdir(parents=True, exist_ok=False)
    checks, commands = [], []

    def check(name, condition):
        checks.append(dict(name=name, passed=bool(condition)))
        if not condition:
            raise AssertionError(name)

    def run(name, command):
        p = subprocess.run(list(map(str, command)), capture_output=True, cwd=out, timeout=300)
        log = out / (name + '.log')
        log.write_bytes(p.stdout + p.stderr)
        commands.append(dict(command=list(map(str, command)), exitCode=p.returncode, log=str(log), sha256=sha(log)))
        check(name, p.returncode == 0)
        print(name + ': passed', flush=True)
        return p.stdout

    failure = None
    try:
        sources = json.loads((project / 'source-map.json').read_text())['objects']
        check('actual-independent-llvm-unit', len(sources) == 1 and sources[0]['unitId'] == 'libcxx:src/new_handler.cpp')
        receipt = json.loads((project / 'runtime-bindings.json').read_text())
        check('only-atomic-runtime-imports', receipt['status'] == 'bound' and not receipt['unresolved'] and
              {row['name'] for row in receipt['bound']} == {'__atomic_load_8', '__atomic_exchange_8'})
        check('canonical-runtime-source-hashes', all(sha(row['path']) == row['sha256'] for row in receipt['implementationInputs']))
        (out / 'Host.cs').write_text(HOST)
        (out / 'Host.csproj').write_text('<Project Sdk="Microsoft.NET.Sdk"><PropertyGroup><OutputType>Exe</OutputType>'
            '<TargetFramework>net10.0</TargetFramework><AllowUnsafeBlocks>true</AllowUnsafeBlocks><IsAotCompatible>true</IsAotCompatible>'
            '</PropertyGroup><ItemGroup><ProjectReference Include="' + str(project / 'Translated.csproj') + '" /></ItemGroup></Project>\n')
        run('jit-build', ['dotnet', 'build', out / 'Host.csproj', '--nologo', '-v:q', '-p:TreatWarningsAsErrors=true'])
        expected = run('jit', ['dotnet', out / 'bin/Debug/net10.0/Host.dll'])
        if args.nativeaot:
            run('aot-build', ['dotnet', 'publish', out / 'Host.csproj', '-r', args.rid, '-p:PublishAot=true',
                '-p:IlcTreatWarningsAsErrors=true', '-o', out / 'aot', '--nologo', '-v:q'])
            check('aot-parity', run('aot', [out / 'aot/Host']) == expected)
    except Exception as error:
        failure = str(error)
    result = dict(schema=1, status='failed' if failure else 'passed', error=failure, checks=checks, commands=commands,
        project=str(project), linkReportSha256=sha(project / 'link-report.json'), sourceMapSha256=sha(project / 'source-map.json'),
        runtimeReceiptSha256=sha(project / 'runtime-bindings.json'), nativeAotVerified=args.nativeaot and not failure,
        scope='Unmodified LLVM new_handler.cpp alone; no complete libc++ or DuckDB claim')
    (out / 'results.json').write_text(json.dumps(result, indent=2) + '\n')
    print(json.dumps(dict(status=result['status'], checks=len(checks), error=failure)))
    return 1 if failure else 0


if __name__ == '__main__':
    raise SystemExit(main())
