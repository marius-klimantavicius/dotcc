#!/usr/bin/env python3
"""Verify the real SQLite public mutex ABI and shared APPDEF provider wiring.

This verifies the platform boundary, not execution of the whole SQLite engine.
"""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
HOST = '''// <auto-generated />
using System;
using System.Threading;
using Edg.Runtime.Sqlite;
public static unsafe class MutexCheckRunner {
    public static int Main() {
        int result = global::Edg.SQLite.SqliteCore.main();
        if (result != 0) return result;
        var methods = HostMutex.GetMutextMethods();
        var mutex = methods->xMutexAlloc(1);
        if (mutex == null || HostMutex.DynamicMutexCount != 1) return 100;
        methods->xMutexEnter(mutex);
        using var checkedContention = new ManualResetEventSlim(false);
        using var release = new ManualResetEventSlim(false);
        bool busy = false, acquired = false;
        var worker = new Thread(() => {
            var callbacks = HostMutex.GetMutextMethods();
            busy = callbacks == methods && callbacks->xMutexTry(mutex) == 5 && callbacks->xMutexNotheld(mutex) == 1;
            checkedContention.Set(); release.Wait();
            callbacks->xMutexEnter(mutex);
            acquired = callbacks->xMutexHeld(mutex) == 1;
            callbacks->xMutexLeave(mutex);
        });
        worker.Start(); checkedContention.Wait();
        GC.Collect(); GC.WaitForPendingFinalizers(); GC.Collect();
        if (methods != HostMutex.GetMutextMethods()) return 101;
        methods->xMutexLeave(mutex); release.Set(); worker.Join();
        methods->xMutexFree(mutex);
        if (!busy || !acquired || HostMutex.DynamicMutexCount != 0) return 102;
        Console.WriteLine("SQLite APPDEF typed callbacks, contention and GC OK");
        return 0;
    }
}
'''


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-dir', type=Path, required=True)
    parser.add_argument('--compiler', type=Path, required=True)
    parser.add_argument('--linker', type=Path, required=True)
    parser.add_argument('--sqlite-header', type=Path, required=True)
    parser.add_argument('--nativeaot', action='store_true')
    parser.add_argument('--rid', default='linux-x64')
    args = parser.parse_args()
    out = args.output_dir.resolve()
    out.mkdir(parents=True, exist_ok=False)
    commands, checks = [], []

    def check(name, value):
        checks.append(dict(name=name, passed=bool(value)))
        if not value:
            raise AssertionError(name)

    def run(name, command, expected=0):
        command = list(map(str, command))
        process = subprocess.run(command, cwd=out, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, timeout=300)
        log = out / (name + '.log')
        log.write_text(process.stdout)
        commands.append(dict(name=name, command=command, exitCode=process.returncode, path=str(log), sha256=sha(log)))
        check(name, process.returncode == expected)
        return process.stdout

    failure = None
    try:
        inputs = out / 'inputs'
        inputs.mkdir()
        shutil.copy2(args.sqlite_header, inputs / 'sqlite3.h')
        shutil.copy2(ROOT / 'tests/sqlite_mutex_boundary.c', inputs / 'main.c')
        obj = out / 'input.dotobj'
        run('compile', [sys.executable, '-B', ROOT / 'compile.py', inputs / 'main.c', '--output', obj, '--work-dir', out / 'work',
                        '--compiler', args.compiler.resolve(), '--std', 'c11', '-I', inputs, '-I', ROOT.parent / 'backend/runtime/libc/include'])
        inputs.rename(out / 'retained-detached-inputs')
        project = out / 'generated'
        link_args = ['dotnet', args.linker.resolve(), 'link', '--namespace', 'Edg.SQLite', '--class', 'SqliteCore', '--entry', 'main', '--allow-externs', obj]
        run('source-free-link', [*link_args, '--out', project])
        run('sqlite-provider', [sys.executable, '-B', ROOT / 'runtime/sqlite.py', '--project', project])
        receipt = project / 'runtime-sqlite.json'
        run('complete-bindings', [sys.executable, '-B', ROOT / 'runtime/bind.py', '--project', project, '--provider-receipt', receipt])
        bindings = json.loads((project / 'runtime-bindings.json').read_text())
        check('three-provided-no-unresolved', len(bindings['bound']) == 3 and not bindings['unresolved'])
        provider = json.loads(receipt.read_text())
        canonical = next(row for row in provider['inputs'] if row['path'].endswith('/sqlite/src/HostVfs.Mutex.cs'))
        check('single-canonical-mutex-source', sha(canonical['path']) == canonical['sha256'])
        (project / 'MutexCheckRunner.cs').write_text(HOST)
        csproj = project / 'Translated.csproj'
        csproj.write_text(csproj.read_text().replace('<StartupObject>__DotObjEntry</StartupObject>', '<StartupObject>MutexCheckRunner</StartupObject>'))
        run('managed-build', ['dotnet', 'build', csproj, '--nologo', '-v:q'])
        output = run('jit', ['dotnet', project / 'bin/Debug/net10.0/Translated.dll'])
        check('thread-contention-and-gc', 'SQLite APPDEF typed callbacks, contention and GC OK' in output)
        if args.nativeaot:
            aot = out / 'aot'
            run('publish', ['dotnet', 'publish', csproj, '-r', args.rid, '-p:PublishAot=true', '-o', aot, '--nologo', '-v:q'])
            check('aot-parity', run('aot', [aot / 'Translated']) == output)
        for mode in ('changed-source', 'wrong-signature', 'duplicate-provider'):
            candidate = out / mode
            run(mode + '-link', [*link_args, '--out', candidate])
            run(mode + '-adapter', [sys.executable, '-B', ROOT / 'runtime/sqlite.py', '--project', candidate])
            candidate_receipt = candidate / 'runtime-sqlite.json'
            extra = []
            if mode == 'changed-source':
                path = candidate / 'Runtime.Sqlite.HostMutex.cs'
                path.write_text(path.read_text() + '\n// changed after receipt\n')
            elif mode == 'wrong-signature':
                value = json.loads(candidate_receipt.read_text())
                value['methods'][0]['Signature'] = 'routine(void;;0;unwind)'
                candidate_receipt.write_text(json.dumps(value))
            else:
                extra = ['--provider-receipt', candidate_receipt]
            run(mode + '-rejected', [sys.executable, '-B', ROOT / 'runtime/bind.py', '--project', candidate,
                                    '--provider-receipt', candidate_receipt, *extra], expected=1)
    except Exception as error:
        failure = str(error)
    result = dict(schema=1, status='failed' if failure else 'passed', error=failure, checks=checks, commands=commands,
                  scope='SQLite public header/APPDEF platform boundary; full SQLite engine is not executed by this test',
                  nativeAotVerified=args.nativeaot and not failure,
                  compiler=dict(path=str(args.compiler.resolve()), sha256=sha(args.compiler)),
                  linker=dict(path=str(args.linker.resolve()), sha256=sha(args.linker)),
                  sqliteHeader=dict(path=str(args.sqlite_header.resolve()), sha256=sha(args.sqlite_header)))
    (out / 'results.json').write_text(json.dumps(result, indent=2) + '\n')
    print(json.dumps(dict(status=result['status'], checks=len(checks), error=failure)))
    return 1 if failure else 0


if __name__ == '__main__':
    raise SystemExit(main())
