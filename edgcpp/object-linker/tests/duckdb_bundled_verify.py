#!/usr/bin/env python3
"""Compare DuckDB's original miniz/xxHash units with their object-backed C#."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
from xml.sax.saxutils import escape

NATIVE = r'''
#include "miniz.hpp"
#include "zstd/common/xxhash.hpp"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
namespace M = duckdb_miniz;
namespace X = duckdb_zstd;
int main() {
    const int lengths[] = {0,1,7,31,256,1024,4096,65536};
    const int levels[] = {0,1,9};
    for (int pattern=0;pattern<3;++pattern) for (int n:lengths) {
        unsigned char *raw=(unsigned char*)malloc(n+2), *input=raw+1;
        unsigned state=0x12345678;
        for (int i=0;i<n;++i) { state=1664525U*state+1013904223U; input[i]=(unsigned char)(pattern==0?state>>24:pattern==1?i%7:'a'); }
        unsigned h32=X::XXH32(input,n,0x12345678U);
        unsigned long long h64=X::XXH64(input,n,0x0123456789abcdefULL);
        auto s32=X::XXH32_createState(); auto s64=X::XXH64_createState();
        if (!s32 || !s64 || X::XXH32_reset(s32,0x12345678U) || X::XXH64_reset(s64,0x0123456789abcdefULL)) return 1;
        for (int i=0;i<n;) {int count=n-i<23?n-i:23; if(X::XXH32_update(s32,input+i,count)||X::XXH64_update(s64,input+i,count))return 2;i+=count;}
        if (X::XXH32_digest(s32)!=h32 || X::XXH64_digest(s64)!=h64) return 3;
        X::XXH32_canonical_t c32; X::XXH64_canonical_t c64;
        X::XXH32_canonicalFromHash(&c32,h32); X::XXH64_canonicalFromHash(&c64,h64);
        if(X::XXH32_hashFromCanonical(&c32)!=h32||X::XXH64_hashFromCanonical(&c64)!=h64)return 4;
        X::XXH32_freeState(s32); X::XXH64_freeState(s64);
        for (int level:levels) {
            M::mz_ulong size=M::mz_compressBound(n), restored=n;
            auto packed=(unsigned char*)malloc(size);auto output=(unsigned char*)malloc(n+1);
            if(M::mz_compress2(packed,&size,input,n,level) || M::mz_uncompress(output,&restored,packed,size) || restored!=(unsigned)n || memcmp(input,output,n))return 5;
            printf("%d %d %d %lu %lu %lu %lu %u %llu\n",pattern,n,level,size,M::mz_crc32(0,packed,size),M::mz_crc32(0,input,n),M::mz_adler32(1,input,n),h32,h64);
            char name[80];snprintf(name,sizeof(name),"packed-%d-%d-%d.bin",pattern,n,level);
            FILE *file=fopen(name,"wb");if(!file||fwrite(packed,1,size,file)!=size||fclose(file))return 7;
            if(size>3) {M::mz_ulong too_short=n; if(M::mz_uncompress(output,&too_short,packed,1)==0)return 6;}
            free(packed);free(output);
        }
        free(raw);
    }
    return 0;
}
'''

