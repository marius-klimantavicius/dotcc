def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-root', type=Path, required=True)
    parser.add_argument('--project', type=Path, required=True)
    parser.add_argument('--output-dir', type=Path, required=True)
    parser.add_argument('--nativeaot', action='store_true')
    parser.add_argument('--rid', default='linux-x64')
    args = parser.parse_args()
    out = args.output_dir.resolve(); out.mkdir(parents=True, exist_ok=False)
    root = args.source_root.resolve()
    checks, commands, inputs = [], [], []

    def check(name, condition):
        checks.append(dict(name=name, passed=bool(condition)))
        if not condition: raise AssertionError(name)

    def run(name, command, cwd=None):
        p = subprocess.run(list(map(str, command)), cwd=cwd or out, capture_output=True, timeout=300)
        stdout, stderr = out / (name+'.stdout'), out / (name+'.stderr')
        stdout.write_bytes(p.stdout); stderr.write_bytes(p.stderr)
        commands.append(dict(command=list(map(str, command)), cwd=str(cwd or out), exitCode=p.returncode,
            stdout=dict(path=str(stdout), sha256=sha(stdout)), stderr=dict(path=str(stderr), sha256=sha(stderr))))
        check(name, p.returncode==0)
        print(name+': passed', flush=True)
        return p.stdout

    failure = None
    try:
        for label, relative in [('miniz','third_party/miniz/miniz.cpp'),('xxhash','third_party/zstd/common/xxhash.cpp')]:
            project=args.project.resolve()
            objects=json.loads((project/'source-map.json').read_text())['objects']
            check(label+'-actual-source-unit',len(objects)==2 and any(Path(obj['primarySource']).resolve()==root/relative for obj in objects))
            receipt=json.loads((project/'runtime-bindings.json').read_text())
            check(label+'-runtime-bound',receipt['status']=='bound' and not receipt['unresolved'])
            inputs.append(dict(source=str(root/relative),sourceSha256=sha(root/relative),project=str(project),
                               sourceMapSha256=sha(project/'source-map.json'),runtimeReceiptSha256=sha(project/'runtime-bindings.json')))
        native=out/'native.cpp';native.write_text(NATIVE)
        run('native-build',['c++','-std=c++17','-O2','-I',root/'third_party/miniz','-I',root/'third_party/zstd/include',
            native,root/'third_party/miniz/miniz.cpp',root/'third_party/zstd/common/xxhash.cpp','-o',out/'native'])
        native_cases=out/'native-cases';native_cases.mkdir()
        expected=run('native',[out/'native'],cwd=native_cases)
        check('native-72-cases',len(expected.splitlines())==72)
        compressed={p.name:p.read_bytes() for p in native_cases.glob('packed-*.bin')}
        check('native-72-compressed-streams',len(compressed)==72)
        (out/'Host.cs').write_text(HOST)
        project=out/'Host.csproj'
        project.write_text('<Project Sdk="Microsoft.NET.Sdk"><PropertyGroup><OutputType>Exe</OutputType><TargetFramework>net10.0</TargetFramework>'
            '<AllowUnsafeBlocks>true</AllowUnsafeBlocks><IsAotCompatible>true</IsAotCompatible></PropertyGroup><ItemGroup>'
            '<ProjectReference Include="'+escape(str(args.project.resolve()/'Translated.csproj'),{'"':'&quot;'})+'" />'
            '</ItemGroup></Project>\n')
        run('jit-build',['dotnet','build',project,'--nologo','-v:q'])
        jit_cases=out/'jit-cases';jit_cases.mkdir()
        check('jit-native-parity',run('jit',['dotnet',out/'bin/Debug/net10.0/Host.dll'],cwd=jit_cases)==expected)
        check('jit-byte-for-byte-compression',compressed=={p.name:p.read_bytes() for p in jit_cases.glob('packed-*.bin')})
        if args.nativeaot:
            run('aot-build',['dotnet','publish',project,'-r',args.rid,'-p:PublishAot=true','-p:IlcTreatWarningsAsErrors=true','-o',out/'aot','--nologo','-v:q'])
            aot_cases=out/'aot-cases';aot_cases.mkdir()
            check('aot-native-parity',run('aot',[out/'aot/Host'],cwd=aot_cases)==expected)
            check('aot-byte-for-byte-compression',compressed=={p.name:p.read_bytes() for p in aot_cases.glob('packed-*.bin')})
    except Exception as error: failure=str(error)
    result=dict(schema=1,status='failed' if failure else 'passed',error=failure,checks=checks,commands=commands,inputs=inputs,
        nativeAotVerified=args.nativeaot and not failure,scope='DuckDB bundled original miniz and xxHash units; not the whole DuckDB engine')
    (out/'results.json').write_text(json.dumps(result,indent=2)+'\n')
    print(json.dumps(dict(status=result['status'],checks=len(checks),error=failure)))
    return 1 if failure else 0


if __name__=='__main__': raise SystemExit(main())
