#!/usr/bin/env python3
"""Native/managed cross-unit acceptance and direct SQL browsing evidence."""
import argparse
from pathlib import Path
import shutil
import sqlite3
import subprocess
import sys

RELATIONAL = Path(__file__).resolve().parents[1]
EDG = RELATIONAL.parents[1]


def run(command, log, expected=0):
    with log.open('w') as output:
        result = subprocess.run([str(x) for x in command], stdout=output, stderr=subprocess.STDOUT)
    if result.returncode != expected:
        raise RuntimeError(f'{command[0]} exited {result.returncode}, expected {expected}: {log}')


def inspect(path):
    with sqlite3.connect(path.as_uri() + '?mode=ro', uri=True) as db:
        assert db.execute('PRAGMA integrity_check').fetchone() == ('ok',)
        assert not list(db.execute('PRAGMA foreign_key_check'))
        tables = list(db.execute("SELECT name,sql FROM sqlite_master WHERE type='table' ORDER BY name"))
        assert not any('edg_graph' in name for name, _ in tables)
        assert not any('BLOB' in sql.upper() or 'JSON' in sql.upper() for _, sql in tables)
        assert db.execute('SELECT COUNT(*) FROM functions').fetchone()[0] > 0
        assert db.execute('SELECT COUNT(*) FROM template_instances').fetchone()[0] > 0
        assert db.execute("SELECT COUNT(*) FROM types WHERE name='Point'").fetchone()[0] > 0
        assert db.execute("SELECT COUNT(*) FROM fields WHERE name IN ('x','y')").fetchone()[0] >= 2
        assert db.execute("SELECT COUNT(*) FROM nodes WHERE value_category='lvalue'").fetchone()[0] > 0
        assert db.execute('SELECT COUNT(*) FROM nodes WHERE type_id IS NOT NULL').fetchone()[0] > 0
        rows = [f'{name}: {db.execute("SELECT COUNT(*) FROM " + name).fetchone()[0]} rows' for name, _ in tables]
        return '\n'.join([f'{path.name}: {path.stat().st_size} bytes', *rows])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', type=Path, required=True)
    parser.add_argument('--compiler', type=Path, default=EDG / 'build/bin/cpfe-dot')
    parser.add_argument('--linker', type=Path, required=True)
    parser.add_argument('--nativeaot', action='store_true')
    args = parser.parse_args()
    work = args.out.resolve()
    work.mkdir(parents=True, exist_ok=False)
    source = work / 'source'
    source.mkdir()
    for name in ('program.h', 'provider.cpp', 'main.cpp'):
        shutil.copy2(RELATIONAL / 'tests' / name, source / name)
    run(['g++', '-std=c++20', source/'provider.cpp', source/'main.cpp', '-o', work/'native'], work/'native-build.log')
    run([work/'native'], work/'native-run.log')
    objects = []
    for name in ('provider', 'main'):
        obj = work / f'{name}.dotobj'
        run([sys.executable, RELATIONAL/'compile.py', source/f'{name}.cpp', '--output', obj,
             '--work-dir', work/f'{name}-work', '--compiler', args.compiler.resolve()], work/f'{name}-compile.log')
        objects.append(obj)
    (work/'database-summary.txt').write_text('\n\n'.join(inspect(p) for p in objects) + '\n')
    # The reader/generator must consume SQL facts without opening original code.
    hidden = work / 'original-source'
    source.rename(hidden)
    generated = work / 'generated'
    run(['dotnet', args.linker.resolve(), 'link', '--out', generated,
         '--namespace', 'Review.Semantic', '--class', 'Core', '--entry', 'main', *objects], work/'link.log')
    run(['dotnet', 'run', '--project', generated/'Translated.csproj', '-c', 'Release'], work/'managed-run.log')
    code = '\n'.join(p.read_text() for p in generated.glob('*.cs'))
    assert '// <auto-generated />' in code
    assert 'accumulate' in code and 'combine' in code and 'Point' in code
    assert 'for (' in code and 'while (' in code and 'continue;' in code
    if args.nativeaot:
        run(['dotnet', 'publish', generated/'Translated.csproj', '-c', 'Release', '-p:PublishAot=true',
             '-o', work/'nativeaot'], work/'nativeaot-build.log')
        apps = [p for p in (work/'nativeaot').iterdir() if p.is_file() and p.suffix == '' and p.stat().st_mode & 0o111]
        if len(apps) != 1:
            raise RuntimeError('Expected one NativeAOT application')
        run(apps, work/'nativeaot-run.log')
    for case in ('unsupported_global_init', 'unsupported_virtual_call', 'unsupported_reversed_subscript'):
        unsupported = work / (case + '.dotobj')
        with (work/(case+'.log')).open('w') as log:
            result = subprocess.run([sys.executable, str(RELATIONAL/'compile.py'),
                str(RELATIONAL/'tests'/(case+'.cpp')), '--output', str(unsupported),
                '--work-dir', str(work/(case+'-work')), '--compiler', str(args.compiler.resolve())],
                stdout=log, stderr=subprocess.STDOUT)
        assert result.returncode != 0 and not unsupported.exists()
        assert 'semantic exporter missing' in (work/(case+'-work/stderr.txt')).read_text()
    print('PASS: direct relational export, SQL integrity, cross-unit linking, source-hidden C# execution' +
          (', NativeAOT' if args.nativeaot else ''))
    print(work)


if __name__ == '__main__':
    main()
