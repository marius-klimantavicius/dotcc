using System.Text;

namespace DotObj.Relational;

internal sealed partial class Emitter
{
    private readonly LinkedProgram program;
    private readonly string namespaceName, className;
    private readonly Names names = new();
    private readonly Dictionary<SymbolRef,string> symbolNames = [];
    private readonly Dictionary<(Unit,long),string> typeNames = [];
    private readonly Dictionary<(Unit,long),string> fieldNames = [];
    private readonly Dictionary<string,(Unit Unit,ProgramType Type,string Name)> records = new(StringComparer.Ordinal);
    private TextWriter output=TextWriter.Null;

    public Emitter(LinkedProgram program,string namespaceName,string className,bool requiredProviders=false)
    {
        this.program=program;this.namespaceName=namespaceName;this.className=className;
        this.requiredProviders=requiredProviders;
        names.Reserve(className);names.Reserve("Main");names.Reserve("_");
        foreach(var symbol in program.Functions)
        {
            string source=symbol.Symbol.Name;
            if(symbol.Unit.FunctionDetails.TryGetValue(symbol.Id,out var details))
                source=details.Kind switch {"constructor"=>"__ctor_"+source,"destructor"=>"__dtor_"+source,_=>source};
            symbolNames.Add(symbol,names.Allocate(source,"symbol_"+symbol.Id));
        }
        PrepareVirtualCatalog();
        PrepareRecordedRecordDefinitions();
        FindExecutableTypes();
        // Callable source names take priority over generated storage getters.
        foreach(var global in program.Globals)
        {
            bool property=global.Unit.IsArray(global.Symbol.Type) || HasPinnedRecordStorage(global.Unit,global.Id) || HasPinnedScalarStorage(global.Unit,global.Id);
            symbolNames.Add(global,property?names.AllocateProperty(global.Symbol.Name,"symbol_"+global.Id):
                names.Allocate(global.Symbol.Name,"symbol_"+global.Id));
        }
        PrepareProviderStorageNames();
        foreach(var unit in program.Units)
            foreach(var type in unit.Types.Values.Where(type=>type.Kind=="record" && unit.VaListRole(type.Id) is null && executableTypes.Contains((unit,type.Id))))
            {
                string key=type.Linkage=="external"?"external:"+type.LinkName:unit.Path+":"+type.Id;
                if(!records.TryGetValue(key,out var record))
                {
                    record=(unit,type,names.Allocate(type.Name,"record_"+type.Id));records.Add(key,record);
                }
                else if(record.Type.Incomplete && !type.Incomplete) records[key]=(unit,type,record.Name);
                typeNames.Add((unit,type.Id),record.Name);
                var members=new Names();
                members.Reserve(record.Name);
                foreach(var field in unit.Fields.Values.Where(field=>field.Owner==type.Id).OrderBy(field=>field.Ordinal))
                {
                    bool property=field.BitWidth is not null || IsZeroExtentArray(unit,field.Type);
                    string member=property?members.AllocateProperty(field.Name,"field_"+field.Ordinal):members.Allocate(field.Name,"field_"+field.Ordinal);
                    if(field.BitWidth is not null)members.Reserve("set_"+member.TrimStart('@'));
                    fieldNames.Add((unit,field.Id),member);
                }
            }
        PrepareEnums();
        PrepareArrays();
        PrepareLiteralStorage();
        if(needsNullptrNormalization)nullptrValueName=names.Allocate("__nullptr_value","nullptr_value");
    }

    public void Write(string directory,string? entry)
    {
        Directory.CreateDirectory(directory);
        string temporary=Path.Combine(directory,".Translated.cs."+Guid.NewGuid().ToString("N")+".tmp");
        try
        {
            using(var writer=new StreamWriter(temporary,false,new UTF8Encoding(false)))
            {
                output=writer;
                WriteProgram(entry);
            }
            File.Move(temporary,Path.Combine(directory,"Translated.cs"),overwrite:true);
            File.WriteAllText(Path.Combine(directory,"Translated.csproj"),"<Project Sdk=\"Microsoft.NET.Sdk\"><PropertyGroup><TargetFramework>net10.0</TargetFramework><AllowUnsafeBlocks>true</AllowUnsafeBlocks><Nullable>enable</Nullable><OutputType>"+(entry is null?"Library":"Exe")+"</OutputType></PropertyGroup></Project>\n",new UTF8Encoding(false));
            if(NeedsExceptionRuntime)WriteExceptionRuntime(directory);
            WriteFloatingRuntime(directory);
            WriteVirtualRuntime(directory);
            WriteVarargsRuntime(directory);
            if(requiredProviders)WriteImportsManifest(directory);
        }
        catch
        {
            if(File.Exists(temporary))Console.Error.WriteLine("Partial generated source retained: "+temporary);
            throw;
        }
        finally {output=TextWriter.Null;}
    }

    private void WriteProgram(string? entry)
    {
        Line(0,"// <auto-generated />");
        Line(0,"namespace "+namespaceName+";");
        Line(0,"public static unsafe partial class "+className);Line(0,"{");
        WriteEnums();
        WriteArrayTypes();
        foreach(var record in records.Values) Record(record.Unit,record.Type,record.Name);
        WriteInheritanceHelpers();
        WriteVirtualTables();
        WriteNullptrHelper();
        PrepareExceptionDescriptors();
        WriteLiteralStorage();
        foreach(var unit in program.Units){WriteClassConversionHelpers(unit,null);WriteVirtualCallHelpers(unit,null);WriteCompoundHelpers(unit,null);WriteAllocationHelpers(unit,null);WriteDeallocationHelpers(unit,null);}
        foreach(var global in program.Globals)
        {
            if(global.Unit.IsArray(global.Symbol.Type)){WriteGlobalArray(global);continue;}
            if(HasPinnedRecordStorage(global.Unit,global.Id))
            {
                WriteGlobalRecord(global,global.Unit.Initializers.TryGetValue(global.Id,out long recordInitializer)?recordInitializer:null);continue;
            }
            if(HasPinnedScalarStorage(global.Unit,global.Id)){WriteGlobalScalar(global);continue;}
            string value=global.Unit.Initializers.TryGetValue(global.Id,out var initializer)
                ? new FunctionWriter(this,global.Unit,null).Expression(global.Unit.Nodes[initializer]):"default";
            Line(1,"public static "+Type(global.Unit,global.Symbol.Type)+" "+SymbolName(global.Unit,global.Id)+" = "+value+";");
        }
        WriteGlobalInitializers();
        foreach(var function in program.Functions)
        {
            using var body=program.LoadFunction(function);
            try
            {
                WriteClassConversionHelpers(function.Unit,function.Id);
                WriteVirtualCallHelpers(function.Unit,function.Id);
                WriteCompoundHelpers(function.Unit,function.Id);
                WriteAllocationHelpers(function.Unit,function.Id);
                WriteDeallocationHelpers(function.Unit,function.Id);
                new FunctionWriter(this,function.Unit,function).Write();
            }
            finally {ReleaseClassConversionNames(function.Unit,function.Id);ReleaseVirtualCallNames(function.Unit,function.Id);ReleaseCompoundNames(function.Unit,function.Id);ReleaseAllocationNames(function.Unit,function.Id);ReleaseDeallocationNames(function.Unit,function.Id);}
        }
        WriteRequiredProviders();
        if(entry is not null)
        {
            var matches=program.Functions.Where(function=>function.Symbol.Name==entry || function.Symbol.LinkName==entry).ToArray();
            if(matches.Length!=1)throw new InvalidDataException("Entry must identify exactly one selected function: "+entry);
            var function=matches[0];
            if(function.Unit.Parameters.GetValueOrDefault(function.Id,[]).Count!=0)
                throw new InvalidDataException("Entry arguments are not yet supported by the relational generator");
            string result=Type(function.Unit,function.Unit.Original(function.Symbol.Type).Result!.Value);
            if(result is not("void" or "int"))throw new InvalidDataException("Entry must return void or int");
            Line(1,"public static "+result+" Main() => "+symbolNames[function]+"();");
        }
        Line(0,"}");
    }

    private void Record(Unit unit,ProgramType record,string name)
    {
        if(record.Dependent)throw new InvalidDataException("Dependent record reached executable C# emission: "+record.Name);
        if(record.Incomplete)
        {
            Line(1,"// Opaque declaration; only pointers to this type can be emitted.");
            Line(1,"public struct "+name+" { }");return;
        }
        if(record.Size is null or <=0)throw new InvalidDataException("Complete record has no positive recorded layout size: "+record.Name);
        bool completeStorage=unit.BaseSubobjects.Values.Any(subobject=>subobject.Owner==record.Id && subobject.Virtual);
        string? alignment=completeStorage?CompleteRecordAlignment(record):null;
        Line(1,"[global::System.Runtime.InteropServices.StructLayout(global::System.Runtime.InteropServices.LayoutKind.Explicit, Size = "+record.Size+
            (completeStorage?", Pack = "+record.Alignment:"")+")]");
        Line(1,"public struct "+name);Line(1,"{");
        if(completeStorage)WriteCompleteRecordStorage(unit,record,name,alignment!);
        var bitfields=WriteBitfieldBacking(unit,record);
        foreach(var field in unit.Fields.Values.Where(field=>field.Owner==record.Id).OrderBy(field=>field.Ordinal))
        {
            if(IsZeroExtentArray(unit,field.Type))
            {
                WriteZeroExtentArrayField(unit,record,name,field);continue;
            }
            if(field.BitWidth is not null)
            {
                if(bitfields.TryGetValue(field.Id,out var bitfield))WriteBitfieldProperty(unit,bitfield);
                continue;
            }
            Line(2,"[global::System.Runtime.InteropServices.FieldOffset("+field.Offset+")]");
            if(OpaqueCallablePointer(unit,field.Type))
                Line(2,"// Source callback "+(unit.Types[field.Type].Name.Length==0?field.Name:unit.Types[field.Type].Name)+": address storage; this declaration has no finalized result ABI.");
            Line(2,"public "+Type(unit,field.Type)+" "+fieldNames[(unit,field.Id)]+";");
        }
        Line(1,"}");
    }

    private string SymbolName(Unit unit,long id)
    {
        var selected=program.Resolve(unit,id);
        if(symbolNames.TryGetValue(selected,out string? name))return name;
        if(RequireProvider(selected) is ProviderImport import)return import.Name;
        throw new InvalidDataException("No definition for "+selected.Symbol.LinkName+" ("+selected.Symbol.Name+")");
    }

    private string Type(Unit unit,long id,bool allowIncomplete=false)
    {
        if(unit.VaListRole(id) is not null)return VaListStorageType();
        var type=unit.Original(id);
        if(type.Dependent)throw new InvalidDataException("Dependent type reached executable C# emission: "+type.Name);
        if(type.Kind=="record" && type.Incomplete && !allowIncomplete && !RecordedRecordDefinition(type,out _))
            throw new InvalidDataException("Incomplete record used by value: type "+type.Id+" "+type.LinkName+" in "+unit.Path);
        return type.Kind switch
        {
            "void"=>"void","bool"=>"bool","i8"=>"sbyte","u8"=>"byte","i16"=>"short","u16"=>"ushort",
            "i32"=>"int","u32"=>"uint","i64"=>"long","u64"=>"ulong","f32"=>"float","f64"=>"double",
            "i128"=>"global::System.Int128","u128"=>"global::System.UInt128",
            "f80" or "f128"=>ExtendedFloatingType(unit,type),
            "nullptr"=>"void*",
            "pointer" or "lvalue-reference" or "rvalue-reference"=>Pointer(unit,type.Pointee!.Value),
            "record"=>typeNames[(unit,type.Id)],
            "enum"=>typeNames[(unit,type.Id)],
            "array"=>IsIncompleteArray(unit,type.Id)?
                throw new InvalidDataException("Incomplete array value/stride storage requires recorded complete layout: type "+type.Id+" in "+unit.Path):IsZeroExtentArray(unit,type.Id)?
                throw new InvalidDataException("Zero-extent array value or stride storage emission is not yet implemented: type "+type.Id):arrayNames[(unit,type.Id)],
            _=>throw new InvalidDataException("Unsupported relational C# type "+type.Id+": "+type.Kind+" "+type.Name)
        };
    }
    private string Pointer(Unit unit,long target)
    {
        var type=unit.Original(target);
        if(IsIncompleteArray(unit,type.Id))
            return Pointer(unit,type.Element??throw new InvalidDataException("Incomplete array element type missing: "+type.Id));
        if(type.Kind!="function")return Type(unit,target,allowIncomplete:true)+"*";
        if(UnfinalizedCallableResult(unit,type))return "void*";
        var parameters=unit.TypeParameters.GetValueOrDefault(type.Id,[]).Select(id=>Type(unit,id));
        if(type.Variadic){needsVarargsRuntime=true;parameters=parameters.Append(VaSpanType);}
        if(type.ObjectType is long receiver && type.ParametersIncludeReceiver!=true)parameters=parameters.Prepend(Pointer(unit,receiver));
        if(type.ReturnStorage=="caller-provided")parameters=parameters.Prepend(Pointer(unit,type.Result!.Value));
        return "delegate* managed<"+string.Join(", ",parameters.Append(type.ReturnStorage=="caller-provided"?"void":Type(unit,type.Result!.Value)))+">";
    }
    private void Line(int indent,string text="")
    {
        output.Write(new string(' ',indent*4));output.WriteLine(text);
    }

    private sealed partial class FunctionWriter
    {
        private readonly Emitter emitter;
        private readonly Unit unit;
        private readonly SymbolRef? function;
        private readonly Dictionary<long,string> locals=[];
        private readonly Names allocator=new();
        private readonly string? returnDestination;
        public FunctionWriter(Emitter emitter,Unit unit,SymbolRef? function)
        {
            this.emitter=emitter;this.unit=unit;this.function=function;
            allocator.Reserve("_");
            foreach(string value in emitter.symbolNames.Values)allocator.Reserve(value);
            foreach(string value in emitter.typeNames.Values)allocator.Reserve(value);
            foreach(string value in emitter.virtualTableNames.Values)allocator.Reserve(value);
            foreach(string value in emitter.virtualCallNames.Values)allocator.Reserve(value);
            foreach(string value in emitter.compoundHelpers.Values)allocator.Reserve(value);
            foreach(string value in emitter.arrayNames.Values)allocator.Reserve(value);
            foreach(string value in emitter.literalNames.Values)allocator.Reserve(value);
            foreach(string value in emitter.allocationNames.Values)allocator.Reserve(value);
            foreach(string value in emitter.deallocationNames.Values)allocator.Reserve(value);
            if(emitter.localArrayStorageName is string arrayStorage)allocator.Reserve(arrayStorage);
            if(emitter.nullptrValueName is string helper)allocator.Reserve(helper);
            if(function is SymbolRef selected)
            {
                foreach(var local in unit.Symbols.Values.Where(value=>value.Parent==selected.Id && value.Kind!="static-local"))
                    locals.Add(local.Id,allocator.Allocate(local.Name,"local_"+local.Id));
                foreach(var local in unit.Symbols.Values.Where(value=>value.Parent==selected.Id && value.Kind=="local" && unit.IsArray(value.Type)))
                    localArrayOwners.Add(local.Id,allocator.Allocate("__"+Name(local.Id)+"_storage","local_array_storage"));
                if(unit.Original(selected.Symbol.Type).ReturnStorage=="caller-provided")
                    returnDestination=allocator.Allocate("__result","return_value");
                if(unit.Original(selected.Symbol.Type).Variadic)
                    varargs=new(allocator.Allocate("__varargs","varargs"),allocator.Allocate("__varargs_capacity","varargs_capacity"),
                        allocator.Allocate("__varargs_workspace","varargs_workspace"),allocator.Allocate("__varargs_pack","varargs_pack"),
                        allocator.Allocate("__varargs_cursor","varargs_cursor"));
            }
        }
        private void Line(int indent,string text="")=>emitter.Line(indent,text);
        private string Name(long id)=>locals.TryGetValue(id,out var name)?name:emitter.SymbolName(unit,id);
        private string Type(long id)=>emitter.Type(unit,id);
        private string NodeType(Node node)=>Type(node.ExecutionType??node.Type??throw unit.Missing(node,"expression type missing"));
        private Node Child(Node node,string role)=>unit.Child(node,role);
        public void Write()
        {
            var selected=function!.Value;
            var signature=unit.Original(selected.Symbol.Type);
            string parameters=string.Join(", ",unit.Parameters.GetValueOrDefault(selected.Id,[]).Select(id=>Type(unit.Symbols[id].Type)+" "+Name(id)));
            if(returnDestination is not null)parameters=Type(signature.Result!.Value)+"* "+returnDestination+(parameters.Length==0?"":", "+parameters);
            if(varargs is not null)parameters+=(parameters.Length==0?"":", ")+"params "+VaSpanType+" "+varargs.Span;
            Line(1,"public static "+(returnDestination is null?Type(signature.Result!.Value):"void")+" "+emitter.symbolNames[selected]+"("+parameters+")");
            WriteFunctionBody(unit.Nodes[unit.Functions[selected.Id]],1);
        }
        private string Truth(Node node,string? rendered=null)
        {
            string value=rendered??Expression(node);
            var type=unit.Original(node.Type??node.ExecutionType??throw unit.Missing(node,"condition type missing"));
            return type.Kind=="bool"?value:"("+value+(type.Kind is "pointer" or "lvalue-reference" or "rvalue-reference" or "nullptr"?" != null)":" != 0)");
        }
        public string Expression(Node node)
        {
            return NormalizeValue(node,RawExpression(node));
        }
        private string RawExpression(Node node)
        {
            if(expandedValues.TryGetValue(node.Id,out var expanded))return expanded;
            if(IncompleteArrayAddress(node) is string incomplete)return incomplete;
            if(node.Type is long zeroArray && IsZeroExtentArray(unit,zeroArray))
                throw unit.Missing(node,"zero-extent array value emission requires a recorded field address view");
            if(node.Lifetime is long ownedLifetime && unit.Destructions.GetValueOrDefault(ownedLifetime,[]).Any(id=>!allocationOwnedCleanups.Contains(id)))
                throw unit.Missing(node,"expression lifetime cleanup needs statement expansion");
            if(node.OriginalLvalueType is long original && unit.IsVolatile(original) ||
                node.Type is long type && unit.IsVolatile(type))
                throw unit.Missing(node,"volatile access emission is not yet implemented");
            switch(node.Kind)
            {
                case "constant":return Constant(node);
                case "address-constant":return LiteralAddress(node);
                case "type-info-address":return TypeInfoAddress(node);
                case "string-literal":return "(*"+ArrayAddress(node)+")";
                case "new":return AllocationExpression(node);
                case "delete":
                    return node.Operator is "destroy" or "virtual-destroy"?DeallocationExpression(node):Expression(Child(node,"execution"));
                case "variable":
                    long variable=node.Symbol??throw unit.Missing(node,"selected symbol missing");
                    return unit.IsArray(unit.Symbols[variable].Type) || emitter.HasPinnedRecordStorage(unit,variable) || emitter.HasPinnedScalarStorage(unit,variable) || emitter.HasProviderAddress(unit,variable)?"(*"+Name(variable)+")":Name(variable);
                case "function":case "routine-address":return FunctionAddress(node);
                case "initialize":return unit.Children(node,"value").FirstOrDefault() is Node value?Expression(value):"default";
                case "operation":return Operation(node);
                case "lifetime-scope":
                    if(node.Lifetime is long lifetime && unit.Destructions.GetValueOrDefault(lifetime,[]).Any(id=>!allocationOwnedCleanups.Contains(id)))
                        throw unit.Missing(node,"expression lifetime cleanup needs statement expansion");
                    return Expression(Child(node,"operand"));
                default:throw unit.Missing(node,"C# expression emission is not implemented");
            }
        }
        private string Constant(Node node)
        {
            if(node.FloatingValue is long floating)return FloatingConstant(node,floating);
            if(EnumConstant(node) is string enumeration)return enumeration;
            string value=node.Constant??throw unit.Missing(node,"constant payload missing");
            string type=NodeType(node);
            if(type is "global::System.Int128" or "global::System.UInt128")return WideIntegerConstant(node,type,value);
            if(type=="bool")return value is "0" or "false"?"false":"true";
            if(type.EndsWith('*') || type.StartsWith("delegate*",StringComparison.Ordinal))
                return value=="0"?"(("+type+")0)":throw unit.Missing(node,"nonzero pointer constant needs a relocation");
            return type switch
            {
                "uint"=>value+"U","long"=>value+"L","ulong"=>value+"UL","float"=>value+"F",
                "sbyte" or "byte" or "short" or "ushort"=>"(("+type+")"+value+")",_=>value
            };
        }
        private string Operation(Node node)
        {
            var operands=unit.Children(node,"operand").ToArray();
            Node N(int index)=>index<operands.Length?operands[index]:throw unit.Missing(node,"operand "+index+" missing");
            string E(int index)=>Expression(N(index));
            string Binary(string op)=>"("+E(0)+" "+op+" "+E(1)+")";
            string Unary(string op)=>"("+op+E(0)+")";
            string BooleanResult(string value)=>NodeType(node)=="bool"?value:"(("+NodeType(node)+")("+value+" ? 1 : 0))";
            string op=node.Operator??throw unit.Missing(node,"operation discriminator missing");
            RequireBitfieldOperationSupport(node,operands);
            if(UsesCompoundHelper(node))return CompoundExpression(node,N(0),N(1));
            if(node.EvaluationOrder=="right-to-left" && operands.Length>1 && !expandedValues.ContainsKey(operands[1].Id) && !IsDirectLocalAssignment(node))
                throw unit.Missing(node,"right-to-left operation needs statement expansion");
            switch(op)
            {
                case "is-constant-evaluated":return Constant(node);
                case "dot-vacuous-destructor-call":case "points-to-vacuous-destructor-call":return VacuousDestructorExpression(node);
                case "add":case "pointer-add":return Binary("+");case "subtract":case "pointer-subtract":return Binary("-");case "multiply":return Binary("*");
                case "pointer-difference":return PointerDifference(node,N(0),N(1));
                case "divide":return Binary("/");case "remainder":return Binary("%");
                case "shift-left":return "("+E(0)+" << (int)"+E(1)+")";case "shift-right":return "("+E(0)+" >> (int)"+E(1)+")";
                case "and":case "bit-and":return Binary("&");case "or":case "bit-or":return Binary("|");case "xor":case "bit-xor":return Binary("^");
                case "assign":return Binary("=");case "add-assign":return Binary("+=");case "subtract-assign":return Binary("-=");
                case "pointer-add-assign":case "pointer-subtract-assign":
                    throw unit.Missing(node,"pointer compound assignment requires recorded operation type/helper support");
                case "multiply-assign":return Binary("*=");case "divide-assign":return Binary("/=");case "remainder-assign":return Binary("%=");
                case "eq":return BooleanResult(Binary("=="));case "ne":return BooleanResult(Binary("!="));case "lt":return BooleanResult(Binary("<"));case "le":return BooleanResult(Binary("<="));case "gt":return BooleanResult(Binary(">"));case "ge":return BooleanResult(Binary(">="));
                case "logical-and":return BooleanResult("("+Truth(N(0))+" && "+Truth(N(1))+")");
                case "logical-or":return BooleanResult("("+Truth(N(0))+" || "+Truth(N(1))+")");
                case "not":return BooleanResult("(!"+Truth(N(0))+")");case "negate":return Unary("-");case "plus":return Unary("+");case "complement":return Unary("~");
                case "pre-increment":return Unary("++");case "pre-decrement":return Unary("--");
                case "post-increment":return "("+E(0)+"++)";case "post-decrement":return "("+E(0)+"--)";
                case "address-of":case "reference-to":
                    if(N(0).Kind=="function")return FunctionAddress(N(0));
                    return AddressExpression(N(0));
                case "indirect":case "ref-indirect":return "(*"+E(0)+")";
                case "cast":case "ref-cast":case "bool-cast":case "lvalue-cast":
                    if(NodeType(node)=="bool")return Truth(N(0));
                    if(NodeType(N(0))=="bool" && NodeType(node)!="bool")return "(("+NodeType(node)+")("+E(0)+" ? 1 : 0))";
                    if(WidePointerConversion(node,N(0)) is string converted)return converted;
                    return "unchecked(("+NodeType(node)+")"+E(0)+")";
                case "lvalue-adjust":case "class-rvalue-adjust":return E(0);
                case "base-class-cast":case "derived-class-cast":return ClassConversionExpression(node,N(0));
                case "array-to-pointer":
                    if(unit.VaListRole(N(0).ExecutionType??N(0).Type!.Value) is not null)return "(&"+E(0)+")";
                    return ArrayDecay(N(0));
                case "va-start":case "va-start-single":case "va-arg":case "va-copy":case "va-end":return VarargsOperation(node);
                case "conditional":return "("+Truth(N(0))+" ? "+E(1)+" : "+E(2)+")";
                case "subscript":return "("+E(0)+")["+E(1)+"]";
                case "dot-field":case "points-to-field":
                    long field=node.Field??N(1).Field??throw unit.Missing(node,"selected field missing");
                    return "("+E(0)+")"+(op=="dot-field"?".":"->")+emitter.fieldNames[(unit,field)];
                case "call":case "dot-member-call":case "points-to-member-call":
                    if(unit.VirtualCalls.TryGetValue(node.Id,out var dispatch))return VirtualCallExpression(node,dispatch);
                    if(CallSignature(N(0)).ReturnStorage=="caller-provided")
                        throw unit.Missing(node,"caller-provided class result requires an explicit initialization destination");
                    string target=N(0).Kind=="function"?Name(N(0).Symbol!.Value):E(0);
                    var args=CallArguments(node,operands,Expression);
                    return target+"("+string.Join(", ",args)+")";
                default:throw unit.Missing(node,"C# operation emission is not implemented");
            }
        }
        private string Declaration(Node node)
        {
            if(node.Kind=="static-assertion")return "";
            if(node.Kind=="static-declaration"){StaticDeclarationSymbol(node);return "";}
            long id=node.Symbol??throw unit.Missing(node,"declaration symbol missing");
            return Type(unit.Symbols[id].Type)+" "+Name(id)+" = "+Expression(node);
        }
        // C# statement expressions cannot be enclosed in the outer parentheses
        // used for expression precedence. Keep the emitted operation itself.
        private string StatementExpression(Node node,string? rendered=null)
        {
            if(VoidDiscardOperand(node) is Node discarded)return StatementExpression(discarded);
            string value=rendered??Expression(node);
            if(node.Kind=="delete")return value;
            if(UsesCompoundHelper(node))return "_ = "+value;
            if(node.Operator is "va-start" or "va-start-single" or "va-copy" or "va-end")return value;
            if(node.Kind=="operation" && node.Operator is "assign" or "add-assign" or "subtract-assign" or "pointer-add-assign" or "pointer-subtract-assign" or "multiply-assign" or "divide-assign" or "remainder-assign" or "pre-increment" or "post-increment" or "pre-decrement" or "post-decrement")
                return value[1..^1];
            if(node.Kind=="operation" && node.Operator is "call" or "dot-member-call" or "points-to-member-call")return value;
            return "_ = "+value;
        }
        private string Header(Node node)
        {
            if(node.Kind=="block")
            {
                var statements=unit.Children(node,"statement").Where(statement=>statement.Kind!="empty").ToArray();
                if(statements.Length==0)return "";
                if(statements.Length!=1)throw unit.Missing(node,"for initializer with multiple statements not yet supported");
                return Header(statements[0]);
            }
            if(node.Kind=="decl")
            {
                var declarations=unit.Children(node,"declaration").ToArray();
                if(declarations.Length!=1)throw unit.Missing(node,"for initializer with multiple declarations not yet supported");
                return Declaration(declarations[0]);
            }
            if(node.Kind is "initialize" or "static-declaration" or "static-assertion")return Declaration(node);
            if(node.Kind=="expr-stmt")return StatementExpression(Child(node,"value"));
            if(node.Kind=="empty")return "";
            return StatementExpression(node);
        }
        private void Body(Node node,int indent)
        {
            if(node.Kind=="block")Statement(node,indent);
            else {Line(indent,"{");Statement(node,indent+1);Line(indent,"}");}
        }
        private void Statement(Node node,int indent)
        {
            switch(node.Kind)
            {
                case "empty":Line(indent,";");break;
                case "block":
                    WriteBlock(node,indent);break;
                case "return":
                    WriteReturn(node,indent);break;
                case "expr-stmt":
                    if(Child(node,"value").Kind is "throw" or "rethrow")WriteThrow(Child(node,"value"),indent);
                    else
                    {
                        Node expression=Child(node,"value");
                        if(!WriteVoidDiscardStatement(expression,indent) && !WriteBitfieldAssignmentStatement(expression,indent) && !WriteSourceCompoundStatement(expression,indent))
                            Line(indent,StatementExpression(expression,ExpandedExpression(expression,indent))+";");
                    }
                    break;
                case "decl":foreach(var declaration in unit.Children(node,"declaration"))WriteDeclaration(declaration,indent);break;
                case "initialize":WriteDeclaration(node,indent);break;
                case "static-declaration":WriteStaticDeclaration(node,indent);break;
                case "static-assertion":WriteDeclaration(node,indent);break;
                case "if":WriteIf(node,indent);break;
                case "constexpr-if":WriteConstexprIf(node,indent);break;
                case "while":WriteWhile(node,indent);break;
                case "do-while":
                    Line(indent,"do");WriteLoopBody(node,indent);
                    Line(indent,"while ("+Truth(Child(node,"condition"))+");");break;
                case "for":WriteFor(node,indent);break;
                case "range-for":WriteRangeFor(node,indent);break;
                case "switch":WriteSwitch(node,indent);break;
                case "case":case "default":WriteCase(node,indent);break;
                case "break":WriteBreak(node,indent);break;
                case "continue":WriteContinue(node,indent);break;
                case "goto":WriteNamedGoto(node,indent);break;
                case "label":WriteNamedLabel(node,indent);break;
                case "try":WriteTry(node,indent);break;
                case "throw":case "rethrow":WriteThrow(node,indent);break;
                default:throw unit.Missing(node,"C# statement emission is not implemented");
            }
        }
    }
