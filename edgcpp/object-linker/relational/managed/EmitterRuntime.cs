using System.Text;

namespace DotObj.Relational;

internal sealed partial class Emitter
{
    private const string ExceptionRuntime = "global::Edg.Runtime.CppExceptions";

    private static string StringLiteral(string text)
    {
        var result = new StringBuilder("\"");
        foreach(char value in text)
            if(value=='"' || value=='\\')result.Append('\\').Append(value);
            else if(value < ' ' || char.IsSurrogate(value))result.Append("\\u").Append(((int)value).ToString("x4"));
            else result.Append(value);
        return result.Append('"').ToString();
    }

    private static void WriteExceptionRuntime(string directory)
    {
        CopyRuntimeSource(directory,"CppExceptions.cs");
        File.WriteAllText(Path.Combine(directory,"Runtime.Exceptions.generated.cs"),ExceptionContract,new UTF8Encoding(false));
    }

    private static void CopyRuntimeSource(string directory,string name)
    {
        using var stream=typeof(Emitter).Assembly.GetManifestResourceStream("DotObj.Relational."+name)
            ??throw new InvalidOperationException("Missing shared runtime source "+name);
        using var reader=new StreamReader(stream);
        File.WriteAllText(Path.Combine(directory,"Runtime."+name),"// <auto-generated />\n"+reader.ReadToEnd(),new UTF8Encoding(false));
    }

    // The provider is the existing shared runtime, copied unchanged. This is
    // its source contract and the program boundary hook, not a second provider.
    private const string ExceptionContract = """
// <auto-generated />
#nullable enable
namespace Edg.Runtime;
public readonly record struct CppExceptionBase(string IdentityKey, nuint ByteOffset, bool IsPublic, bool IsAmbiguous);
public sealed record CppExceptionType(string IdentityKey, string LeafIdentityKey, string LeafKind,
    global::System.ReadOnlyMemory<int> PointerQualifiers, nuint PayloadSize, nuint PayloadAlignment,
    bool RequiresDestruction, global::System.ReadOnlyMemory<CppExceptionBase> Bases);
public sealed record CppCatchType(string IdentityKey, string LeafIdentityKey, string LeafKind,
    global::System.ReadOnlyMemory<int> PointerQualifiers);
public abstract unsafe class CppException : global::System.Exception
{
    public abstract void* ObjectAddress { get; }
}
public abstract class CppCatch
{
    public abstract bool Active { get; }
}
public abstract unsafe class CppTypedCatch : CppCatch
{
    public abstract void* ObjectAddress { get; }
}
public static unsafe partial class CppExceptions
{
    public static partial CppException Allocate(CppExceptionType type, delegate* managed<void*, void> completeDestructor);
    public static partial void EnsureStarted(CppException payload);
    public static partial void MarkComplete(CppException payload);
