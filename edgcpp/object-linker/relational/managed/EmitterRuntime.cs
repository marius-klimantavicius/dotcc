public static partial class ObjectProgram
{
    static partial void ClassifyTransfer(global::System.Exception error, ref bool result);
    public static bool IsRuntimeTransfer(global::System.Exception error)
    {
        bool result=false;
        ClassifyTransfer(error,ref result);
        return result;
    }
    public static bool BeginUnwind(global::System.Exception error, ref bool unwinding)
    {
        unwinding=true;
        return false;
    }
    public static bool TerminateCleanupFailure(global::System.Exception error)
